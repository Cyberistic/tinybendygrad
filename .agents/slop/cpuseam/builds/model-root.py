# THE ROOT CAUSE, IN ONE PLACE.
#
# MEASURED (probe-outer-walk.py, IN THE DAEMON):
#   THE OUTER WALK (THE BLOCK LIST): 33,360 ELEMENTS A TURN (27.0 A CALL)
#   THE INNER WALK (THE BLOCK):      19,187 ELEMENTS A TURN (15.5 A CALL)
#   THE TOTAL:                       52,547 ELEMENTS A TURN
#
# AND THE ROOT IS THE REVERSE INDEX ITSELF: `rtp(r, i)` READS ROW `i` AS `d = n-1-i`,
# AND BOTH WALKS ARE LONG BECAUSE THE INDEX IS REVERSED.
#
# AND THE INNER WALK IS THE BLOCK's OFFSET (`d & 15`), AND THE LARGE `d` MAKES THE LARGE
# OFFSET -- SO THE INNER WALK IS ALSO LONG FOR THE HOT ACCESSES.
#
# =>=>=> AND THE FIX IS THE SAME AT BOTH LEVELS: STORE THE ROWS IN FORWARD ORDER AND INDEX
# THEM DIRECTLY -- THEN `rtp` BECOMES A PLAIN FORWARD ACCESS.
#
# =>=>=> AND THE COST OF THAT IS THE `Rows` TYPE CHANGE: THE BLOCKS ARE BUILT BY PREPENDING
# THE NEWEST (THE O(1) FORM), SO THE CURRENT BLOCK IS AT THE HEAD, AND THE REVERSE ACCESS
# FINDS THE OLDEST BLOCKS AT THE TAIL -- WHICH IS WHY THE WALK IS 42-49.
#
# =>=>=> AND A REVERSAL OF THE BLOCK LIST IS O(n), AND THE BLOCK LIST IS 49 LONG AND IT GROWS
# 16 ROWS AT A TIME, SO A REVERSAL PER NEW BLOCK IS ~49 ELEMENT COPIES PER 16 ROWS --
# =>=>=> AND THE ALU's SOURCE WALK IS 602 CALLS A TURN, SO THE REVERSAL WOULD BE ~1,900
# ELEMENT COPIES A TURN, AGAINST THE ~4,000 WALKS IT REPLACES -- =>=>=> AND SO IT MIGHT PAY,
# =>=>=> AND IT MUST BE MEASURED.

NB = 49
print("THE WALK, EACH WAY, FOR THE HOT ACCESSES:")
for bi, calls in [(46, 1200), (45, 150), (44, 690), (43, 840), (42, 300), (38, 240)]:
    print(f"  bi {bi:3d} ({calls:5d} calls): NOW {bi:3d} STEPS, FORWARD {NB - 1 - bi:3d} STEPS")
print()
