#!/usr/bin/env python3
"""portc.py -- render a LIVE uop list with the PORT's OWN `cstyle.bend`.

    import portc; c_source = portc.render(uops)

WHY THIS EXISTS: `BEND_C=1`'s compiled lane handed `[ClangRenderer]` to `Compiled`, i.e. it rendered C
with TINYGRAD's code. The port has its own renderer, `tinybendygrad/renderer/cstyle.bend`, and
`.agents/slop/cpuseam/compare.py` proves it equivalent (5 kernels, max_abs=0, fail=0) -- but nothing in
the device path called it. This is that call.

HOW IT WORKS, AND WHY IT LOOKS LIKE THIS: `cstyle.bend`'s `C.render` takes a `KU` LIST -- a Bend value,
not text -- so the uop list must be turned into Bend LITERALS and compiled. That is what `gen_kus.py`
does for the fixtures (`uops/<name>.rows` -> `gen/<name>.bend`), and the port's own seam runs it as
`bend -o .js` then `bun`. This module does the same for an arbitrary live list:

    uops -> rows (dump_kernel.dump_uops, the SAME formatter the fixture uses)
         -> gen/live_<hash>.bend   (a `kus()` literal, via gen_kus.one)
         -> live_<hash>-driver.bend (prints C.render(C.dev_clang(), True{}, K.kus()))
         -> bend -o <js> -> bun <js> -> the C on stdout

THE TRANSCRIPTION IS NOT RE-TYPED: `dump_uops` and `gen_kus.one` are IMPORTED, not copied, so a live
render and a fixture render cannot disagree about the format.

THE CACHE IS CONTENT-KEYED (sha256 of the rows AND of every source the renderer compiles against), so the
same kernel renders once and a renderer edit re-keys. Repeating an unchanged uop list costs nothing.

**THE BUILD IS THE COST AND IT IS FIXED, NOT PER-KERNEL.** MEASURED 2026-11-03: one `bin/bend` build of a
driver holding ONE kernel takes 941 ms and a driver holding SIX takes 967 ms, because what is being paid
for is the typecheck of `cstyle.bend`'s closure, not the kernel. So `render_many` puts every cache miss in
ONE driver: 6 cold kernels cost 1.07 s instead of 6.05 s, and the marginal cost of a kernel falls from
~1.0 s to ~20 ms. `render` is `render_many` with one element, so the two paths cannot emit different C.
"""
import hashlib
import re
import os
import pathlib
import subprocess
import sys
import time

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
BEND = ROOT / "bin" / "bend"
BUN = pathlib.Path(os.environ.get("BUN", str(pathlib.Path.home() / ".bun" / "bin" / "bun")))

# **`BEND_NO_TELEMETRY=1` ON EVERY SPAWN, AND IT IS THE TREE's OWN RULE, NOT A TUNING.** Bend's runtime
# fetches `https://bend-lang.com/check` once a day into `~/.bend/check.json` and prints a "newer bend" notice;
# `checks/differ.py:83` sets this flag for every corpus child for exactly that reason ("THE ONLY OFF-REPO INPUT
# IN THE MEASUREMENT"). `portc`'s two spawn points never did -- MEASURED: 24.1 ms of start-up without the flag
# and 22.9 ms with it, so the phone-home was 1.1 ms of every one-shot render, and on a slow network it is not
# 1.1 ms at all, it is whatever the resolver decides.
ENV = {k: v for k, v in os.environ.items() if k != "PYTHONPATH"} | {"BEND_NO_TELEMETRY": "1"}
GEN = HERE / "gen"
OUT = HERE / "out"

sys.path.insert(0, str(HERE))
import dump_kernel  # noqa: E402
import gen_kus  # noqa: E402

# **THE BUILD IS THE COST, AND IT DOES NOT GROW WITH THE KERNEL COUNT.** MEASURED 2026-11-03: one `bin/bend`
# build of a driver holding ONE kernel takes 941 ms, and a driver holding SIX takes 967 ms -- the typecheck
# of `cstyle.bend`'s closure is the whole of it. So the batch driver below renders N kernels for the price
# of one, and the per-kernel marginal cost falls from ~1 s to ~5 ms.
#
# The separator is a line marker rather than a length prefix because the C source is the payload: a length
# would have to be counted by the renderer, and a marker can be stripped by the caller that already splits
# lines. `@@KERNEL ` cannot occur in C the renderer emits -- it would be a C token starting with `@`.
MARK = "@@KERNEL "

DRIVER = """# %(name)s-driver.bend -- GENERATED by portc.py. DO NOT HAND-EDIT.
import Base
%(imports)s
import ./../../../tinybendygrad/renderer/cstyle.bend as C

def main() -> IO(Unit):
  do IO<Unit>:
%(prints)s
"""


# EVERY input that can change the emitted C: the port's own sources AND this transcription's two
# generators. MEASURED 2026-11-03, twice: a key without the renderer returned the pre-fix `inff` after
# `cstyle.bend` was fixed, and a key without `gen_kus.py` returned `0.0f` after the `-0.0` fix.
RENDERER_SOURCES = ("tinybendygrad/renderer/cstyle.bend", "tinybendygrad/renderer/live.bend",
                    "tinybendygrad/base.bend",
                    "tinybendygrad/uop/ops.bend", "tinybendygrad/LAWS/spec.bend",
                    "tinybendygrad/helpers.bend",
                    ".agents/slop/cpuseam/gen_kus.py", ".agents/slop/cpuseam/portc.py")


def _renderer_stamp() -> str:
  """mtime+size of every source the renderer compiles against, so a renderer edit re-keys."""
  parts = []
  for rel in RENDERER_SOURCES:
    st = (ROOT / rel).stat()
    parts.append(f"{rel}:{st.st_mtime_ns}:{st.st_size}")
  return ";".join(parts)


def rows(uops) -> list[str]:
  """the fixture's own row format, for a live uop list."""
  return [r for r in dump_kernel.dump_uops(uops) if r and not r.startswith("#")]


def _key(rs: list[str]) -> str:
  """the content key: the rows AND every source that can change what the renderer emits."""
  # **THE KEY MUST COVER THE RENDERER, NOT JUST THE UOPS.** A uop-only key returned the PRE-FIX C after
  # `cstyle.bend` was corrected for non-finite constants, so the fix looked like it did nothing --
  # MEASURED: `exp` still failed to compile with the old `inff` after the renderer had been fixed.
  # A cache that hides a fix is the same defect class as a gate that cannot go red.
  return hashlib.sha256(("\n".join(rs) + "|" + _renderer_stamp()).encode()).hexdigest()[:16]


def child_counts(rs) -> list[int]:
  """how many times each uop is a src -- `cstyle.py:212`'s `Counter`, computed where an ARRAY exists."""
  counts = [0] * len(rs)
  for r in rs:
    for s in (int(x) - 1 for x in r.split("|")[6].split()):
      if 0 <= s < len(counts):
        counts[s] += 1
  return counts


def _literal(name: str, rs: list[str]) -> None:
  body = "\n".join(gen_kus.one(name, r, c) for r, c in zip(rs, child_counts(rs)))
  # gen_kus.HEADER is the fixture generator's OWN header: same imports, same paths,
  # so the live list and the fixture list are rendered by identical code.
  (GEN / f"{name}.bend").write_text(gen_kus.HEADER.format(name=name) + "  [\n" + body + "\n  ]\n")


def _build(names: list[str]) -> dict[str, str]:
  """ONE `bin/bend` build and ONE `bun` run for every name, so N kernels cost one typecheck."""
  driver = HERE / f"{names[0]}-driver.bend"
  driver.write_text(DRIVER % {
    "name": names[0],
    "imports": "\n".join(f"import ./gen/{n}.bend as K{i}" for i, n in enumerate(names)),
    "prints": "\n".join(f'    IO.print("{MARK}{n}")\n'
                        f'    IO.print(C.render(C.dev_clang(), True{{}}, K{i}.kus()))'
                        for i, n in enumerate(names)),
  })
  js = OUT / f"{names[0]}.js"
  try:
    build = subprocess.run([str(BEND), str(driver), "-o", str(js)], capture_output=True, text=True)
    if build.returncode != 0:
      raise RuntimeError(f"portc: the port's renderer did not build: {build.stderr.strip()[:400]}")
    run = subprocess.run([str(BUN), str(js)], capture_output=True, text=True, env=ENV)
    if run.returncode != 0:
      raise RuntimeError(f"portc: the port's renderer did not run: {run.stderr.strip()[:400]}")
  finally:
    driver.unlink(missing_ok=True)
  # SPLIT ON THE MARKER, NOT ON A LINE COUNT: the payload is the C, and its line count is the renderer's.
  out, cur = {}, None
  for line in run.stdout.splitlines(keepends=True):
    if line.startswith(MARK):
      cur = line[len(MARK):].strip()
      out[cur] = []
    elif cur is not None:
      out[cur].append(line)
  got = {n: "".join(v) for n, v in out.items()}
  if set(got) != set(names):
    raise RuntimeError(f"portc: rendered {sorted(got)}, asked for {sorted(names)}")
  for n, src in got.items():
    if not src.strip():
      raise RuntimeError(f"portc: the port's renderer printed no C for {n}")
  return got


def render_many(uops_list) -> list[str]:
  """the C for every uop list, with ONE build for all the cache misses. Same bytes as `render`."""
  work = []
  for uops in uops_list:
    rs = rows(uops)
    if not rs:
      raise RuntimeError("portc: the port rendered no uops")
    work.append((f"live_{_key(rs)}", rs))
  missing, seen = [], set()
  for name, rs in work:
    if name not in seen and not (OUT / f"{name}.c").exists():
      missing.append((name, rs))
      seen.add(name)
  if missing:
    GEN.mkdir(parents=True, exist_ok=True)
    OUT.mkdir(parents=True, exist_ok=True)
    for name, rs in missing:
      _literal(name, rs)
    for name, src in _build([n for n, _ in missing]).items():
      (OUT / f"{name}.c").write_text(src)
  return [(OUT / f"{name}.c").read_text() for name, _ in work]


def render(uops) -> str:
  """the C the PORT's renderer emits for this uop list, cached by content."""
  return render_many([uops])[0]



# ===========================================================================
# THE LIVE PATH: build `renderer/live.bend` ONCE into a JS artifact, then feed it kernels at RUNTIME.
#
# WHY IT EXISTS. The literal path above puts the kernel INTO the driver, so each new kernel costs one
# `bin/bend` build -- and that build is the TYPECHECK OF THE CLOSURE, not the kernel: MEASURED 2026-11-03,
# 941 ms for a driver holding one kernel and 967 ms for one holding six. `render_many` amortises that over
# a batch, which is the right shape for a caller that already has every kernel. A REAL PROGRAM DOES NOT: it
# asks for one kernel at a time, in the scheduler's order, so it paid ~1 s per kernel and no batch could
# help it. `live.bend` makes the renderer a fixed artifact and the kernel a string argument.
#
# THE DECODER IS PYTHON AND THE CONSTRUCTOR IS BEND, on purpose: a CONST arrives as EXACT BITS (`hi~lo`,
# or the f32 pattern), never as text, because text is where `1e999`, `-0.0` and 64-bit constants each had
# their own defect.
# ===========================================================================
import struct


def _f32_bits(v: float) -> int:
  return struct.unpack("<I", struct.pack("<f", v))[0]


def _const(payload: str) -> tuple[str, str]:
  """a CONST's value as exact bits -- never as text the renderer would have to parse."""
  p = payload.strip()
  if p.startswith("ConstFloat(") and p.endswith(")"):
    p = p[len("ConstFloat("):-1]
  if p in ("True", "False"):
    return "const_bool", ("1" if p == "True" else "0")
  try:
    v = int(p)
  except ValueError:
    return "const_float", str(_f32_bits(float(p)))
  u = v & 0xFFFFFFFFFFFFFFFF
  return "const_int", f"{(u >> 32) & 0xFFFFFFFF}~{u & 0xFFFFFFFF}"


# **THE WIRE IS 32.5 BYTES PER UOP AND SCANNING IT COSTS 0.15 us A CHARACTER** (`PARITY.md` §48). So the
# three NAME fields travel as ONE CHARACTER each: the dtype, the address space, and the arg kind. `kind` is
# the big one -- `range_PLACEHOLDER` is 17 bytes for one fact. The op NAME stays textual because coding it
# would need a 75-arm table whose only guard is a coverage check, and the win here is already 44% of the wire.
KIND_CODE = {"const_int": "i", "const_float": "f", "const_bool": "t", "param": "p", "index": "x",
             "sink": "s", "special": "q", "none": "-",
             "range_WEAK": "RW", "range_GLOBAL": "RG", "range_LOCAL": "RL", "range_DEVICE": "RD",
             "range_UPCAST": "RU", "range_WARP": "RR", "range_LOOP": "RO", "range_PLACEHOLDER": "RP",
             "wmma_f32": "M1", "wmma_f16": "M2", "wmma_bf16": "M3"}
DT_CODE = {"f32": "1", "i32": "2", "u32": "3", "i64": "4", "u64": "5", "u8": "6", "i8": "7", "u16": "8",
           "i16": "9", "bool": "b", "void": "v", "weakint": "w", "weakfloat": "W", "f16": "h",
           "bf16": "B", "f64": "d"}
ADDR_CODE = {"GLOBAL": "g", "LOCAL": "l", "REG": "r", "ALU": "a", "NONE": "n"}


def enum_members() -> list[str]:
  """`uop/ops.bend`'s enum, in declaration order -- the index space the wire uses."""
  import re as _re
  body = _OPS_SRC.read_text()
  body = body[body.index("type Op is Data:"):]
  body = body[:body.index("\ndef ")]
  return [m[3:] for m in _re.findall(r"^\s+(Ops[A-Z0-9_]+)\{\}", body, _re.M)]


def enum_pin() -> str:
  return hashlib.sha256("\n".join("Ops" + m for m in enum_members()).encode()).hexdigest()[:16]


def _arg(kind: str, payload: str) -> tuple[str, str]:
  """the (tag, payload) pair `live.bend`'s `arg_of` reads. THE TAG CARRIES THE SLICING."""
  if kind == "const":
    return _const(payload)
  if kind == "range":
    axis, _sep, ids = payload.partition("~")
    return f"range_{axis}", ids or "-"
  if kind == "wmma":
    dims, _sep, dt_in = payload.partition("~")
    return f"wmma_{dt_in}", dims.replace("x", "~")
  if kind == "special":
    nm = payload.strip()
    return "special", f"{nm[0]}~{int(nm[-1])}~{nm}"
  if kind == "index":
    return "index", ("0" if payload.strip() in ("-", "", "None") else str(int(payload)))
  if kind in ("param", "sink"):
    return kind, payload.strip()
  return "none", "-"


# ===========================================================================
# THE OP TABLE IS TWO TABLES AND THE ENUM IS THEIR DENOMINATOR, SO THE COVERAGE IS COMPUTED AND NOT ASSUMED.
#
# `live.bend` maps a name to an `Op` with `P.op_of` (46 members, the ones the EXECUTOR ports) and then
# `extra_op` (the rest). **AN UNKNOWN NAME FALLS TO A DEFAULT, WHICH IS A SILENT WRONG ANSWER** -- MEASURED
# while building this: `PAD` and `MSELECT` defaulted and the kernel rendered `(float4){,,,}`, which compiled.
# So the enum is READ OUT OF `uop/ops.bend` and the two tables OUT OF `live.bend`, and a member that neither
# covers RAISES HERE instead of rendering. A new enum member therefore breaks the build, not the C.
# ===========================================================================
_OPS_SRC = ROOT / "tinybendygrad/uop/ops.bend"
_EXEC_SRC = ROOT / "tinybendygrad/runtime/ops_python.bend"
_LIVE_SRC = ROOT / "tinybendygrad/renderer/live.bend"


def op_table_cover(enum_src: str, exec_src: str, live_src: str) -> tuple[list[str], list[str]]:
  """(the enum's members, the INDEX ARMS `live.bend` is missing) -- text in, so a doctored copy can be
  measured. `exec_src` is unused since the op table stopped being the executor's, and is kept so the
  signature (and every caller) does not have to churn."""
  import re as _re
  body = enum_src[enum_src.index("type Op is Data:"):]
  body = body[:body.index("\ndef ")]
  members = [m[3:] for m in _re.findall(r"^\s+(Ops[A-Z0-9_]+)\{\}", body, _re.M)]
  tbl = live_src[live_src.index("def op_by_idx("):]
  tbl = tbl[:tbl.index("def op_of(")]
  # **THE ARM KEY MAY BE A NUMBER OR A STRING, AND BOTH ARE READ.** `live.bend`'s op table was keyed by
  # the enum index as a DECIMAL STRING, and `PARITY.md` §133 changed it to a `U32` because a `match` on a
  # String in Bend COMPILES TO A CHARACTER TRIE (84 `slice`s and 2,560 `char_len` calls a render) while a
  # `match` on a `U32` IS AN INTEGER COMPARE. **⇒ THIS CHECK'S SUBJECT IS THE COVERAGE, NOT THE
  # SPELLING** -- so it reads both, and a table that spelled one key would still be checked.
  have = set(int(m) for m in _re.findall(r'case "(\d+)": O\.Ops', tbl)) | \
         set(int(m) for m in _re.findall(r'case (\d+): O\.Ops', tbl))
  return members, [m for i, m in enumerate(members) if i not in have]


def _check_op_tables() -> None:
  live = _LIVE_SRC.read_text()
  pin = re.search(r"# ENUM-PIN ([0-9a-f]{16})", live)
  if pin is None:
    raise RuntimeError("portc: live.bend has no ENUM-PIN; the op index table is unguarded")
  if pin.group(1) != enum_pin():
    raise RuntimeError(f"portc: the enum moved (pin {pin.group(1)} != {enum_pin()}); regenerate "
                       f"op_by_idx in liven.bend. REFUSING to render with an order-coupled table.")
  members, missing = op_table_cover(_OPS_SRC.read_text(), _EXEC_SRC.read_text(), live)
  if missing:
    raise RuntimeError(f"portc: live.bend names {len(members) - len(missing)} of {len(members)} ops; "
                       f"it would render these as a default: {missing}")


_OPS_INDEX = {m: i for i, m in enumerate(enum_members())} if "_OPS_SRC" in globals() else {}


def wire_rows(rs) -> str:
  """the RUNTIME wire: NINE space-separated fields per uop, FLAT -- no line structure at all, because every
  separator is a pass over every byte and the decoder can group nine tokens as cheaply as it can split a
  line. `PARITY.md` §78 measures the second pass at 0.89 ms of a 2.17 ms decode."""
  _check_op_tables()
  # **THE CHILD COUNT TRAVELS ON THE WIRE BECAUSE THE RENDERER CANNOT COMPUTE IT FOR FREE.** `cstyle.py:212`
  # builds `Counter(v for ru in uops for v in ru.src)` once and then asks `child_count[u] == 1` twice per uop
  # (`:252`, `:254`). In this port the kernel is a `List`, so `List.get` is O(index) and `List.set` rebuilds
  # the prefix: MEASURED, building that counter cost 104,946 list steps and reading it back 154,915, i.e. 32%
  # of every `List.get` step in a 405-uop render (805,127 total). Python has the array, so it counts here.
  child = child_counts(rs)
  lines = []
  for r, cc in zip(rs, child):
    _idx, op, dt, addr, shape, numel, srcs, kind, payload = r.split("|")
    ss = [int(x) - 1 for x in srcs.split()] if srcs.strip() else []
    tag, val = _arg(kind, payload)
    zero = "-" if not ss else "~".join(str(s) for s in ss)
    idx = _OPS_INDEX.get(op)
    if idx is None:
      raise RuntimeError(f"portc: {op} is not in uop/ops.bend's enum")
    lines.append(" ".join([str(idx), DT_CODE[dt], ADDR_CODE[addr], shape or "-", numel,
                           KIND_CODE[tag], val, zero, str(cc)]))
  if not lines:
    raise RuntimeError("portc: the port rendered no uops")
  return " ".join(lines)


def wire(uops) -> str:
  """the RUNTIME wire for a live uop list."""
  return wire_rows(rows(uops))


def _live_js() -> pathlib.Path:
  """the renderer compiled ONCE. Keyed on every source that can change the C, so an edit rebuilds it."""
  js = OUT / f"live-{hashlib.sha256(_renderer_stamp().encode()).hexdigest()[:16]}.js"
  if js.exists():
    return js
  OUT.mkdir(parents=True, exist_ok=True)
  build = subprocess.run([str(BEND), str(ROOT / "tinybendygrad/renderer/live.bend"), "-o", str(js)],
                         capture_output=True, text=True)
  if build.returncode != 0:
    raise RuntimeError(f"portc: live.bend did not build: {build.stderr.strip()[:400]}")
  return js


# **A LARGER STACK WAS TRIED FIRST AND DOES NOT WORK: `bun --stack-size=8192` IS A NO-OP HERE.** MEASURED
# with a control -- a trivial 60 000-frame recursion fails identically with and without the flag -- so the
# bound had to be removed from the parser instead of bought from the runtime.
# **THE WIRE IS CHUNKED, BECAUSE `String.split` IS RECURSIVE PER CHARACTER.** The runtime's own JS
# (`langs/js/core.js:357`, `$String$split$`) recurses on the tail string, so ONE call over ~28 KB answers
# `RangeError` -> "the machine stack overflowed". MEASURED on this parser: 900 lines / 24.3 KB decoded and
# 1500 lines / 40.5 KB did not, and 100 lines / 18.6 KB decoded while 200 long lines / 37.2 KB did not --
# i.e. the cliff is on CHARACTERS, not on uops. MEASURED against this parser with the SAME bytes moved
# between chunk sizes: 15 KB per chunk decoded at 1200 and at 2400 uops, while 20 KB and 30 KB failed at
# both -- so the bound is the per-chunk string and 10 KB is margin, not a guess.
CHUNK = 10000


def _chunks(text: str) -> list[str]:
  """split the wire at UOP boundaries into pieces `live.bend` can each split without the cliff.

  A chunk has to carry whole rows: nine tokens per uop, so the split is on the token count, never on a
  character count that could land mid-row."""
  toks = text.split()
  per = 9 * max(1, CHUNK // 27)          # 27 bytes is the longest row this wire emits
  return [" ".join(toks[i:i + per]) for i in range(0, len(toks), per)] or [""]


# **THE RENDERER AS A COMPILED EXECUTABLE, BECAUSE START-UP IS NOW THE COST.** §52's profile of the shipped
# artifact is 30.2% `resolve` and 6.1% `parseModule`: loading a 433 KB script is 24.1 ms of a 47 ms one-shot
# render, twice the work it does. `bun build --compile` embeds the runtime and the script in one executable,
# and MEASURED on the same 405-uop wire it is `median 0.8907, 14 of 14 rounds faster` than `bun file.js` with
# byte-identical output. The build is 0.2 s ONCE per renderer stamp, cached beside the .js.
def _live_bin() -> pathlib.Path | None:
  """the compiled renderer, or None when `bun build` cannot make one (the .js path still works)."""
  js = _live_js()
  # **`--bytecode` IS THE SECOND HALF OF THE PACKAGING WIN.** `--compile` embeds the script as SOURCE, so the
  # runtime still parses 433 KB at every start; `--bytecode` ships the COMPILED form. MEASURED on the
  # 405-uop wire against the §53 binary, same output: `median 0.8491, 13 of 14 rounds faster`, and against
  # `bun file.js` the pair is `47.0 -> 37.0 ms` of one-shot render. The suffix is `.bc` so a pre-bytecode
  # `.bin` beside it cannot be mistaken for this one.
  exe = js.with_suffix(".bc")
  if exe.exists():
    return exe
  build = subprocess.run([str(BUN), "build", "--compile", "--minify", "--bytecode", str(js), "--outfile", str(exe)],
                         capture_output=True, text=True, env=ENV)
  if build.returncode != 0 or not exe.exists():
    return None
  return exe


def _render_wire(text: str) -> str:
  """render a WIRE STRING -- the live path's whole input, so it can be exercised without a uop list."""
  exe = _live_bin()
  cmd = [str(exe), *_chunks(text)] if exe else [str(BUN), str(_live_js()), *_chunks(text)]
  run = subprocess.run(cmd, capture_output=True, text=True, env=ENV)
  if run.returncode != 0:
    raise RuntimeError(f"portc: the live renderer did not run: {run.stderr.strip()[:400]}")
  if not run.stdout.strip():
    raise RuntimeError("portc: the live renderer printed no C")
  return run.stdout


# ===========================================================================
# THE LONG-LIVED RENDERER: one `bun` for the whole session, one kernel per signal.
#
# WHY IT EXISTS. `render_live` removes the per-kernel TYPECHECK but not the per-kernel PROCESS: MEASURED, a
# fresh `bun` costs ~26.5 ms of start-up and ~20 ms of loading a 349 KB artifact, and at ~163 uops that
# fixed cost is larger than the render itself. `serve.bend` is the same renderer in a loop.
#
# THE TWO THINGS THAT MAKE IT SAFE RATHER THAN A HANG:
#   * THE REQUEST IS A FILE AND THE PIPE CARRIES ONE BYTE. `File.read` on a pipe returns what is available,
#     so a 13 KB wire down a pipe can be truncated; a regular file written-then-renamed is whole, and a
#     one-byte signal is a whole signal.
#   * EVERY READ HAS A TIMEOUT AND A FALLBACK. A worker that does not answer in `TIMEOUT` is killed and the
#     call goes to the ONE-SHOT path, which is the same renderer and the same bytes, just slower. That is
#     not the silent-fallback defect the tree forbids (that was handing the kernel to TINYGRAD's renderer):
#     the port still renders it, and `worker_stats()` counts every fallback so nothing is invisible.
# ===========================================================================
# **THE DAEMON IS THE DEFAULT, AND IT GOT THERE BY LOSING ITS LAST DEFECT.** It first stalled on the FOURTH
# turn while the same six signals driven from a shell all answered -- which localised the fault to this file
# and not to Bend: `select.select([proc.stdout], ...)` plus `readline()` is wrong against a `TextIOWrapper`,
# because `readline` fills an 8 KB buffer and a later result can already be IN PYTHON with the fd empty, so
# `select` waits for a byte that has arrived. A reader thread blocking in `readline` with a `Queue` has no
# such window. MEASURED after the fix: 12 consecutive turns, median 6.0 ms, every answer byte-identical,
# zero fallbacks; and `compile.py` cold 38.4 -> 14.2 ms per kernel. `BEND_SERVE=0` opts out, and one stall
# still disables it for the session, so the failure mode stays a timeout and a fallback rather than a hang.
TIMEOUT = 20.0
_FALLBACKS = []
_WORKER = None
_OFF = [False]


class Worker:
  """the live renderer, resident. `render` answers the C for one wire."""

  def __init__(self, js: pathlib.Path, stamp: str):
    self.js = js
    self.dir = OUT / f"serve-{stamp}"
    self.dir.mkdir(parents=True, exist_ok=True)
    self.fifo = self.dir / "sig.fifo"
    self.req = self.dir / "req.wire"
    if not self.fifo.exists():
      os.mkfifo(self.fifo)
    self.proc = None
    self.w = None
    self.q = None
    self.reader = None
    self.turns = 0

  def start(self) -> None:
    # **THE DAEMON PAYS START-UP ONCE PER SESSION, AND §53/§54 SHOWED PACKAGING IS WORTH 26% OF IT.** The
    # worker used to be spawned as `bun serve.js`, i.e. the same module-resolution start the one-shot path
    # had before `--compile --minify --bytecode`. `_serve_bin` ships the same program as an executable, so
    # the FIRST turn of a session pays the packed start and every later turn pays nothing.
    exe = _serve_bin(self.js)
    cmd = [str(exe), f"{self.fifo}|{self.req}"] if exe else [str(BUN), str(self.js), f"{self.fifo}|{self.req}"]
    self.proc = subprocess.Popen(cmd,
                                 stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                                 stderr=subprocess.PIPE, text=True, bufsize=1, env=ENV)
    # **THE WRITER STAYS OPEN FOR THE WHOLE SESSION, AND THAT IS A MEASURED FIX.** Opening and closing it
    # per request gives the reader an EOF BETWEEN requests, and the worker -- which has no way to tell an
    # EOF read from a signal read without a branch it cannot express -- renders the current request file on
    # every read. MEASURED with a per-request writer: `live 1/6 byte-identical`, because one extra turn per
    # request shifted every answer by one. A writer that never closes has no EOF between requests.
    self.w = open(self.fifo, "wb", buffering=0)
    # **A READER THREAD, NOT `select` ON THE STREAM.** MEASURED: `select.select([proc.stdout], ...)` plus
    # `readline()` stalled on the FOURTH turn while the worker answered all six when the same six signals
    # were driven from a shell. The cause is read-ahead: `readline()` on a `TextIOWrapper` fills an 8 KB
    # buffer, so a later result can already be IN PYTHON with the fd empty, and `select` then waits for a
    # byte that has arrived. A thread that blocks in `readline()` has no such window, and a `Queue` carries
    # the line to the caller with its own timeout.
    import threading
    import queue
    self.q = queue.Queue()
    out = self.proc.stdout

    def pump():
      for line in out:
        self.q.put(line)
      self.q.put(None)

    self.reader = threading.Thread(target=pump, daemon=True)
    self.reader.start()

  def stop(self) -> None:
    if self.q is not None:
      self.q.put(None)
    if self.w is not None:
      self.w.close()
      self.w = None
    if self.proc is not None:
      self.proc.kill()
      self.proc.wait(timeout=5)
      self.proc = None

  def render(self, text: str) -> str:
    """one kernel. Raises `TimeoutError`/`RuntimeError` so the caller can fall back."""
    import select
    if self.proc is None or self.proc.poll() is not None:
      self.start()
    # **THE FRAME IS "<decimal length>\n<wire>" IN ONE WRITE.** §79.2 measured the file round trip (write,
    # rename, open, read, close) at 0.96 ms of a 5.88 ms turn; two A/B runs of this protocol against it
    # were median 0.9103 and 0.9459 (`PARITY.md` §84). A short pipe read is not a truncated request here:
    # the worker loops until it has the length it was promised (§83 records the shape the language forces).
    # **THE FRAME IS ONE "<length>\n<chunk>" PER CHUNK, TERMINATED BY A ZERO-LENGTH CHUNK.** The chunks are
    # the ones `_chunks` already cuts at ROW boundaries, so the daemon splits exactly what the one-shot path
    # splits -- one `String.split` over 28 KB overflows this runtime's stack, and §84.3 measured a 1,215-uop
    # kernel killing the worker and downgrading the rest of the session to the one-shot path.
    parts = _chunks(text)
    self.w.write("".join(f"{len(c)}\n{c}" for c in parts).encode() + b"0\n")
    import queue
    deadline = time.time() + TIMEOUT
    lines, started = [], False
    while True:
      left = deadline - time.time()
      if left <= 0:
        raise TimeoutError("serve: no answer within the timeout")
      try:
        line = self.q.get(timeout=left)
      except queue.Empty:
        raise TimeoutError("serve: no answer within the timeout") from None
      if line is None:
        raise RuntimeError("serve: worker exited")
      line = line.rstrip("\n")
      if line == "@@BEGIN":
        started = True
      elif line == "@@END" and started:
        self.turns += 1
        return "\n".join(lines) + "\n"
      elif started:
        lines.append(line)


def _serve_bin(js: pathlib.Path) -> pathlib.Path | None:
  """the WORKER as a compiled executable, cached beside its .js; None when `bun build` cannot."""
  exe = js.with_suffix(".bc")
  if exe.exists():
    return exe
  build = subprocess.run([str(BUN), "build", "--compile", "--minify", "--bytecode", str(js), "--outfile", str(exe)],
                         capture_output=True, text=True, env=ENV)
  return exe if build.returncode == 0 and exe.exists() else None


def worker_stats() -> dict:
  return {"turns": _WORKER.turns if _WORKER is not None else 0, "fallbacks": len(_FALLBACKS)}


def _worker() -> Worker:
  global _WORKER
  if _WORKER is None:
    stamp = hashlib.sha256(_renderer_stamp().encode()).hexdigest()[:16]
    js = OUT / f"serve-{stamp}.js"
    if not js.exists():
      build = subprocess.run([str(BEND), str(HERE / "serve.bend"), "-o", str(js)],
                             capture_output=True, text=True)
      if build.returncode != 0:
        raise RuntimeError(f"portc: serve.bend did not build: {build.stderr.strip()[:400]}")
    _WORKER = Worker(js, stamp)
    import atexit
    atexit.register(_WORKER.stop)
  return _WORKER


def render_live(uops) -> str:
  """the C for one kernel, with NO build: the renderer is an artifact and the kernel is an argument."""
  text = wire(uops)
  key = hashlib.sha256((text + "|" + _renderer_stamp()).encode()).hexdigest()[:16]
  cached = OUT / f"livew_{key}.c"
  if cached.exists():
    return cached.read_text()
  if os.environ.get("BEND_SERVE") == "0" or _OFF[0]:
    src = _render_wire(text)
  else:
    try:
      src = _worker().render(text)
    except (TimeoutError, RuntimeError, OSError) as e:
      # ONE STALL IS ENOUGH: the worker is killed and this process stops asking, so a broken daemon costs
      # one timeout and not one per kernel.
      _FALLBACKS.append(str(e)[:120])
      _OFF[0] = True
      try:
        _worker().stop()
      except Exception:
        pass
      src = _render_wire(text)
  cached.write_text(src)
  return src
