#!/usr/bin/env python3
"""portc.py -- render a LIVE uop list with the PORT's OWN `cstyle.bend`.

    import portc; c_source = portc.render(uops)

WHY THIS EXISTS: `BEND_C=1`'s compiled lane handed `[ClangRenderer]` to `Compiled`, i.e. it rendered C
with TINYGRAD's code. The port has its own renderer, `tinybendygrad/renderer/cstyle.bend`, and
`.agents/slop/cpuseam/compare.py` proves it equivalent (5 kernels, max_abs=0, fail=0) -- but nothing in
the device path called it. This is that call.

HOW IT WORKS, AND WHY IT LOOKS LIKE THIS: `cstyle.bend`'s `C.render` takes a `KU` LIST -- a Bend value,
not text -- so the uop list must be turned into Bend LITERALS and compiled. That is what `gen_kus.py`
does for the fixtures (`uops/<name>.rows` -> `gen/<name>.bend`), and the port's own seam runs it as
`bend -o .js` then `bun`. This module does the same for an arbitrary live list:

    uops -> rows (dump_kernel.dump_uops, the SAME formatter the fixture uses)
         -> gen/live_<hash>.bend   (a `kus()` literal, via gen_kus.one)
         -> live_<hash>-driver.bend (prints C.render(C.dev_clang(), True{}, K.kus()))
         -> bend -o <js> -> bun <js> -> the C on stdout

THE TRANSCRIPTION IS NOT RE-TYPED: `dump_uops` and `gen_kus.one` are IMPORTED, not copied, so a live
render and a fixture render cannot disagree about the format.

THE CACHE IS CONTENT-KEYED (sha256 of the rows), so the same kernel renders once. A render costs one
`bend` build (~10-15 s on this machine); repeating it for an unchanged uop list costs nothing.
"""
import hashlib
import os
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
BEND = ROOT / "bin" / "bend"
BUN = pathlib.Path(os.environ.get("BUN", str(pathlib.Path.home() / ".bun" / "bin" / "bun")))
GEN = HERE / "gen"
OUT = HERE / "out"

sys.path.insert(0, str(HERE))
import dump_kernel  # noqa: E402
import gen_kus  # noqa: E402

DRIVER = """# live_%(name)s-driver.bend -- GENERATED by portc.py. DO NOT HAND-EDIT.
import Base
import ./gen/%(name)s.bend as K
import ./../../../tinybendygrad/renderer/cstyle.bend as C

def main() -> IO(Unit):
  do IO<Unit>:
    IO.print(C.render(C.dev_clang(), True{}, K.kus()))
"""


def rows(uops) -> list[str]:
  """the fixture's own row format, for a live uop list."""
  return [r for r in dump_kernel.dump_uops(uops) if r and not r.startswith("#")]


def render(uops) -> str:
  """the C the PORT's renderer emits for this uop list, cached by content."""
  rs = rows(uops)
  if not rs:
    raise RuntimeError("portc: the port rendered no uops")
  key = hashlib.sha256("\n".join(rs).encode()).hexdigest()[:16]
  name = f"live_{key}"
  cached = OUT / f"{name}.c"
  if cached.exists():
    return cached.read_text()
  GEN.mkdir(parents=True, exist_ok=True)
  OUT.mkdir(parents=True, exist_ok=True)
  body = "\n".join(gen_kus.one(name, r) for r in rs)
  # gen_kus.HEADER is the fixture generator's OWN header: same imports, same paths,
  # so the live list and the fixture list are rendered by identical code.
  (GEN / f"{name}.bend").write_text(gen_kus.HEADER.format(name=name) + "  [\n" + body + "\n  ]\n")
  driver = HERE / f"{name}-driver.bend"
  driver.write_text(DRIVER % {"name": name})
  js = OUT / f"{name}.js"
  try:
    build = subprocess.run([str(BEND), str(driver), "-o", str(js)], capture_output=True, text=True)
    if build.returncode != 0:
      raise RuntimeError(f"portc: the port's renderer did not build: {build.stderr.strip()[:400]}")
    run = subprocess.run([str(BUN), str(js)], capture_output=True, text=True)
    if run.returncode != 0:
      raise RuntimeError(f"portc: the port's renderer did not run: {run.stderr.strip()[:400]}")
  finally:
    driver.unlink(missing_ok=True)
  src = run.stdout
  if not src.strip():
    raise RuntimeError("portc: the port's renderer printed no C")
  cached.write_text(src)
  return src
