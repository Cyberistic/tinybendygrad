#!/usr/bin/env python3
"""gen_kus.py -- TURN THE ORACLE's UOP LIST INTO A BEND `KU` LIST.

    .venv/bin/python .agents/slop/cpuseam/gen_kus.py

WHAT IT WRITES: `gen/<name>.bend`, ONE FILE PER KERNEL, each holding

    import ./../../../../tinybendygrad/renderer/cstyle.bend as C
    import ./../tinybendygrad/uop/ops.bend as O
    import ./../tinybendygrad/LAWS/spec.bend as S
    import ./../tinybendygrad/helpers.bend as H

    def kus() -> List<&2, C.KU>: [ C.KU{...}, ... ]

WHY A GENERATED `.bend` AND NOT A PARSER: the port's assembler takes a `KU`
LIST, and the fixture that PRODUCES that list is the ORACLE's own uop list
(`.agents/slop/cpuseam/uops/<name>.rows`, written by `dump_kernel.py` from
upstream's live objects). Writing the list out as a Bend LITERAL keeps the
transcription in ONE SCRIPT -- this one -- and keeps the port's assembler free
of FILE PARSING, which is not what it is for.

THE EXPECTATIONS ARE NEVER TYPED: every field below is READ OUT OF THE
SCRIPT-WRITTEN `.rows` FIXTURE, WHICH IS ITSELF READ OUT OF UPSTREAM's OWN
OBJECTS.
"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
UOPS = HERE / "uops"
GEN = HERE / "gen"

# **THE OP MAP IS DERIVED FROM THE PORT's OWN ENUM, NOT HAND-LISTED.** A hand list is exactly the
# shape AGENTS.md forbids for a population, and it FAILED ON ITS FIRST REAL USE: the matmul battery ran
# `exp`/`log2`/`sin` and hit `unknown op CDIV`, which the list simply did not carry -- while carrying
# `IDIV`, an entry whose target `O.OpsIDIV` DOES NOT EXIST in the enum (75 members, no OpsIDIV), so any
# `IDIV` would have emitted invalid Bend rather than failing loudly. MEASURED: 0 of the fixture rows use
# `DIV`, `IDIV` or `MOD`, so all three aliases were dead as well as wrong.
#
# The port's `Ops` enum is 1:1 with upstream's (75 members, same names), so the name IS the mapping.
PORT_OPS_BEND = pathlib.Path(__file__).resolve().parents[3] / "tinybendygrad" / "uop" / "ops.bend"


def enum_ops() -> dict[str, str]:
    """upstream's op NAME -> the port's constructor, read out of `uop/ops.bend`."""
    text = PORT_OPS_BEND.read_text()
    body = text[text.index("type Op is Data:"):]
    names = re.findall(r"^\s+(Ops[A-Z0-9_]+)\{\}", body, re.M)
    if not names:
        raise SystemExit(f"gen_kus: no Ops members found in {PORT_OPS_BEND}")
    return {n[len("Ops"):]: f"O.{n}{{}}" for n in names}


OPS = enum_ops()

DTS = {
    "f32": "S.single()", "i32": "S.int32()", "u32": "S.uint32()",
    "i64": "S.int64()", "u64": "S.uint64()", "u8": "S.uint8()",
    "i8": "S.int8()", "u16": "S.uint16()", "i16": "S.int16()",
    "bool": "S.boolean()", "void": "S.void()", "weakint": "S.weakint()",
    "weakfloat": "S.weakfloat()",
    "f16": "S.half()", "bf16": "S.bfloat16()", "f64": "S.double()",
    "weakfloat": "S.weakfloat()",
}

ADDRS = {"GLOBAL": "S.AGlobal{}", "LOCAL": "S.ALocal{}", "REG": "S.AReg{}",
         "ALU": "S.Aalu{}", "NONE": "S.Aalu{}"}

AXES = {"WEAK": "O.AXIS_WEAK{}", "GLOBAL": "O.AXIS_GLOBAL{}", "LOCAL": "O.AXIS_LOCAL{}",
        "DEVICE": "O.AXIS_DEVICE{}", "UPCAST": "O.AXIS_UPCAST{}", "WARP": "O.AXIS_WARP{}",
        "LOOP": "O.AXIS_LOOP{}", "PLACEHOLDER": "O.AXIS_PLACEHOLDER{}"}

HEADER = """# {name}.bend -- GENERATED by .agents/slop/cpuseam/gen_kus.py FROM
# .agents/slop/cpuseam/uops/{name}.rows. DO NOT HAND-EDIT.
#
# THE INPUT IS UPSTREAM's OWN UOP LIST (see dump_kernel.py), AND THE OUTPUT IS
# THE PORT's OWN `KU` LIST, SO THE PORT's `cstyle.bend` RENDERS C FROM IT.
import Base
import ./../../../../tinybendygrad/renderer/cstyle.bend as C
import ./../../../../tinybendygrad/uop/ops.bend as O
import ./../../../../tinybendygrad/LAWS/spec.bend as S
import ./../../../../tinybendygrad/helpers.bend as H
import ./../../../../tinybendygrad/base.bend as F

def kus() -> List<&2, C.KU>:
"""


def num(s: str) -> str:
    """a Bend U32 literal -- every numeric field of `KU` is a `U32`."""
    return str(int(s))


def const_arg(payload: str) -> str:
    """the CONST's value: a bool, an int, or a float -- decided by PARSING, never by sniffing."""
    p = payload.strip()
    # upstream's float const is a `ConstFloat` OBJECT; the VALUE is what the port needs.
    if p.startswith("ConstFloat(") and p.endswith(")"):
        p = p[len("ConstFloat("):-1]
    # **A BOOL CONST IS NOT A FLOAT, AND SUBSTRING SNIFFING SAID IT WAS.** `"True"` CONTAINS AN `e`,
    # so the old `"e" in p` test emitted `O.CFloat{True}` and the render failed with "expected : a
    # defined name, observed : True". MEASURED on `exp`, whose kernel carries a `CONST bool`.
    if p in ("True", "False"):
        return "C.KAConst{O.CBool{True{}}}" if p == "True" else "C.KAConst{O.CBool{False{}}}"
    # **`1e999` AND `inf` ARE NOT BEND LITERALS.** MEASURED with `bin/bend --check-only`: `1e999`
    # answers "expected : a numeric literal", `inf` answers "expected : a defined name", and
    # `O.CFloat{(0.0-inf : F32)}` is a parse error at the `-`. The port has `F32.from_bits`, and
    # MEASURED `(1.0/0.0 : F32)` = 2139095040 (+inf), `(0.0-1.0/0.0 : F32)` = 4286578688 (-inf),
    # `(0.0/0.0 : F32)` = 2143289344 (nan) -- so these are the EXACT patterns, not approximations.
    special = {"inf": 2139095040, "-inf": 4286578688, "nan": 2143289344}
    if p in special:
        return f"C.KAConst{{O.CFloat{{F.F32.from_bits({special[p]})}}}}"
    # **NEGATIVE ZERO IS NOT `(0.0-0.0)`.** That expression is +0.0, so the sign was destroyed at
    # TRANSCRIPTION time and the renderer then spelled `0.0f` where upstream spells `-0.0f`.
    # MEASURED 2026-11-03: `log2` and `sin` differed on exactly that token (`val0[i]<-0.0f` vs `<0.0f`)
    # while still agreeing numerically. `F32.from_bits(0x80000000)` is the exact pattern.
    if p.startswith("-"):
        try:
            if float(p) == 0.0:
                return "C.KAConst{O.CFloat{F.F32.from_bits(2147483648)}}"
        except ValueError:
            pass
    try:
        v = int(p)
    except ValueError:
        # **A NEGATIVE LITERAL NEEDS ITS PARENS AND ITS TYPE.** MEASURED: `O.CFloat{-1.44}` is a
        # parse error, `O.CFloat{(0.0-1.44)}` is still one, and `(0.0-1.44 : F32)` compiles.
        v = f"(0.0{p} : F32)" if p.startswith("-") else p
        return f"C.KAConst{{O.CFloat{{{v}}}}}"
    # **AN INT CONST IS 64 BITS, AND `i64_of_i32` IS 32.** The mask `& 0xFFFFFFFF` plus a
    # sign-extending constructor silently truncated every wide constant: a `2**62-1` mask became
    # `-1`. MEASURED 2026-11-03: `sin` was the last kernel to differ from upstream and its 11
    # divergent lines were exactly `&4611686018427387903ul` against `&-1ul`. `i64_of_hi_lo` is the
    # constructor that carries both halves (they are two's complement, helpers.bend:1644).
    u = v & 0xFFFFFFFFFFFFFFFF
    return f"C.KAConst{{O.CInt{{H.i64_of_hi_lo({(u >> 32) & 0xFFFFFFFF}, {u & 0xFFFFFFFF})}}}}"


def param_arg(payload: str) -> str:
    f = payload.split("~")
    slot, name, vol, nbytes = f[0], f[1], f[2], f[3]
    nm = "None{}" if name == "-" else f'Some{{"{name}"}}'
    return f"C.KAParam{{{num(slot)}, {nm}, {'True{}' if vol == '1' else 'False{}'}, {num(nbytes)}}}"


def range_arg(payload: str) -> str:
    f = payload.split("~")
    ax = AXES.get(f[0])
    if ax is None:
        raise SystemExit(f"unknown axis {f[0]}")
    ids = ", ".join(num(x) for x in f[1:])
    return f"C.KARange{{{ax}, [{ids}]}}"


def index_arg(payload: str) -> str:
    off = 0 if payload.strip() in ("-", "", "None") else int(payload.strip())
    return f"C.KAIndex{{{num(off)}, False{{}}}}"


def wmma_arg(payload: str) -> str:
    """`Ops.WMMA`'s arg is `(dims, dtype_in, ...)`; the dims join with `_` into the
    helper's NAME (cstyle.py:114), so both travel."""
    dims, dt_in = payload.split("~")
    ids = ", ".join(str(int(x)) for x in dims.split("x"))
    d = DTS.get(dt_in)
    if d is None:
        raise SystemExit(f"unknown WMMA input dtype {dt_in}")
    return f"C.KAWmma{{[{ids}], {d}}}"


def special_arg(payload: str) -> str:
    """`Ops.SPECIAL`'s arg IS its name -- "lidx0".

    cstyle.py:239 binds the variable NAME from it (`r[u] = u.arg`), and :47 reads the
    axis off `arg[0]` and the index off `arg[-1]`, so all three travel. The index is one
    DIGIT for the same reason: upstream indexes by `arg[-1]`.
    """
    nm = payload.strip()
    return f'C.KASpecial{{"{nm[0]}", {int(nm[-1])}, "{nm}"}}'


def sink_arg(payload: str) -> str:
    return f'C.KASink{{"{payload.strip()}"}}'


def one(name: str, line: str) -> str:
    f = line.split("|")
    idx, op, dt, addr, shape, numel, srcs, kind, payload = f
    o = OPS.get(op)
    if o is None:
        raise SystemExit(f"{name}: unknown op {op}")
    d = DTS.get(dt)
    if d is None:
        raise SystemExit(f"{name}: unknown dtype {dt}")
    a = ADDRS.get(addr)
    if a is None:
        raise SystemExit(f"{name}: unknown addrspace {addr}")
    shp = "Nil{}" if shape == "" else "[" + ", ".join(num(x) for x in shape.split("x")) + "]"
    ss = "Nil{}" if srcs.strip() == "" else "[" + ", ".join(num(int(x) - 1) for x in srcs.split()) + "]"
    if kind == "const":
        arg = const_arg(payload)
    elif kind == "param":
        arg = param_arg(payload)
    elif kind == "range":
        arg = range_arg(payload)
    elif kind == "index":
        arg = index_arg(payload)
    elif kind == "sink":
        arg = sink_arg(payload)
    elif kind == "special":
        arg = special_arg(payload)
    elif kind == "wmma":
        arg = wmma_arg(payload)
    else:
        arg = "C.KANone{}"
    return (f"  C.KU{{{o}, {d}, {a}, {num(numel)}, {shp}, {arg}, {ss}}}, # {idx} {op} {dt} {addr}")


def main() -> int:
    GEN.mkdir(parents=True, exist_ok=True)
    names = sorted(p.stem for p in UOPS.glob("*.rows"))
    for name in names:
        rows = [ln for ln in (UOPS / f"{name}.rows").read_text().splitlines()
                if ln and not ln.startswith("#")]
        body = "\n".join(one(name, ln) for ln in rows)
        (GEN / f"{name}.bend").write_text(HEADER.format(name=name) + "  [\n" + body + "\n  ]\n")
        print(f"# {name}: {len(rows)} uops")
    print(f"# wrote {len(names)} files to {GEN}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
