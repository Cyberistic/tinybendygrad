#!/usr/bin/env python3
"""Extract the four rendered kernels from `.agents/slop/browser/fchain-c.rows` into C.

The rows file is the probe's stdout, and the C in it is the artifact: one `--kN` section per kernel,
each holding an UNMODIFIED `void test(...)`. The ONLY edit here is the function NAME, so `k0`..`k3`
can be linked in one TU -- a rename is a fact the compiler checks, unlike a transcription."""
import re, sys, pathlib

HERE = pathlib.Path(__file__).resolve().parent
rows = (HERE / "fchain-c.rows").read_text()
body = rows.split("chain_c=", 1)[1].replace("\\n", "\n")
parts = re.split(r"--k(\d+)\n", body)
kernels = [(parts[i], parts[i + 1]) for i in range(1, len(parts), 2)]

out = ["/* GENERATED by fchain-gen.py from fchain-c.rows -- do not edit. */", "#include <stdio.h>"]
for tag, src in kernels:
    assert src.count("void test(") == 1, f"k{tag}: expected exactly one definition"
    out.append(src.strip().replace("void test(", f"void k{tag}(", 1))
(HERE / "fchain-kernels.c").write_text("\n\n".join(out) + "\n")
print(f"wrote {len(kernels)} kernels")
