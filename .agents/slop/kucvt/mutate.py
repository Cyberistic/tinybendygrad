#!/usr/bin/env python3
"""mutate.py -- WRITE THE PLANT's COPY OF THE PORT's CONVERTER.

    .venv/bin/python .agents/slop/kucvt/mutate.py

WHAT IT DOES
------------
IT READS `tinybendygrad/renderer/kuconv.bend` (THE PORT's OWN CONVERTER) AND
WRITES `.agents/slop/kucvt/kuconv_plant.bend` WITH **ONE** EDIT:

    `kuconv.pos(ix, s)`  ->  `U32.add(kuconv.pos(ix, s), 1)`

**THE OFF-BY-ONE ON THE `srcs` RE-INDEX.**  THAT IS THE WHOLE PROBLEM THE
CONVERTER SOLVES (§2.3 OF THE REPORT), SO BREAKING IT IS THE CONTROL THAT
PROVES THE MEASUREMENT IS A MEASUREMENT.

IT REFUSES IF THE EDIT SITE IS NOT FOUND, **EXACTLY ONCE**, BECAUSE A PLANT
THAT SILENTLY DID NOTHING IS A ROW THAT CANNOT GO RED.

THE PORT's CONVERTER IS NEVER EDITED.  THE PLANT LIVES IN THE HARNESS's OWN
DIRECTORY AND IS USED ONLY BY `.agents/slop/kucvt/harness_plant/`.
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
PORT = HERE.parent.parent.parent / "tinybendygrad" / "renderer" / "kuconv.bend"
PLANT = HERE / "kuconv_plant.bend"

OLD = "List.append(&2, U32, acc, [kuconv.pos(ix, s)])"
NEW = "List.append(&2, U32, acc, [U32.add(kuconv.pos(ix, s), 1)])"

# THE PLANT LIVES THREE DIRECTORIES DEEPER THAN THE PORT's FILE, SO THE
# RELATIVE IMPORTS ARE REPOINTED.  THE REWRITES ARE COUNTED AND MUST ALL
# FIRE, BECAUSE A PLANT THAT DID NOT EVEN COMPILE IS NOT A PLANT.
IMPORTS = [
    ("import ./../uop/ops.bend as O", "import ./../../../tinybendygrad/uop/ops.bend as O"),
    ("import ./../uop/fold.bend as F", "import ./../../../tinybendygrad/uop/fold.bend as F"),
    ("import ./../LAWS/spec.bend as S", "import ./../../../tinybendygrad/LAWS/spec.bend as S"),
    ("import ./../helpers.bend as H", "import ./../../../tinybendygrad/helpers.bend as H"),
    ("import ./cstyle.bend as C", "import ./../../../tinybendygrad/renderer/cstyle.bend as C"),
]

HEADER = ("# kuconv_plant.bend -- GENERATED by .agents/slop/kucvt/mutate.py FROM\n"
          "# tinybendygrad/renderer/kuconv.bend.  DO NOT HAND-EDIT.\n"
          "#\n"
          "# THE PLANT: THE `srcs` RE-INDEX IS OFF BY ONE.  SEE THE GENERATOR's HEADER.\n")


def main() -> int:
    src = PORT.read_text()
    n = src.count(OLD)
    if n != 1:
        print("REFUSED: the edit site occurs %d times (expected exactly 1)" % n)
        return 1
    out = src.replace(OLD, NEW)
    for a, b in IMPORTS:
        if out.count(a) != 1:
            print("REFUSED: the import %r occurs %d times (expected exactly 1)"
                  % (a, out.count(a)))
            return 1
        out = out.replace(a, b)
    PLANT.write_text(HEADER + out)
    print("# wrote %s (%d B)" % (PLANT.name, len(HEADER) + len(out)))
    print("# the mutation: %s  ->  %s" % (OLD, NEW))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
