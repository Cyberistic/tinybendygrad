#!/usr/bin/env python3
"""diff.py -- THE MEASUREMENT DRIVER.

    .venv/bin/python .agents/slop/kucvt/diff.py            # the port's own converter
    .venv/bin/python .agents/slop/kucvt/diff.py --plant    # the plant

WHAT IT DOES, ONE BEND PROCESS AT A TIME
----------------------------------------
FOR EACH KERNEL:

  1. `./bin/bend .agents/slop/kucvt/harness/<name>.bend -o <tmp>.js`   (ONE PROCESS)
  2. `bun <tmp>.js`                                                      (the JS lane)
  3. COMPARE THE C ON STDOUT WITH UPSTREAM's OWN `csrc/<name>.c` **WHOLE FILE**.

**THE ORACLE IS UPSTREAM's OWN FILE.**  NOTHING IS TYPED.

THE ROWS GO TO `.agents/slop/kucvt/<mode>.rows`, ONE ROW PER KERNEL, AND THE
ROW IS THE WHOLE-FILE COMPARISON'S VERDICT PLUS THE BYTE COUNTS -- SO A ROW
THAT SAID "IDENTICAL" WITHOUT THE COUNTS WOULD BE SATISFIED BY A HARNESS THAT
DID NOTHING.

**ONE `bend` PROCESS AT A TIME.  NO BACKGROUND.  NO FAN-OUT.**  THE `--plant`
MODE IS THE SAME DRIVER OVER `harness_plant/`, AND ITS ROWS MUST DIFFER.
"""
import pathlib
import subprocess
import sys
import time

HERE = pathlib.Path(__file__).resolve().parent
CSRC = HERE.parent / "cpuseam" / "csrc"
BEND = HERE.parent.parent.parent / "bin" / "bend"


def run_one(name: str, mode: str) -> tuple:
    src = HERE / mode / f"{name}.bend"
    js = pathlib.Path("/tmp") / f"kucvt_{mode}_{name}.js"
    t0 = time.time()
    r = subprocess.run([str(BEND), str(src), "-o", str(js)],
                       capture_output=True, text=True)
    t1 = time.time()
    if r.returncode != 0:
        return (name, "COMPILE-FAILED", 0, 0, 0.0, r.stdout + r.stderr)
    p = subprocess.run(["bun", str(js)], capture_output=True, text=True)
    t2 = time.time()
    got = p.stdout
    want = (CSRC / f"{name}.c").read_text()
    same = got == want
    verdict = "IDENTICAL" if same else "DIFFERS"
    return (name, verdict, len(got), len(want), t2 - t0, "")


def main() -> int:
    mode = "harness_plant" if "--plant" in sys.argv else "harness"
    names = sorted(p.stem for p in CSRC.glob("*.c"))
    rows = []
    total = 0.0
    for n in names:
        name, verdict, got, want, secs, err = run_one(n, mode)
        total += secs
        rows.append((name, verdict, got, want, secs))
        print("# %-24s %-14s got=%d want=%d  %.2f s" % (name, verdict, got, want, secs))
        if err:
            print(err[:2000])
    out = HERE / ("plant.rows" if mode == "harness_plant" else "measure.rows")
    with out.open("w") as f:
        f.write("# %s.rows -- generated by .agents/slop/kucvt/diff.py\n" % mode)
        f.write("# columns: kernel|verdict|got_bytes|want_bytes|seconds\n")
        for r in rows:
            f.write("|".join(str(x) for x in r) + "\n")
    ident = sum(1 for r in rows if r[1] == "IDENTICAL")
    print("# %s: %d of %d IDENTICAL, total %.2f s" % (mode, ident, len(rows), total))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
