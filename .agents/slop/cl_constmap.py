"""THE HAND MAP for `runtime/ops_cl.bend`'s 103 numeric constant defs.

WHY A FILE AND NOT A FLAG. `.agents/slop/const-audit.py` is a NAME-MATCHING
smoke test, and on this file it is worse than useless in one direction: `OP_*` and
`V_*` are a PORT-INTERNAL tag space with no Python counterpart at all, `cl_err_n`
is a dict LENGTH rather than a dict value, and `CUDA_HOST_REGISTERED` is a code in
one vendor's error enum while `cl_err_code` holds the same idea for another. The
names mean different things on the two sides.

WHAT THIS IS. A hand-built map from every constant NAME to the AUTHORITY that
answers for it, with every value GENERATED BY CALLING CPython:

  * `hdr`   -- `getattr` on `autogen.opencl` / `autogen.cuda` / `autogen.hip`.
  * `src`   -- an int literal CPython's own `ast` extracts from one of the three
               `.py` sources at a NAMED line, optionally selected by position or
               regex. A line carrying two ints must say which one, or this file
               is where an audit invents a bug (see `cu:82`).
  * `call`  -- NOT a value. A constant whose number is a tag in a port-internal
               space, checked as a NAME -> (python line) map instead. Same
               treatment `mt_constmap.py` gives `CALL_*`.
  * `live`  -- measured: a real `mmap.PAGESIZE`, a real `ctypes.sizeof`.
  * `derived` -- computed here from a Python expression that IS the authority.
  * `dead`  -- the def exists and NOTHING reads it.
  * `fix`   -- a fixture parameter, not a port of a Python number.

Every value is produced by RUNNING this file:

    .venv/bin/python .agents/slop/cl_constmap.py [port.bend]
"""
