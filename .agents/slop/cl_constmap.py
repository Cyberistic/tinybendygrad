def bend_lists(path):
  """every `List<&2, U32>` literal in the port, as python lists. A constant's
  authority may be a WHOLE TABLE (cl_err_code, cu_err_code), and those are lists
  in the port and dicts in CPython."""
  txt = Path(path).read_text()
  out = {}
  for m in BEND_LIST.finditer(txt):
    name = m.group(1)
    vals = re.findall(r"-?\d+", m.group(3).replace('"', ' ')) if m.group(2) == "U32" \
      else re.findall(r'"([^"]*)"', m.group(3))
    out[name] = vals if m.group(2) == "U32" else vals
  return out


def bend_list(path, name):
  txt = Path(path).read_text()
  m = re.search(rf"^def {name}\(\) -> List<&2, (?:U32|String)>:\s*((?:\s*\[[^\]]*\])+)\s*$", txt, re.M)
  assert m, f"ops_cl.bend has no one-line `def {name}()` list"
  body = m.group(1)
  return re.findall(r"-?\d+", body) if "U32" in m.group(0) else re.findall(r'"([^"]*)"', body)


def cu32(x):
  """a signed python code as the port's `U32` two's complement. Bend has no
  signed integer, and the port says so at :187-188."""
  return x & 0xFFFFFFFF


