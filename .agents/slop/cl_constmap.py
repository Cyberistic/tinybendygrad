def bend_consts(path):
  out = {}
  for i, line in enumerate(Path(path).read_text().splitlines(), 1):
    m = BEND_CONST.match(line)
    if m: out[m.group(1)] = (i, int(m.group(2)))
  return out


def main():
  port = bend_consts(PORT)
  kinds, wrong, noauth, unmapped, unknown = {}, [], [], [], []
  for name, (ln, val) in sorted(port.items()):
    if name in NO_AUTH:
      kinds.setdefault("no-auth", []).append(name); noauth.append((name, val, ln)); continue
    if name not in MAP:
      unknown.append((name, val, ln)); continue
    kind, fn, why = MAP[name]
    kinds.setdefault(kind, []).append(name)
    if kind in ("dead", "fix", "host"): continue
    if kind == "call":
      try: fn()
      except AssertionError as e: wrong.append((name, val, str(e), ln, why))
      continue
    got = fn()
    if got != val: wrong.append((name, val, got, ln, why))
  for name in MAP:
    if name not in port and name not in TABLES and name != "cl_err_aliases":
      unmapped.append(name)

  # ---- the four whole-table constants ------------------------------------
  tbad = 0
  print("== WHOLE-TABLE CONSTANTS")
  for name, (vendor, fn, why) in TABLES.items():
    want = fn()
    got = bend_list(PORT, name)
    if [str(x) for x in want] != got:
      tbad += 1
      print(f"  !! {name}: {len(got)} cells in the port, {len(want)} from CPython")
      for i, (a, b) in enumerate(zip(got, want)):
        if str(a) != str(b): print(f"       cell {i}: port {a!r}, CPython {b!r}")
      if len(got) != len(want):
        print(f"       length differs; port tail {got[len(want):] or got[-3:]}, "
              f"cpython tail {want[len(got):] or want[-3:]}")
    else:
      print(f"  OK  {name}: {len(want)} cells agree with CPython, cell for cell")

  total = len(port)
  checked = total - len(noauth) - len(unknown) - len(kinds.get("call", [])) - len(kinds.get("host", []))
  print(f"\n{PORT.name}: {total} numeric constant defs")
  print(f"  compared against a CPython authority : {checked}")
  print(f"  tag space, checked as (line,selector) : {len(kinds.get('call', []))}")
  print(f"  HOST-DEPENDENT (no single value)      : {len(kinds.get('host', []))}")
  for n in kinds.get("host", []):
    print(f"    HOST {n}: the authority measures {MAP[n][1]()} on THIS host, and the port's "
          f"{port[n][1]} is the value every platform CUDA runs on answers. Not a wrong constant; "
          f"a U32 literal cannot be host-dependent.")
  print(f"  NO AUTHORITY                          : {len(noauth)}")
  print(f"  WRONG                                 : {len(wrong)}")
  for n, p, g, ln, why in wrong:
    print(f"    WRONG {n}: port {p} at line {ln}, authority {g} -- {why}")
  for n, v, ln in noauth: print(f"    NO-AUTH {n}={v} at line {ln}: {NO_AUTH[n]}")
  for n, v, ln in unknown: print(f"    UNMAPPED {n}={v} at line {ln} -- ADD IT TO THE MAP")
  for n in unmapped: print(f"    MAP-ONLY {n}: in the map, not in the port")
  # ---- the tag spaces' one checkable property: DENSITY -------------------
  for pre in ("OP", "V"):
    tags = sorted(val for k, (_ln, val) in port.items() if k.startswith(pre + "_")
                  and k != "OP_N" and not re.match(r"^OP_(RT_|IDX_|DESC_|KERNARGS_|SIGNAL_SLOT|TAG_)", k))
    want = list(range(len(tags))) if pre == "V" else list(range(len(tags)))
    print(f"  {pre}_* tag values                     : {tags[0]}..{tags[-1]} n={len(tags)} "
          f"DENSE={tags == want}")
    if tags != want: print(f"    !! the {pre}_* tags are NOT 0..n-1")
  # ---- and the one thing the density check cannot see: V_HIP's VALUE ------
  # `vend.name(v, op)` compares `v` against V_CUDA()/V_HIP() and every gate row
  # passes V_CL()/V_CUDA()/V_HIP() as the ARGUMENT, so the constant appears on
  # BOTH sides of its own comparison: V_HIP+1 moves NOTHING (measured by the far
  # sweep). The only property the gate does pin is that the three are DISTINCT,
  # which `V_CL+1` and `V_CUDA+1` both break. So V_HIP's exact value is
  # unconstrained by the port and must be judged as a port-internal tag.
  v = {k: port[k][1] for k in ("V_CL", "V_CUDA", "V_HIP")}
  print(f"  V_* values                            : {v}  DISTINCT={len(set(v.values())) == 3}")
  if len(set(v.values())) != 3: print("    !! two vendors share a tag")
  print(f"  whole-table disagreements             : {tbad}")
  return 1 if (wrong or unknown or unmapped or tbad) else 0


if __name__ == "__main__":
  sys.exit(main())
