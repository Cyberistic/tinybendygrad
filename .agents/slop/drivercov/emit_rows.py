def main():
    out = [f"# generated by .agents/slop/drivercov/emit_rows.py -- {census.stamp()}",
           "# artifact\trole\texecuted_by_corpus\tin_digest\tnote"]
    for path, role, ex, note in ROWS:
        if path.endswith("/**"):
            base = path[:-3]
            members = [m for m in RUNTREE if m == base or m.startswith(base + "/")]
            # NON-VACUOUSLY. The first version wrote
            #   all(f"{base}/{m}" in ENTRIES for m in RUNTREE if m.startswith(base))
            # and `references/bend/bend2/**` came back `yes` -- because its member list is EMPTY
