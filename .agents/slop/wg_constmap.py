#!/usr/bin/env python3
"""THE HAND MAP for `runtime/ops_webgpu.bend`'s 67 numeric constant defs.

WHY A FILE AND NOT A FLAG. `.agents/slop/const-audit.py` matches by NAME, and on
this file the port RENAMES the autogen enum members (`USAGE_MAP_READ` against
`WGPUBufferUsage_MapRead`, `MAP_MAPPED` against `WGPUBufferMapState_Mapped`) and
`CALL_*`/`OBJ_*`/`SYNC_*` are PORT-INTERNAL tag spaces with no Python counterpart
at all. A name-matching audit reaches none of them.

WHAT THIS IS. Every constant NAME mapped to the AUTHORITY that answers for it,
with every value GENERATED BY CALLING CPython:

  * `hdr` -- `getattr` on `tinygrad.runtime.autogen.webgpu`, the generated ctypes
             module. THE authority for 19 of the 67.
  * `src` -- an int literal CPython's own `ast` extracts from `ops_webgpu.py` at
             a NAMED line, selected by position or by a regex. A line carrying
             several ints must say which one.
  * `emit` -- NOT a value. `CALL_*` is a tag space; its authority is the
             NAME -> (python line, symbol) map, checked here and again by
             `wg_emit_map.py`.
  * `live` -- measured on this machine / off a real dict.
  * `dead` -- the def exists and NOTHING reads it.

Run: .venv/bin/python .agents/slop/wg_constmap.py [port.bend]
"""
import ast, importlib.util, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OPS = ROOT / "tinygrad/runtime/ops_webgpu.py"
PORT = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "tinybendygrad/runtime/ops_webgpu.bend"
SRC = OPS.read_text()
SLINES = SRC.splitlines()
TREE = ast.parse(SRC)
BEND_CONST = re.compile(r"^def\s+([A-Za-z_][A-Za-z_0-9]*)\(\)\s*->\s*\w+:\s*(-?\d+)\s*$")
WGPU = None

_IDX = {}


def _ints(n):
  """every int literal SPANNING line n, in SOURCE order, by CPython's AST. A
  number inside a STRING is not a number, so this is the AST and not a regex."""
  if not _IDX:
    out = {}
    for x in ast.walk(TREE):
      if isinstance(x, ast.Constant) and isinstance(x.value, int) and not isinstance(x.value, bool):
        for ln in range(x.lineno, (x.end_lineno or x.lineno) + 1):
          out.setdefault(ln, []).append(x)
    _IDX.update({ln: sorted(v, key=lambda x: (x.lineno, x.col_offset)) for ln, v in out.items()})
  return _IDX.get(n, [])


def src(n, at=None, rx=None):
  if rx is not None:
    m = re.search(rx, SLINES[n - 1])
    assert m, f"ops_webgpu.py:{n} does not match {rx!r}: {SLINES[n - 1].strip()!r}"
    return int(m.group(1))
  vals = [x.value for x in _ints(n)]
  if at is None:
    assert len(vals) == 1, f"ops_webgpu.py:{n} has {vals}, not one int"
    return vals[0]
  return vals[at]


def hdr(name):
  """the authority is an attribute of the REAL generated ctypes module."""
  global WGPU
  if WGPU is None:
    import tinygrad.runtime.autogen.webgpu as m
    WGPU = m
  return getattr(WGPU, name)


def emit(*sites):
  """NOT a value. The authority for a CALL_* tag is that this python line really
  names that wgpu symbol -- the NAME -> meaning map, which is the part that can be
  wrong the way `CLASS_BLACKWELL_COMPUTE_A` was in ops_nv. Several sites are
  accepted because the `synchronous` WRAPPER at :45-50 rebinds six wgpu entry
  points to Python names (`BufferMapAsync` IS `wgpuBufferMapAsync2`), so a tag's
  symbol appears on the wrapper's definition line and its use elsewhere. Both are
  asserted where both exist.
  """
  for n, needle in sites:
    if needle in SLINES[n - 1]: return n
  raise AssertionError(f"no site among {sites} names its symbol: "
                       + "; ".join(f":{n}={SLINES[n - 1].strip()[:60]!r}" for n, _ in sites))


def _wrapper(n):
  """the `synchronous(...)` DECORATOR call inside an assignment, or None.
  `X = synchronous(enum, True)(webgpu.f)` is a Call whose FUNC is a Call whose own
  func is the Name `synchronous`, so looking only at `n.value.func.id` finds
  nothing -- which is how a checker reports an EMPTY list where six wrappers are."""
  if not (isinstance(n, ast.Assign) and isinstance(n.value, ast.Call)): return None
  inner = n.value.func
  if isinstance(inner, ast.Call) and getattr(inner.func, "id", None) == "synchronous":
    return inner
  return None


def sync_ids():
  """the six `synchronous(...)(webgpu.f)` wrapper defs at :45-50, in SOURCE
  ORDER. The port's SYNC_* ids ARE that order, so the authority for
  SYNC_MAP_ASYNC..SYNC_WORK_DONE is the definition order, read off the AST."""
  return [(n.lineno, [t.id for t in n.targets],
           getattr(n.value.args[0], "attr", None))
          for n in TREE.body if (d := _wrapper(n))]


def has_emsg_flags():
  """`synchronous(enum, True)` vs `synchronous(enum)`. The port's SYNC_HAS_EMSG /
  SYNC_NO_EMSG is a two-value tag, and what is checkable is the PATTERN: which of
  the six carry the `True`. Read off the AST's argument count of the decorator."""
  out = []
  for n in TREE.body:
    d = _wrapper(n)
    if d is None: continue
    a = d.args[1] if len(d.args) > 1 else None
    out.append(not (a is None or (isinstance(a, ast.Constant) and a.value is False)))
  return out


