NO_AUTH = {}


def bend_consts(path):
  out = {}
  for i, line in enumerate(Path(path).read_text().splitlines(), 1):
    m = BEND_CONST.match(line)
    if m: out[m.group(1)] = (i, int(m.group(2)))
  return out


def main():
  port = bend_consts(PORT)
  kinds, wrong, noauth, unmapped, unknown = {}, [], [], [], []
  for name, (ln, val) in sorted(port.items()):
    if name in NO_AUTH:
      kinds.setdefault("no-auth", []).append(name); noauth.append((name, val, ln)); continue
    if name not in MAP:
      unknown.append((name, val, ln)); continue
    kind, fn, why = MAP[name]
    kinds.setdefault(kind, []).append(name)
    if kind in ("dead", "fix", "tag"): continue
    got = fn()
    if kind == "both":
      got = got[0]
      if got != hdr("WGPUWaitStatus_Success"):
        wrong.append((name, val, f"{got} vs header {hdr('WGPUWaitStatus_Success')}", ln, why))
      continue
    if kind == "emit":
      try: fn()
      except AssertionError as e: wrong.append((name, val, str(e), ln, why))
      continue
    if got != val: wrong.append((name, val, got, ln, why))
  for name in MAP:
    if name not in port: unmapped.append(name)
  total = len(port)
  checked = total - len(noauth) - len(unknown) - len(kinds.get("emit", [])) - len(kinds.get("tag", []))
  print(f"{PORT.name}: {total} numeric constant defs")
  print(f"  compared against a CPython authority : {checked}")
  print(f"  CALL_* name->(line,symbol) map       : {len(kinds.get('emit', []))}")
  print(f"  tag space (checked for DENSITY below): {len(kinds.get('tag', []))}")
  print(f"  NO AUTHORITY                          : {len(noauth)}")
  print(f"  WRONG                                 : {len(wrong)}")
  for n, p, g, ln, why in wrong:
    print(f"    WRONG {n}: port {p} at line {ln}, authority {g} -- {why}")
  for n, v, ln in noauth: print(f"    NO-AUTH {n}={v} at line {ln}: {NO_AUTH[n]}")
  for n, v, ln in unknown: print(f"    UNMAPPED {n}={v} at line {ln} -- ADD IT TO THE MAP")
  for n in unmapped: print(f"    MAP-ONLY {n}: in the map, not in the port")

  # ---- the tag spaces' one checkable property: DENSITY -------------------
  for pre, excludes in (("OBJ", ()), ("CALL", ()), ("SYNC", ("SYNC_HAS_EMSG", "SYNC_NO_EMSG",
                                                             "SYNC_NONE", "SYNC_ONE", "SYNC_MANY"))):
    vals = sorted(val for k, (_ln, val) in port.items() if k.startswith(pre + "_") and k not in excludes)
    # the six SYNC ids ARE the 1-BASED definition order of the wrappers at :45-50,
    # so SYNC's density is 1..6 and not 0..5. Asserting 0-based would be the
    # AUDIT's own bug, so the expectation is stated per space.
    want = list(range(1, len(vals) + 1)) if pre == "SYNC" else list(range(len(vals)))
    print(f"  {pre}_* tag values                     : {vals[0]}..{vals[-1]} n={len(vals)} "
          f"DENSE={vals == want} (want {'1..n' if pre == 'SYNC' else '0..n-1'})")
    if vals != want: print(f"    !! the {pre}_* tags do not have the required density")

  # ---- the two MEASURED facts behind the SYNC_* ids ----------------------
  ids = sync_ids()
  flags = has_emsg_flags()
  print(f"  MEASURED sync wrapper order           : {[ln for ln, _, _ in ids]}  (expect [45,46,47,48,49,50])")
  print(f"  MEASURED wrapper targets              : {[s for _, _, s in ids]}")
  print(f"  MEASURED has_emsg per wrapper         : {flags}  "
        f"(port claims True for SYNC 1,3,4,5 and False for 2,6)")
  bad = 0
  if [ln for ln, _, _ in ids] != [45, 46, 47, 48, 49, 50]:
    print("    !! the six wrappers are not at :45-50"); bad += 1
  want = [True, False, True, True, True, False]
  if flags != want:
    print(f"    !! the port's SYNC_HAS_EMSG/NO_EMSG pattern is wrong: {flags} != {want}"); bad += 1
  # each SYNC id's SYMBOL is the wrapper's target, and the six targets must be
  # DISTINCT and must be the six wgpu entry points :45-50 really wrap. This is the
  # check that a duplicated or transposed SYNC id cannot pass.
  want_syms = ["wgpuBufferMapAsync2", "wgpuDevicePopErrorScope2", "wgpuDeviceCreateComputePipelineAsync2",
               "wgpuInstanceRequestAdapter2", "wgpuAdapterRequestDevice2", "wgpuQueueOnSubmittedWorkDone2"]
  # The PORT's own claim, id -> the wrapper it is. Hand-written, because the port
  # records only the NUMBER in `Call{CALL_WAIT, SYNC_X}` and nothing anywhere
  # binds that number to a symbol -- which is why the transposition control
  # (SYNC_MAP_ASYNC <-> SYNC_POP_ERROR_SCOPE) is invisible to the gate AND to a
  # density check, and only this map sees it.
  PORT_SYNC = {"SYNC_MAP_ASYNC": "wgpuBufferMapAsync2", "SYNC_POP_ERROR_SCOPE": "wgpuDevicePopErrorScope2",
               "SYNC_CREATE_PIPELINE": "wgpuDeviceCreateComputePipelineAsync2",
               "SYNC_REQUEST_ADAPTER": "wgpuInstanceRequestAdapter2",
               "SYNC_REQUEST_DEVICE": "wgpuAdapterRequestDevice2",
               "SYNC_WORK_DONE": "wgpuQueueOnSubmittedWorkDone2"}
  by_line = {ln: (sym, targets[0]) for ln, targets, sym in ids}
  print(f"  MEASURED wrapper order                 : "
        f"{ {targets[0]: by_line[ln][1] for ln, targets, _ in ids} }")
  print(f"  PORT CLAIMS                            : {PORT_SYNC}")
  for name, sym in sorted(PORT_SYNC.items()):
    # the port's id must be the 1-based index of the wrapper that wraps `sym`
    want_id = next((i for i, (_, _, s) in enumerate(ids, 1) if s == sym), None)
    got_id = port[name][1]
    if got_id != want_id:
      print(f"    WRONG SYNC ID {name}: port {got_id}, authority {want_id} "
            f"(the {want_id}th `synchronous` wrapper, ops_webgpu.py:{45 + want_id - 1}, is {sym})")
      bad += 1
  got_syms = [s for _, _, s in ids]
  if got_syms != want_syms:
    print(f"    !! the six wrappers target {got_syms}"); bad += 1

  # ---- OBJ_*'s ONE real authority: the release order at :132-138 ----------
  rel = [re.search(r"wgpu(\w+)Release", SLINES[i - 1]) for i in range(132, 139)]
  want_obj = ["BindGroupLayout", "PipelineLayout", "BindGroup", "ComputePipeline",
              "CommandEncoder", "ComputePassEncoder", "CommandBuffer"]
  got_obj = [m.group(1) for m in rel if m]
  print(f"  MEASURED release order :132-138        : {got_obj}")
  if got_obj != want_obj:
    print("    !! ops_webgpu.py:132-138 releases in another order than the port assumes")
    bad += 1
  obj_of = {"BindGroupLayout": "OBJ_BIND_GROUP_LAYOUT", "PipelineLayout": "OBJ_PIPELINE_LAYOUT",
            "BindGroup": "OBJ_BIND_GROUP", "ComputePipeline": "OBJ_COMPUTE_PIPELINE",
            "CommandEncoder": "OBJ_COMMAND_ENCODER", "ComputePassEncoder": "OBJ_COMPUTE_PASS",
            "CommandBuffer": "OBJ_COMMAND_BUFFER"}
  vals = [port[obj_of[o]][1] for o in got_obj if o in obj_of]
  print(f"  the OBJ ids in that order              : {vals}")
  if vals != sorted(vals):
    print("    !! the OBJ ids do NOT increase along the Python release order -- "
          "the trace would print the release of one object under another's kind")
    bad += 1
  return 1 if (wrong or unknown or unmapped or bad) else 0


if __name__ == "__main__":
  sys.exit(main())
