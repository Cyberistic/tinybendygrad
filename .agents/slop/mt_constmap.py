"""THE HAND MAP for `runtime/ops_metal.bend`'s 106 numeric constant defs.

WHY THIS IS A FILE AND NOT A FLAG. `.agents/slop/const-audit.py` is a NAME-MATCHING
smoke test and on this file it reaches **0 of 106**: the port RENAMES (`CMD`
TYPE_CONCURRENT` vs the header's `MTLIndirectCommandTypeConcurrentDispatch`) and
several names mean something else on the two sides (`ADDR_SIZE` is `Ops.GETADDR`'s
dtype, not a header field). Its `0 likely-WRONG` is NOT a verdict.

WHAT THIS IS. A hand-built map, `MAP` below, from every port constant NAME to the
authority that answers for it, and every value GENERATED BY CALLING CPython:

  * `src`   -- an int literal CPython `ast`-extracts from `ops_metal.py` at a NAMED
               line, optionally selected by position/regex. A wrong line number is a
               LOUD failure, not a silent pass.
  * `mtl`   -- an attribute of `tinygrad.runtime.autogen.metal`, read by `getattr`.
  * `live`  -- a value measured by OPENING a real `MetalDevice` / running a real
               kernel / asking a real dtype. Never transcribed.
  * `sel`   -- `(HANDLES + SELECTORS).index(name)`, called in CPython.
  * `call`  -- NOT a value. `ops_metal.py`'s numbers are a port-internal tag space, so
               the audit instead checks the NAME -> (source line, selector) map that
               gives each tag its meaning, plus the tag set's density.
  * `dead`  -- no authority: the def exists and NOTHING reads it.
  * `fix`   -- a fixture parameter, not a port of a Python number.

EVERY value on the right-hand side is produced by running this file. Run it with
`.venv/bin/python` (constraint at bend2-constraints.md line 1733: NOT `python3`).

  usage: .venv/bin/python .agents/slop/mt_constmap.py [port.bend]
"""
