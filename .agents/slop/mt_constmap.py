def seam(key):
  """the REAL `MTLCodeGenServiceBuildRequest`, run. Imported from the probe rather
  than reimplemented here, because two implementations of "what MTLCompiler
  answered" is the setup that produced `nv_query_litter`."""
  global SEAM
  if SEAM is None:
    import importlib.util
    spec = importlib.util.spec_from_file_location("mt_seam_rows", Path(__file__).with_name("mt_seam_rows.py"))
    m = importlib.util.module_from_spec(spec)
    import io, contextlib
    with contextlib.redirect_stdout(io.StringIO()):
      spec.loader.exec_module(m)
    SEAM = {}
    with contextlib.redirect_stdout(io.StringIO()):
      import sys as _s
      buf = io.StringIO()
      with contextlib.redirect_stdout(buf):
        m.main()
      for line in buf.getvalue().splitlines():
        if "=" in line:
          k, v = line.split("=", 1)
          SEAM[k] = int(v) if re.fullmatch(r"-?\d+", v) else v
  return SEAM[key]


def live(key):
  global LIVE
  if LIVE is None: LIVE = _live()
  return LIVE[key]


