def emit_rows():
  """`name=value`, one per constant with a NUMERIC authority -- the oracle half of the
  gate's `t_const` section. Every value below is computed here, never transcribed."""
  out = {}
  for name, (kind, fn, _why) in MAP.items():
    if kind == "call" or name not in ROW: continue
    out[ROW[name]] = fn()
  for name, val in (("RUN_COUNT_ALL", 0),):  # the dead one: :166's `run(h, 0, n, True)`
    if name in ROW: out[ROW[name]] = src(166, rx=r"run\(h, (\d+), n, True\)")
  return out


GATEROW = re.compile(r'^\s*(?:urow|lrow|row|srow)\("([a-z0-9_]+)"')


def gate_rows(path):
  """EVERY row name the port's gate prints, read out of the .bend. All four
  printers, not just the `mt_c_` one, because six constants print under the seam's
  own names -- a row NAME is a pairing, and the pairing is what this checks."""
  return {m.group(1) for m in (GATEROW.match(l) for l in Path(path).read_text().splitlines()) if m}


# --------------------------------------------------------------------------- main
def bend_consts(path):
  out = {}
  for i, line in enumerate(Path(path).read_text().splitlines(), 1):
    m = BEND_CONST.match(line)
    if m: out[m.group(1)] = (i, int(m.group(2)))
  return out


def main():
  if "--rows" in sys.argv:
    argv = [a for a in sys.argv if not a.startswith("--")]
    for k, v in sorted(emit_rows().items()): print(f"{k}={v}")
    # A row in the gate with no oracle row is a row nothing can check, and an oracle
    # row with no gate row is coverage that does not exist. Both are loud.
    g = gate_rows(argv[1] if len(argv) > 1 else PORT)
    o = set(emit_rows())
    for k in sorted(set(ROW.values()) - o - set()): print(f"  !! GATE-ONLY {k}: no authority")
    for k in sorted(set(ROW.values()) - g): print(f"  !! ORACLE-ONLY {k}: not printed by the gate")
    return 1 if (set(ROW.values()) - o or set(ROW.values()) - g) else 0
  port = bend_consts(PORT)
  kinds, wrong, noauth, unmapped, unknown = {}, [], [], [], []
  for name, (ln, val) in sorted(port.items()):
    if name in NO_AUTH:
      kinds.setdefault("no-auth", []).append(name); noauth.append((name, val, ln)); continue
    if name not in MAP:
      unknown.append((name, val, ln)); continue
    kind, fn, why = MAP[name]
    kinds.setdefault(kind, []).append(name)
    if kind in ("dead", "fix"): continue
    got = fn()
    if kind == "call":
      continue  # the tag NUMBER has no authority; the (line, selector) map was checked
    if got != val: wrong.append((name, val, got, ln, why))
  for name in MAP:
    if name not in port: unmapped.append(name)

  total = len(port)
  checked = total - len(noauth) - len(unknown) - len(kinds.get("call", []))
  print(f"{PORT.name}: {total} numeric constant defs")
  print(f"  compared against a CPython authority : {checked}")
  print(f"  CALL_* name->(line,selector) map      : {len(kinds.get('call', []))}")
  print(f"  NO AUTHORITY (dead / fixture)         : {len(noauth)}")
  print(f"  WRONG                                 : {len(wrong)}")
  for n, p, g, ln, why in wrong:
    print(f"    WRONG {n}: port {p} at line {ln}, authority {g} -- {why}")
  for n, v, ln in noauth: print(f"    NO-AUTH {n}={v} at line {ln}: {NO_AUTH[n]}")
  for n, v, ln in unknown: print(f"    UNMAPPED {n}={v} at line {ln} -- ADD IT TO THE MAP")
  for n in unmapped: print(f"    MAP-ONLY {n}: in the map, not in the port")
  # the CALL_* tag space: the one property that IS checkable without a Python value.
  tags = sorted(port[n][1] for n in kinds.get("call", []) if n != "CALL_NKIND")
  dense = tags == list(range(len(tags)))
  print(f"  CALL_* tag values                     : {tags[0]}..{tags[-1]} n={len(tags)} DENSE={dense}")
  if not dense:
    print("    !! the CALL_* tags are NOT 0..n-1 -- two kinds share a tag or one is missing")
  return 1 if (wrong or unknown or unmapped or not dense) else 0


if __name__ == "__main__":
  sys.exit(main())
