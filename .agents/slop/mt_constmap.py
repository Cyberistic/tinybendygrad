# --------------------------------------------------------------------------- src
def _line(n):
  """the real source line n of ops_metal.py, 1-indexed."""
  return SRC[n - 1]


def _ints(n):
  """every int literal CPython's parser finds on line n. A line with a number in a
  STRING is not a number, so this is the AST and not a regex."""
  return [x.value for x in ast.walk(ast.parse(_line(n).strip())) if isinstance(x, ast.Constant)
          and isinstance(x.value, int) and not isinstance(x.value, bool)]


def src(n, at=None, rx=None):
  """the authority is an int literal in ops_metal.py line n.
  at  -- the `at`-th int on the line in SOURCE order (assert several, so a line that
         moved under us is loud).
  rx  -- a regex with ONE capture group around the number, matched against the REAL
         line. Precise and order-free, which `at` is not: line 132 is
         `...[zero // 8 + 3:]` and picking by position silently swaps the two."""
  if rx is not None:
    m = re.search(rx, _line(n))
    assert m, f"ops_metal.py:{n} does not match {rx!r}: {_line(n).strip()!r}"
    return int(ast.literal_eval(m.group(1)))
  vs = sorted((x for x in ast.walk(ast.parse(_line(n).strip()))
               if isinstance(x, ast.Constant) and isinstance(x.value, int) and not isinstance(x.value, bool)),
              key=lambda x: x.col_offset)
  vals = [x.value for x in vs]
  if at is None:
    assert len(vals) == 1, f"ops_metal.py:{n} has {vals}, not one int"
    return vals[0]
  return vals[at]


def _calls(n):
  """every Call node CPython's parser finds on line n, paired with its callee name."""
  out = []
  for x in ast.walk(ast.parse(_line(n).strip())):
    if isinstance(x, ast.Call):
      f = x.func
      out.append((getattr(f, "attr", getattr(f, "id", None)), x))
  return out


def carg(n, callee, k):
  """the `k`-th positional argument of the call to `callee` on line n, when it is an
  int literal. The AST, not a regex: line 257 is
  `..._options(desc, max(len(cmds), 1), 0)` and BOTH ints are on the line, so a
  positional regex reads the wrong one -- which is how an audit invents a bug."""
  hits = [c for name, c in _calls(n) if name == callee]
  assert len(hits) == 1, f"ops_metal.py:{n}: {len(hits)} calls to {callee}"
  a = hits[0].args[k]
  assert isinstance(a, ast.Constant) and isinstance(a.value, int), f"arg {k} of {callee} is not an int"
  return a.value


def arr_index(n, needle):
  """the index of the element mentioning `needle` in the ONE list literal on line n.
  `:266` writes `[icb.value, *[c.value for c in commands], *[...for p in pipes]]`,
  and the ICB's word index is a POSITION in that list, not a number printed
  anywhere -- so it has to be asked of the AST."""
  lists = [x for x in ast.walk(ast.parse(_line(n).strip())) if isinstance(x, ast.List)]
  assert len(lists) == 1, f"ops_metal.py:{n}: {len(lists)} list literals"
  for i, el in enumerate(lists[0].elts):
    if needle in ast.dump(el): return i
  raise AssertionError(f"ops_metal.py:{n}: no element mentions {needle}")


def srcslice(n, which):
  """a list-index pair `a:b` on line n. `which` is 'lo' or 'hi'; the authority for
  the INDEX of the last slot written is `hi - 1`, so `which` also takes 'last'."""
  m = re.search(r"\[(\d+):(\d+)\]", _line(n))
  assert m, f"ops_metal.py:{n} has no [a:b] slice"
  return {"lo": int(m.group(1)), "hi": int(m.group(2)), "last": int(m.group(2)) - 1}[which]


def call(n, needle):
  """NOT a value. The authority for a CALL_* tag is that ops_metal.py line n really
  carries this selector -- the NAME -> meaning map, which is the part that can be
  wrong the way `CLASS_BLACKWELL_COMPUTE_A` was. Returns the line number."""
  assert needle in _line(n), f"ops_metal.py:{n} does not mention {needle!r}: {_line(n).strip()!r}"
  return n


def mtl(name):
  import tinygrad.runtime.autogen.metal as m
  return getattr(m, name)


def sel(name):
  import tinygrad.runtime.ops_metal as om
  return (om.HANDLES + om.SELECTORS).index(name)


def magic(word):
  """`ret[:4] == b"MTLB"` is a BYTES compare; the port holds it as a u32 word, so the
  authority is that word read little-endian -- the host's byte order."""
  assert struct.pack("<I", int.from_bytes(word, "little")) == word
  return int.from_bytes(word, "little")


# --------------------------------------------------------------------------- live
def _live():
  """ONE real MetalDevice and ONE real kernel launch, measured. Everything under
  `live` comes out of here, so there is no hand-typed expectation anywhere."""
  import tinygrad.runtime.ops_metal as om
  from tinygrad.runtime.autogen import metal
  d = om.MetalDevice()
  out = {}

  # :213 check_family, verbatim, on the real device.
  ns = d.sysdevice
  def check_family(f):
    return next(filter(ns.supportsFamily, reversed([v for v, nm in metal.enum_MTLGPUFamily.items() if f in nm])), 0)
  out["fam_apple"] = check_family("Apple")
  out["fam_mac"] = check_family("Mac")
  out["fam_chosen"] = check_family("Apple") or check_family("Mac")
  out["arch"] = metal.enum_MTLGPUFamily[out["fam_chosen"]][12:]

  # :224-226 `sels`, read off the real Buffer.
  out["sels_len"] = d.sels.size
  out["sels_bytes"] = d.sels.nbytes
  out["sels_itemsize"] = d.sels.dtype.itemsize

  # :89 MSGSEND, the real dict: its LENGTH and the position of each key.
  out["msgsend_n"] = len(om.MSGSEND)
  out["msgsend_keys"] = [("None" if k is None else getattr(k, "__name__", str(k))) for k in om.MSGSEND]
  out["msgsend_dtype"] = next(getattr(k, "__name__", str(k)) for k in om.MSGSEND if k is not None)

  # :111 `bufs[i].getaddr(self.devs)` -- the dtype the ADDRESS word carries.
  from tinygrad.uop.ops import UOp, Ops
  out["getaddr_itemsize"] = UOp(Ops.GETADDR).dtype.itemsize

  # :116 `dims`, on a REAL kernel through the REAL MetalQueue.exec, and the mask
  # that is `(1 << len(dims)) - 1`.
  rec = {}
  orig = om.MetalQueue.exec
  def spy(self, call, prg):
    rec.setdefault("dims", []).append((*prg.arg.global_size, *prg.arg.local_size))
    rec.setdefault("nglob", []).append(len(prg.arg.globals))
    return orig(self, call, prg)
  om.MetalQueue.exec = spy
  try:
    from tinygrad import Tensor, Device
    Device["METAL"]
    a = Tensor.empty(64, 16, device="METAL").realize()
    (a @ a.T).realize()
  finally:
    om.MetalQueue.exec = orig
  out["dims"] = rec["dims"][0]
  out["dim_words"] = len(rec["dims"][0])
  out["all_syms"] = (1 << len(rec["dims"][0])) - 1

  # :216-220 pm_bufferize: the THREE rules, in source order.
  n = 0
  for node in ast.walk(TREE):
    if isinstance(node, ast.Attribute) and node.attr == "pm_bufferize":
      for sub in ast.walk(node):
        if isinstance(sub, ast.List): n = max(n, len(sub.elts))
  out["pmb_rules"] = n
  return out


