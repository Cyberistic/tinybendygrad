#!/usr/bin/env python3
"""train.py -- TRAIN THE MODEL ON CPYTHON, ONCE, AND SAVE THE WEIGHTS.

    .venv/bin/python .agents/slop/mnist/train.py

WHY CPYTHON AND NOT THE BEND DEVICE. The Bend device is an INTERPRETER: the
measured cost of one forward pass is minutes. A training epoch is 60000/BS
forward passes plus two backward passes each. ⇒ **THE BEND DEVICE IS THE
EVALUATION DEVICE, NOT THE TRAINING DEVICE**, and the weights it is evaluated
with are produced here, by upstream tinygrad's own `nn.optim.Adam`, on
upstream's own `CPU` renderer. The brief's rule 1 holds: the port's numbers
are compared against CPython's numbers, and CPython's numbers are computed by
calling upstream's code.

THE OUTPUT IS A `.npz` OF NUMPY ARRAYS plus a `.rows` receipt. Nothing is
transcribed: the weights come out of the tensors upstream's optimizer wrote.
"""
import pathlib
import sys
import time

import numpy as np

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from tinygrad import Tensor, Context, nn  # noqa: E402
from tinygrad.nn.state import get_parameters, get_state_dict  # noqa: E402

from harness import mnist_npy  # noqa: E402
from model import Model, save_weights, n_params, FLAT, C1, C2  # noqa: E402

EPOCHS = int(sys.argv[1]) if len(sys.argv) > 1 else 8
BS = 64
NTRAIN = 20000
LR = 0.002


def main() -> int:
    X, y = mnist_npy("train", NTRAIN)
    print(f"# train images {X.shape} labels {y.shape}", flush=True)

    with Context(DEV="CPU", TRAINING=1):
        model = Model()
        params = get_parameters(model)
        opt = nn.optim.Adam(params, lr=LR)
        print(f"# parameters: {n_params(model)}", flush=True)

        Xt = Tensor(X.astype(np.float32) / 255.0)
        yt = Tensor(y.astype(np.int32))
        for ep in range(EPOCHS):
            t0 = time.perf_counter()
            tot, seen = 0.0, 0
            for i in range(0, NTRAIN, BS):
                xb, yb = Xt[i:i + BS], yt[i:i + BS]
                loss = model(xb).sparse_categorical_crossentropy(yb)
                opt.zero_grad()
                loss.backward()
                opt.step()
                tot += float(loss.item()) * xb.shape[0]
                seen += xb.shape[0]
            print(f"# epoch {ep} loss {tot / seen:.4f} {time.perf_counter() - t0:.1f}s", flush=True)

        save_weights(model, HERE / "weights.npz")
        # the training loss, as a receipt
        with np.load(HERE / "weights.npz") as z:
            keys = sorted(z.files)
            rows = [f"param {k} shape={z[k].shape} dtype={z[k].dtype} nbytes={z[k].nbytes} "
                    f"sha256={__import__('hashlib').sha256(z[k].tobytes()).hexdigest()}" for k in keys]
        (HERE / "weights.rows").write_text(
            "# weights.rows -- generated by .agents/slop/mnist/train.py\n"
            f"# model: conv1(1,{C1},3,p1) conv2({C1},{C2},3,p1) fc({FLAT},10)\n"
            f"# params: {n_params(model)}\n" + "\n".join(rows) + "\n"
        )
    print(f"# saved {HERE / 'weights.npz'}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
