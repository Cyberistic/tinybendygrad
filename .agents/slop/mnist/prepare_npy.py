#!/usr/bin/env python3
"""prepare_npy.py -- HOST-SIDE DATA PREPARATION. NOT THE PORT.

    .venv/bin/python .agents/slop/mnist/prepare_npy.py

WHAT IT DOES. It downloads nothing (the four `.gz` files must already be beside
this script, in `data/`) and it produces four `.npy` files: the MNIST payload
that upstream's `tinygrad/nn/datasets.py` would have produced, in the shape the
port's `.npy` device path reads.

WHY IT IS HOST-SIDE. `tinygrad/nn/datasets.py:6` is
`Tensor.from_url(base_url+file, gunzip=True)` -- a socket, a TLS handshake, a
content-length check and a gzip stream. `tinybendygrad/nn/datasets.bend` records
that as WALL 1. Preparing the bytes on the host is DATA PREPARATION, not the
port: the bytes are the SAME bytes upstream would have seen, and the row
arithmetic the port does downstream (the reshape to (-1,1,28,28) and the
784-wide row) is checked against them.

THE IDX SKIPS ARE UPSTREAM'S, NOT OURS. `datasets.py:7` slices the image file
at `0x10` and the label file at `8`, and reshapes the images to `(-1,1,28,28)`.
The header bytes are: images 16 (magic 4 + dims 3*4 + rows 4 + cols 4) and
labels 8 (magic 4 + dims 2*4). So the skip is the header, and the row width is
784 = 28*28.

THE OUTPUT IS CHECKED, NOT ASSUMED. Every array's shape, dtype and C-contiguity
are asserted here, and `npy_facts.rows` records what was written so the port's
own `.npy` path can be gated against it.
"""
import gzip
import hashlib
import struct
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
DATA = HERE / "data"

# the four files, in upstream's own order: X_train, y_train, X_test, y_test.
# `datasets.py:7` -- the four `_mnist` calls, in that order, and the tuple's
# order IS the contract.
FILES = [
    ("train-images-idx3-ubyte.gz", "mnist_train_images.npy", 16, (1, 28, 28)),
    ("train-labels-idx1-ubyte.gz", "mnist_train_labels.npy", 8, None),
    ("t10k-images-idx3-ubyte.gz", "mnist_test_images.npy", 16, (1, 28, 28)),
    ("t10k-labels-idx1-ubyte.gz", "mnist_test_labels.npy", 8, None),
]


def read_idx(gz_path: Path, skip: int) -> bytes:
    with gzip.open(gz_path, "rb") as f:
        raw = f.read()
    return raw[skip:]


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main() -> int:
    rows = []
    for gz_name, out_name, skip, shape in FILES:
        gz = DATA / gz_name
        if not gz.exists():
            print(f"MISSING {gz}", file=sys.stderr)
            return 2
        payload = read_idx(gz, skip)
        nbytes = len(payload)
        if shape is None:
            arr = np.frombuffer(payload, dtype=np.uint8)
            # upstream slices the label file and does NOT reshape it: `datasets.py:7`
            # returns `_mnist("train-labels-idx1-ubyte.gz")[8:]` -- flat.
            assert arr.ndim == 1, arr.ndim
        else:
            row = shape[1] * shape[2]
            assert nbytes % row == 0, f"{gz_name}: {nbytes} is not a multiple of {row}"
            arr = np.frombuffer(payload, dtype=np.uint8).reshape(-1, *shape)
        assert arr.flags["C_CONTIGUOUS"], out_name
        out = DATA / out_name
        np.save(out, arr, allow_pickle=False)
        rows.append(
            f"{out_name} shape={arr.shape} dtype={arr.dtype} nbytes={nbytes} "
            f"sha256={sha256(out)}"
        )
        print(f"{out_name} shape={arr.shape} dtype={arr.dtype} nbytes={nbytes}")

    # the facts the port's own .npy path is gated against.
    (HERE / "npy_facts.rows").write_text(
        "# npy_facts.rows -- generated by .agents/slop/mnist/prepare_npy.py\n"
        "# columns: name shape dtype nbytes sha256\n" + "\n".join(rows) + "\n"
    )
    # the source archives' digests, so a reader can tell WHICH mirror was used.
    (HERE / "source_digests.rows").write_text(
        "# source_digests.rows -- generated by .agents/slop/mnist/prepare_npy.py\n"
        "# columns: name bytes sha256\n"
        + "\n".join(
            f"{p.name} {p.stat().st_size} {sha256(p)}"
            for p in sorted(DATA.glob("*.gz"))
        )
        + "\n"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
