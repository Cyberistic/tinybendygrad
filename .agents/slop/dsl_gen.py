def main():
  # Bend has NO f-string interpolation -- a probe measured that `f"..."` in a
  # `do` block is a parse error -- and every row name here is already fully
  # interpolated by THIS file's own f-strings, so the leftover `f"` prefix is
  # stripped in one place rather than chased row by row.
  # `f"` must be preceded by `(` or a space: a bare replace also eats the `f` of
  # every identifier that ENDS in f followed by a quote -- `alias_null_off"` came
  # out as `alias_null_of"`, which is a wrong row name and not a parse error.
  body = MARK + "\n" + re.sub(r'(?<=[( ])f"', '"', gen())
  if "--check" in sys.argv:
    print(body)
    return
  text = PORT.read_text()
  i = text.find(MARK)
  if i >= 0:
    text = text[:i]
  # t_names / t_names_rev from the earlier hand-written block are superseded
  for d in ("t_names", "t_names_rev"):
    a = text.find(f"def {d}() -> IO(Unit):")
    if a >= 0:
      b = a
      while b < len(text) and not text[b].startswith("def ") and not text[b].startswith("# ==="):
        b += 1
      text = text[:a] + text[b:]
  MAIN = '''def main() -> IO(Unit):
  do IO<Unit>:
    a : Unit <- g_tables()
    b : Unit <- g_const()
    c : Unit <- g_get()
    d : Unit <- g_fmt()
    e : Unit <- g_mod()
    f : Unit <- g_bf()
    +g : Unit <- g_enc()
    h : Unit <- g_lit()
    +i : Unit <- g_inst()
    +j : Unit <- g_ops()
    +k : Unit <- g_vs()
    IO.print("dsl-done=1")
'''
  a = text.find("def main() -> IO(Unit):")
  if a >= 0:
    text = text[:a]
  PORT.write_text(text.rstrip() + "\n\n" + FIXTURES.rstrip() + "\n\n" + body + "\n" + MAIN)
  print(f"wrote {PORT.relative_to(ROOT)}")


main()