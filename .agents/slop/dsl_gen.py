#!/usr/bin/env python3
"""GENERATE the gate rows of `renderer/amd/dsl.bend` and APPEND them.

WHY A GENERATOR. The oracle names every row after the CPython expression that
produced it (`names_fwd_102`, `bfset_3_0_3735928559_-1`), so a port row that is
hand-typed with a different name is a row the harness cannot pair -- and a row
the harness cannot pair is a row that never ran. Generating both sides' NAMES
from one spec is what keeps the diff honest, and it is the same discipline as
".agents/slop/mt_constmap.py", which is a generator too.

WHAT IT GENERATES, IN ORDER.

  T  the four tables, both directions, plus each table's length
  C  the register constants and the space boundaries
  R  `Reg.__getitem__` -- index, slice, and both refusals
  F  `Reg.fmt` -- every arm, at sz 1 and sz>1, upper and not, with modifiers
  M  the modifier flags and `__neg__`/`__abs__`/`.h`/`.l`
  B  `BitField` masks and `set`, with both refusals
  E  the five field classes' `encode`, one negative per positive
  N  `_needs_literal`
  I  the `Inst` field order, `_base_size`, and the raw-word walk
  O  `op_bits` / `op_regs` / `canonical_*` / `num_srcs`
  V  `_variant_suffix`

    usage: .venv/bin/python .agents/slop/dsl_gen.py [--check]
"""
