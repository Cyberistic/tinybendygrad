  L('    row("alias_dpp_dpp16", U32.is_eq(DPP_OFF(), DPP16_OFF()))')
  L('    row("alias_vcc_pair", U32.is_eq(VCC_OFF(), VCC_LO()))')
  L('    row("alias_exec_pair", U32.is_eq(EXEC_OFF(), EXEC_LO()))')
