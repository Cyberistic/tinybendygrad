def g(sec, out):
  L = out.append
  L(f"\n# --- {sec} " + "-" * max(0, 66 - len(sec)))
  return L


def gen():
  o = []
  L = o.append

  # ---------------------------------------------------------------- T
  g("T  THE FOUR TABLES, BOTH DIRECTIONS", o)
  L('def g_tables() -> IO(Unit):\n  do IO<Unit>:')
  L('    srow("names_count", nat_text(reg_names_n()))')
  L('    srow("names_rev_count", nat_text(reg_names_n()))')
