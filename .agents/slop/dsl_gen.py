  L('    srow("raw_vop2_fnolit", rws(raw_walk(VOP2_FNOLIT())))')
  L('    srow("raw_vop2_int65", rws(raw_walk(VOP2_INT65())))')
  L('    srow("raw_vop2_intn17", rws(raw_walk(VOP2_INTN17())))')
  L('    srow("raw_vop2_big2", rws(raw_walk(VOP2_BIG2())))')
  L('    srow("raw_vop2_lit", rws(raw_walk(VOP2_LIT())))')
  L('    srow("raw_vop2_sdwa", rws(raw_walk(VOP2_SDWA())))')
  L('    srow("raw_vop2_dpp", rws(raw_walk(VOP2_DPP())))')
  L('    srow("raw_vop2_big", rws(raw_walk(VOP2_BIG())))')
  L('    srow("raw_f32i", rws(raw_walk(F32_VALS())))')
  L('    srow("raw_f16i", rws(raw_walk(F16_VALS())))')
  L('    srow("raw_f64i", rws(raw_walk(F64_VALS())))')
  L('    srow("raw_f40i", rws(raw_walk(F40_VALS())))')
  L('    srow("raw_f8i", rws(raw_walk(F8_VALS())))')
  # THE EXEMPTION SETS, one row per boundary and one row just outside it. M44
  # and M45 were BLIND because nothing read `no_resize` / `exempt_width` at all;
  # a `0` from a mutation is a request for a fixture, not a coverage claim.
  for off in [105, 106, 107, 124, 125, 126, 127, 128, 239, 240, 248, 249, 254, 255, 256]:
    L(f'    row(f"noresize_{off}", no_resize({off}))')
    L(f'    row(f"exemptw_{off}", exempt_width({off}))')
  # `mod_merge` with the `or 0` guard and without it: the guard is what makes a
  # ZERO accumulator leave the caller's value alone (:322).
  for mg, mh, mbits in [(0, "False{}", 0), (0, "True{}", 0), (0, "False{}", 1),
                        (0, "True{}", 1), (2, "True{}", 0), (2, "True{}", 1), (6, "True{}", 1)]:
    L(f'    urow(f"modmerge_{mg}_{int(mh == chr(84) + chr(114) + chr(117) + chr(101))}_{mbits}", mod_merge({mg}, {mh}, {mbits}))')
  # `src_bit` -- the four register->bit bindings of dsl.py:314/:320. A count of
  # four would not tell you WHICH bit, so each is one row.
