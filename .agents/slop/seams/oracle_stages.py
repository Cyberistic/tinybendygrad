#!/usr/bin/env python3
"""oracle_stages.py -- CPython's OWN device, stage by stage. THE ORACLE.

    .venv/bin/python .agents/slop/seams/oracle_stages.py CPU

WHAT IT WRITES: `.agents/slop/seams/expected.rows` -- the stage-by-stage tensors
of the MNIST forward pass, on CPython's own `CPU` device, with the same weights
`.agents/slop/mnist/weights.npz` holds and the same input image
`.agents/slop/seams/img0.u8`.

THE POINT: the port's kernel must be compared against CPython's OWN device at
EVERY STAGE, not against a hand-typed number. The stages are

    conv1   (1,4,28,28)   relu1   (1,4,28,28)   pool1 (1,4,14,14)
    conv2   (1,8,14,14)   relu2   (1,8,14,14)   pool2 (1,8,7,7)
    flat    (1,392)       logits  (1,10)

and every tensor is written CHANNEL-MAJOR (o, y, x), which is the order the port's
kernel walks it, and each stage carries its own sha256 so a reader can see WHICH
bytes were compared.

ONE DEVICE AT A TIME: the device is an argument and the script runs one lane.
"""
import hashlib
import pathlib
import sys

import numpy as np

HERE = pathlib.Path(__file__).resolve().parent
MNIST = HERE.parent / "mnist"
sys.path.insert(0, str(MNIST))

from tinygrad import Tensor, Context  # noqa: E402
from tinygrad.nn.state import load_state_dict  # noqa: E402

from model import Model, load_weights  # noqa: E402

WEIGHTS = MNIST / "weights.npz"


def main() -> int:
    device = sys.argv[1] if len(sys.argv) > 1 else "CPU"

    img = np.frombuffer((HERE / "img0.u8").read_bytes(), dtype=np.uint8).reshape(28, 28)
    x_host = (img.astype(np.float32) / 255.0).reshape(1, 1, 28, 28)

    with Context(DEV=device):
        m = Model()
    load_weights(m, WEIGHTS)

    with Context(DEV=device):
        x = Tensor(x_host).realize()
        c1 = m.conv1(x).realize()
        r1 = c1.relu().realize()
        p1 = r1.max_pool2d(2).realize()
        c2 = m.conv2(p1).realize()
        r2 = c2.relu().realize()
        p2 = r2.max_pool2d(2).realize()
        fl = p2.flatten(1).realize()
        lg = m.fc(fl).realize()

    stages = [
        ("conv1", c1.numpy()),
        ("relu1", r1.numpy()),
        ("pool1", p1.numpy()),
        ("conv2", c2.numpy()),
        ("relu2", r2.numpy()),
        ("pool2", p2.numpy()),
        ("flat", fl.numpy()),
        ("logits", lg.numpy()),
    ]

    lines = [
        "# expected.rows -- generated by .agents/slop/seams/oracle_stages.py",
        f"# device={device} weights=.agents/slop/mnist/weights.npz image=.agents/slop/seams/img0.u8",
        "# columns: stage shape count sha256 f32_bits_be_hex",
        "# the hex is each float32's IEEE-754 bit pattern as a BIG-ENDIAN u32 hex,",
        "# 8 chars, so the port's printer and this one can be compared byte for byte.",
    ]
    for name, arr in stages:
        flat = arr.reshape(-1).astype(np.float32)
        b = flat.tobytes(order="C")
        bits = flat.view(np.uint32)
        hexs = "".join(f"{int(v):08x}" for v in bits)
        lines.append(f"{name} {'x'.join(str(d) for d in arr.shape)} {flat.size} "
                     f"{hashlib.sha256(b).hexdigest()} {hexs}")
    (HERE / "expected.rows").write_text("\n".join(lines) + "\n")

    print(f"# device={device}")
    for name, arr in stages:
        print(f"# {name} shape={arr.shape} min={arr.min():.6f} max={arr.max():.6f}")
    lg = stages[-1][1].reshape(-1)
    print("# logits " + " ".join(f"{v:.6f}" for v in lg))
    print(f"# argmax {int(lg.argmax())}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
