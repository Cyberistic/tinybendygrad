#!/usr/bin/env python3
"""mk_inputs.py -- THE PORT's INPUTS, prepared on the host, in the port's own reading format.

    .venv/bin/python .agents/slop/seams/mk_inputs.py

WHAT IT WRITES (all under `.agents/slop/seams/`):

  weights.f32   the trained parameters, float32 LITTLE-ENDIAN, concatenated in a
                DETERMINISTIC order (the state-dict keys, sorted). 4266 floats.
  img0.u8       ONE test image, 784 uint8 bytes (28x28), row-major.
  inputs.rows   the MANIFEST: key, shape, byte offset, element count, sha256 of
                the slice. THE ORACLE FOR THE PORT's READ.

WHY THE HOST PREPARES THE BYTES. The port's `Tensor` is a UOP SLOT IN AN ARENA,
NOT A BUFFER (`tinybendygrad/nn/mnist_cnn.bend`'s header, wall W2), so the port
cannot own a tensor's storage yet. The bytes are the DATA; the port's arithmetic
over them is the port's. Nothing here is an EXPECTATION: every number is read
out of the file the training wrote (`.agents/slop/mnist/weights.npz`).
"""
import hashlib
import pathlib
import struct
import sys

import numpy as np

HERE = pathlib.Path(__file__).resolve().parent
MNIST = HERE.parent / "mnist"


def main() -> int:
    sys.path.insert(0, str(MNIST))
    from tinygrad import Tensor, nn  # noqa: E402
    from tinygrad.nn.state import get_state_dict  # noqa: E402

    # the model, built by upstream tinygrad's own classes, so the parameter
    # names and shapes are upstream's and not ours.
    import model as M  # noqa: E402
    model = M.Model()

    # THE TRAINED PARAMETERS, NOT A FRESH INITIALISATION. `M.Model()` allocates
    # RANDOM weights (upstream's own `nn.Conv2d`/`nn.Linear` init), so a state
    # dict read straight off a fresh model is a DIFFERENT MODEL from the one
    # the oracle runs -- and the two would agree on shapes while disagreeing on
    # every number. `load_weights` reads the file the training wrote
    # (`.agents/slop/mnist/weights.npz`), and CPython's oracle
    # (`oracle_stages.py`) loads the SAME file, so the two lanes run the SAME
    # model and not merely the same architecture.
    M.load_weights(model, MNIST / "weights.npz")

    sd = get_state_dict(model)
    keys = sorted(sd.keys())

    chunks, rows, off = [], [], 0
    for k in keys:
        v = sd[k].numpy()
        b = v.astype(np.float32).tobytes(order="C")
        chunks.append(b)
        rows.append((k, tuple(int(d) for d in v.shape), off, v.size, hashlib.sha256(b).hexdigest()))
        off += len(b)

    blob = b"".join(chunks)
    (HERE / "weights.f32").write_bytes(blob)

    X = np.load(MNIST / "data" / "mnist_test_images.npy", allow_pickle=False)[0]
    assert X.shape == (1, 28, 28), X.shape
    img = X.reshape(-1).astype(np.uint8).tobytes()
    (HERE / "img0.u8").write_bytes(img)
    y = int(np.load(MNIST / "data" / "mnist_test_labels.npy", allow_pickle=False)[0])
    (HERE / "img0.u8.label").write_text(f"{y}\n")

    lines = [
        "# inputs.rows -- generated by .agents/slop/seams/mk_inputs.py",
        "# columns: key shape byte_offset elements sha256",
    ]
    for k, shape, o, n, h in rows:
        lines.append(f"{k} {','.join(str(d) for d in shape)} {o} {n} {h}")
    lines.append(f"weights.f32 total_bytes {off} sha256 {hashlib.sha256(blob).hexdigest()}")
    lines.append(f"img0.u8 bytes {len(img)} sha256 {hashlib.sha256(img).hexdigest()} label {y}")
    # THE SOURCE OF THE PARAMETERS, BY DIGEST. `weights.f32` is a CONCATENATION,
    # so its own digest says nothing about which trained model produced it; this
    # row says which file was read, and the two together pin the port's input
    # to the oracle's input.
    lines.append(f"source weights.npz sha256 {hashlib.sha256((MNIST / 'weights.npz').read_bytes()).hexdigest()}")
    (HERE / "inputs.rows").write_text("\n".join(lines) + "\n")

    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
