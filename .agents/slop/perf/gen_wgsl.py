#!/usr/bin/env python3
"""gen_wgsl.py -- A CAPTURED UOP LIST AS THE PORT's `W.R` RECORDS.

    .venv/bin/python .agents/slop/perf/gen_wgsl.py

IT READS `.agents/slop/perf/stage1/<name>.rows` (written by stage1_webgpu.py from the uops
the SCHEDULER produced) and writes `.agents/slop/perf/gen_wgsl/<name>.bend`, a module whose
`rs()` is the port's own flat record list. `render_wgsl.bend` then walks it with
`W.walk`/`W.render_kernel` -- THE PORT's OWN renderers, not a pasted body.

WHY A GENERATED MODULE AND NOT A PARSER IN BEND: the same reason `cpuseam/gen_kus.py` gives
-- the expectations are TRANSCRIBED BY SCRIPT, never typed, and a parser in Bend would be a
second implementation of the `.rows` format to keep in step with `dump_kernel.py`.
"""
from __future__ import annotations
import pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
SRC, OUT = pathlib.Path(__file__).resolve().parent / "stage1", pathlib.Path(__file__).resolve().parent / "gen_wgsl"

DT = {"f32": "S.single()", "i32": "S.int32()", "u32": "S.uint32()", "i64": "S.int64()",
      "u64": "S.uint64()", "u8": "S.uint8()", "i8": "S.int8()", "u16": "S.uint16()",
      "i16": "S.int16()", "bool": "S.boolean()", "void": "S.void()", "weakint": "S.weakint()",
      "weakfloat": "S.weakfloat()", "f16": "S.half()", "bf16": "S.bfloat16()", "f64": "S.double()"}
ADDR = {"ALU": "S.Aalu{}", "GLOBAL": "S.AGlobal{}", "REG": "S.AReg{}", "LOCAL": "S.ALocal{}", "NONE": "S.Aalu{}"}


def one(line: str) -> str:
    f = line.split("|")
    idx, op, dt, addr, shape, numel, srcs, kind, payload = f
    d, a = DT.get(dt), ADDR.get(addr)
    if d is None or a is None:
        raise SystemExit(f"{op}: unknown dtype {dt} or addrspace {addr}")
    nm, num, slot = '""', 0, 0
    fexpr = "0.0"
    shp = "Nil{}"
    if shape:
        shp = "[" + ", ".join(str(int(x)) for x in shape.split("x")) + "]"
    if kind == "const":
        # `ConstFloat(0.0)` is upstream's float const. The port's walk SKIPS every CONST
        # (upstream does too), so the value has to reach the text some other way -- that gap
        # is recorded by the comparison, not hidden here, so the number is 0 and the walk's
        # output will simply lack it.
        p_ = payload.strip()
        p_ = p_[len("ConstFloat("):-1] if p_.startswith("ConstFloat(") else p_
        try:
            num = int(p_)
        except ValueError:
            num = 0
        # THE VALUE ITSELF travels in `f`, and `str` keeps the transcribed text as the arm a
        # NON-float const still needs. A float const is F32-typed upstream, so its literal here is
        # parsed back to the same f32 by Bend's reader; the walk then COMPUTES the digits with
        # `FR.repr` instead of reading CPython's string (which is what `str` used to be used for).
        nm = f'"{p_}"'
        flt = float(p_) if p_ not in ("nan", "inf", "-inf") else 0.0
        fexpr = f"(0.0-{-flt} : F32)" if flt < 0 else repr(flt)
    elif kind == "param":
        p = payload.split("~")
        slot, nm = int(p[0]), ('"-"' if p[1] == "-" else f'"{p[1]}"')
    elif kind == "special":
        nm = f'"{payload.replace("~", "")}"'
        num = int(payload.replace("~", "")[-1])
    elif kind == "sink":
        nm = f'"{payload.strip()}"'
    elif kind == "range":
        # `RANGE`'s payload is `<axis>~<ids...>`: the AXIS NAME becomes `str` (the walk turns it
        # into the letter, `axis_letters`) and the ids become `shape` (the walk joins them,
        # `range_str`), so the walker owns both rules and the generator only transcribes.
        f_ = payload.split("~")
        nm = f'"{f_[0]}"'
        shp = "[" + ", ".join(str(int(x)) for x in f_[1:]) + "]"
    ss = "Nil{}" if srcs.strip() == "" else "[" + ", ".join(str(int(x)) for x in srcs.split()) + "]"
    return (f"  W.R{{O.Ops{op}{{}}, {d}, {a}, {numel}, {nm}, {num}, {slot}, {shp}, {ss}, {fexpr}}},"
            f" # {idx} {op}")


def main() -> int:
    names = sys.argv[1:] or sorted(p.stem for p in SRC.glob("*.rows"))
    OUT.mkdir(parents=True, exist_ok=True)
    for name in names:
        rows = [ln for ln in (SRC / f"{name}.rows").read_text().splitlines() if ln and not ln.startswith("#")]
        body = "\n".join(one(ln) for ln in rows)
        (OUT / f"{name}.bend").write_text(
            f"# {name}.bend -- GENERATED by .agents/slop/perf/gen_wgsl.py from stage1/{name}.rows.\n"
            "# DO NOT HAND-EDIT.\nimport Base\n"
            "import ./../../../../tinybendygrad/renderer/wgsl_walk.bend as W\n"
            "import ./../../../../tinybendygrad/uop/ops.bend as O\n"
            "import ./../../../../tinybendygrad/LAWS/spec.bend as S\n\n"
            "def rs() -> List<&2, W.R>:\n  [\n" + body + "\n  ]\n")
        print(f"# wrote {name}.bend ({len(rows)} uops)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
