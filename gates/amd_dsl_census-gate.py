# WHY THIS GATE DOES NOT CALL `gatekit.Gate.run()`.
#
# `Gate.diverges` is a NAME -> (oracle, port) dict and its exclusion is a regex
# built from the KEYS (gatekit.py:453-454), so it can express "these rows differ"
# but NOT "this row name differs TWICE". MEASURED WHEN IT APPLIED: `dsl.bend`'s
# body printed `modmerge_0_0_0` and `modmerge_0_0_1` twice each, so the pins file
# carried 118 lines under 117 names, and gatekit's own staleness check --
# `if len(hits) != want` with `want = len(self.diverges)` for the py lane
# (gatekit.py:469-470) -- read 118 against 117 and returned FAIL. Both readings:
#
#   py carries 118 excluded rows, expected 117 -- the exclusion list is stale
#   py has 1057 COMPARED rows, expected 1058
#
# **THE DUPLICATED NAME IS NO LONGER PINNED** -- both `modmerge_*` pairs became EXACT -- so the
# two numbers are 47 and 47 today and gatekit's staleness check would pass BY COINCIDENCE.
# The rows are STILL printed twice (`dup_rows_hold()` measures the 14 duplicates on every run),
# and a future divergence on either name would reopen exactly this failure, so the gate keeps
# running its own three lanes and keeps pinning by OCCURRENCE rather than betting on a
# coincidence. Dropping the duplicated name to make gatekit happy would either compare a row
# that genuinely differs (the diff fails) or pin only one of the two (a real
# divergence becomes an unchecked one). Both weaken the instrument, so this gate
# runs the three lanes itself, re-uses gatekit's PLUMBING (BEND, PY, WARM, the
# `.tmp.` staging convention, `_settle`'s promote-or-discard), and pins by
# OCCURRENCE. `gatekit.py` is not edited.
def _lines(s):
    return [l for l in s.splitlines() if l.strip()]


def _staged(n):
    return ART / f"{TMP}{n}"


def lane(argv, name, rows=ROWS):
    """One lane, retried while it emits the wrong ROW COUNT -- `bend`'s machine
    stack overflows on roughly 1 run in 20 and prints nothing at all, which is
    indistinguishable from 'did not start'. A named failure says which STEP."""
    out = _staged(name)
    for _ in range(25):
        r = subprocess.run(argv, capture_output=True, text=True, cwd=str(ROOT))
        if r.returncode == 0 and len(_lines(r.stdout)) == rows:
            out.write_text(r.stdout)
            return True
        said = " | ".join(l.strip() for l in (r.stderr or "").splitlines()
                          if l.strip() and not NOTICE.match(l.strip()))
        if said:
            break
    print(f"  lane {name} did not produce {rows} rows"
          + (f" -- {said}" if said else " in 25 tries (the flake)"), file=sys.stderr)
    return False


def warm():
    """`--check-only`'s FIRST LINE, never its exit status: an EMPTY file
    typechecks (gatekit's `_warm`, and the reason it is there)."""
    for _ in range(25):
        r = subprocess.run([str(BEND), str(PORT), "--check-only"],
                           capture_output=True, text=True, cwd=str(ROOT))
        first = (r.stdout or "").splitlines()[:1]
        if first and first[0].strip() == WARM:
            return True
    print("  the substrate did not warm: `bend --check-only` never printed "
          f"{WARM!r}", file=sys.stderr)
    return False


def run():
    """PRODUCE THREE LANES, COMPARE THEM, AND SETTLE ON EVERY EXIT.

    Staging is gatekit's own `.tmp.` convention and the promote-or-discard is its
    `_settle`, so a red run leaves neither a half-written artifact nor a temp and
    the promoted files always name a run that COMPLETED.
    """
    ok = False
    try:
        ART.mkdir(parents=True, exist_ok=True)
        for f in ART.iterdir():
            f.unlink()
        if not warm():
            return REFUSED
        if not lane([str(PY), str(ORACLE)], "py.rows"):
            return REFUSED
        if not lane([str(BEND), str(PORT)], "bd.out"):
            return DEAD
        binp = _staged("gate.bin")
        c = subprocess.run([str(BEND), str(PORT), "-o", str(binp)],
                           capture_output=True, text=True, cwd=str(ROOT))
        if c.returncode != 0:
            print(f"  the native compile failed: {(c.stderr or '').strip()[:200]}",
                  file=sys.stderr)
            return REFUSED
        if not lane([str(binp)], "bn.out"):
            return DEAD

        lanes = {t: _lines(_staged(t).read_text()) for t in ("py.rows", "bd.out", "bn.out")}
        n0 = {t: len(v) for t, v in lanes.items()}
        if any(n != ROWS for n in n0.values()):
            print("  " + ", ".join(f"{t} has {n}" for t, n in n0.items())
                  + f", expected {ROWS}", file=sys.stderr)
            return DEAD if 0 in n0.values() else FAIL

        # THE PINS ARE EXCLUDED ON BOTH SIDES, and the exclusion is by NAME --
        # so a lane is never compared on a row that is KNOWN to differ.
        trip = [l.split("\t") for l in PINS.read_text().splitlines()
                if l.strip() and not l.startswith("#")]
        pinned = {row for row, _, _ in trip}
        want = {row: sum(1 for r, _, _ in trip if r == row) for row, _, _ in trip}
        kept = {t: [l for l in v if l.split("=", 1)[0] not in pinned] for t, v in lanes.items()}
        n = {t: len(v) for t, v in kept.items()}
        if len(set(n.values())) != 1 or n["py.rows"] != ROWS - sum(want.values()):
            print("  " + ", ".join(f"{t} kept {v}" for t, v in n.items())
                  + f", expected {ROWS - sum(want.values())} everywhere -- the "
                    f"exclusion list is stale", file=sys.stderr)
            return FAIL
        for tag in ("bd.out", "bn.out"):
            if kept[tag] != kept["py.rows"]:
                d = [(x, y) for x, y in zip(kept["py.rows"], kept[tag]) if x != y][:2]
                print(f"  DISAGREE ({tag}): {d}", file=sys.stderr)
                return FAIL
        # AND EVERY PIN IS STILL CHECKED, BY OCCURRENCE -- the exclusion removes a
        # row from the diff; it does not excuse it.
        for row, pv, bv in trip:
            for tag, text in (("py.rows", f"{row}={pv}"),
                              ("bd.out", f"{row}={bv}"), ("bn.out", f"{row}={bv}")):
                got = sum(1 for l in lanes[tag] if l == text)
                if got != want[row]:
                    print(f"  {tag}: {text!r} appears {got} times, the pins say "
                          f"{want[row]} -- a pin moved, or a duplicated row name "
                          f"was lost", file=sys.stderr)
                    return FAIL
        _staged("cmp.rows").write_text("\n".join(kept["py.rows"]) + "\n")
        ok = True
    finally:
        for t in ART.glob(f"{TMP}*"):
            if ok:
                t.replace(ART / t.name[len(TMP):])
            else:
                t.unlink()
    return 0 if ok else 1


SUMMARY = (f"amd_dsl_census: PASS -- {ROWS} rows x 3 lanes, "
           f"{ROWS - pin_lines()} exact, {pin_lines()} pinned "
           f"({len(DIVERGES or {})} names)")


def main():
    code = run()
    if code == 0 and not checks_hold():
        code = 1
    print(SUMMARY if code == 0 else f"amd_dsl_census-gate: {VERDICT[code]}")
    return code


