# THE DIVERGENCE POPULATION -- declared here, PINNED on both sides, in a file
# beside the gate and written by `--refresh` and by nothing else.
# ===========================================================================
def _pins():
    """`(DIVERGES, why)` -- the pins LOADED BY PATH, and the population they must
    agree with. The pins are a PAIRS file: `row<TAB>oracle<TAB>port`, because a
    divergence is precisely where the two sides differ and pinning one string
    can only ever describe half of it."""
    if not PINS.is_file():
        return None, (f"{PINS.name} is MISSING -- a gate's declared divergences "
                      f"must live in git, beside the gate. Run --refresh.")
    pins = {}
    for ln in PINS.read_text().splitlines():
        if not ln.strip() or ln.startswith("#"):
            continue
        parts = ln.split("\t")
        if len(parts) != 3:
            return None, f"{PINS.name}: a line is not row<TAB>oracle<TAB>port: {ln!r}"
        row, py_v, port_v = parts
        pins[row] = (f"{row}={py_v}", f"{row}={port_v}")
    return pins, ""


def pin_lines():
    """How many pins LINES the file carries -- which is NOT `len(DIVERGES)`.

    FINDING A bites here too, and it is the same shape twice: the port's body
    prints `modmerge_0_0_0` and `modmerge_0_0_1` TWICE each, so a pins file that
    pins either of them carries two LINES under one NAME, and `gatekit`'s
    exclusion is a dict keyed by name. `compared` is therefore computed from the
    LINE count. It was 118 lines under 117 names when this was written; it is 47
    lines under 47 names now, because the duplicated `modmerge_*` rows became
    EXACT and no pin needs the occurrence count any more -- and
    `divergences_hold()` asserts BOTH numbers so they cannot drift apart again.
    """
    return sum(1 for ln in PINS.read_text().splitlines()
               if ln.strip() and not ln.startswith("#")) if PINS.is_file() else 0


DIVERGES, WHY = _pins()


def divergences_hold() -> bool:
    """Every pinned row really is a divergence, and the count is the measured one.
    Without this, a pin list could grow to cover the whole census."""
    if DIVERGES is None:
        return report("divergences_hold", [WHY])
    want, _ = oracle_rows()
    bad = []
    if len(DIVERGES) != 47:
        bad.append(f"{len(DIVERGES)} pinned divergences by NAME, expected 47")
    if pin_lines() != 47:
        bad.append(f"{pin_lines()} pins lines, the header says 47")
    for row in DIVERGES:
        if want is not None and not any(l.split("=", 1)[0] == row for l in want):
            bad.append(f"pinned row {row!r} is not in the oracle's population")
    return report("divergences_hold", bad)


def classes_hold() -> bool:
    """Every pinned row lands in EXACTLY ONE declared class, by the same patterns
    `--refresh` used, and each class carries its reason. A pin that moves between
    classes is a finding that changed shape, not a formatting slip -- and a pin
    with no class is a divergence nobody has explained."""
    bad = []
    trip = [l.split("\t") for l in PINS.read_text().splitlines()
            if l.strip() and not l.startswith("#")]
    got = {}
    for row, _, _ in trip:
        hits = [c for c, pat in CLASSES if re.search(pat, row)]
        if not hits:
            bad.append(f"no class for {row!r}")
        elif len(hits) > 1:
            bad.append(f"{row!r} matches {hits}")
        else:
            got[hits[0]] = got.get(hits[0], 0) + 1
    declared = {c for c, _ in CLASSES}
    if set(got) != declared:
        bad.append(f"classes with no rows: {sorted(declared - set(got))}")
    for c, _ in CLASSES:
        if c not in CLASS_WHY:
            bad.append(f"class {c} has no reason")
    return report("classes_hold", bad)


