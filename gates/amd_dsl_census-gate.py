def _header(n):
    out = [
        "# amd_dsl_census-pins.rows -- GENERATED by",
        "# `amd_dsl_census-gate.py --refresh`, which is its ONLY writer. One TAB-",
        "# separated TRIPLE per line: the row NAME, the ORACLE's value, the PORT's.",
        "# Loaded by path by the gate and committed BESIDE it, because a gate's",
        "# declared divergences must live in git -- not in `gates/artifacts/`",
        "# (`.gitignore`d, and where one `rm -rf` takes them) and not in the",
        "# environment of whoever ran it last.",
        f"#\n# {n} DIVERGENCES of {ROWS} ROWS. Each block is a CLASS, and each",
        "# class says WHY the two sides differ. A pin without a reason is a",
        "# weakened instrument; a divergence without a pin is a silent one.",
        f"#\n# dsl.py blob at HEAD, at `ad117c928` and at the pin `{PIN}`:",
        "# `pin_drift_hold()` re-measures all three on every run.",
        f"# HEAD blob of tinygrad/renderer/amd/dsl.py when these rows were taken: "
        f"{pins_blob()}",
        "",
        f"# {len(RETIRED)} CLASSES ARE RETIRED AND GONE, AND EVERY ONE OF THEIR ROWS IS EXACT NOW.",
        "# THEY ARE NOT IN `CLASSES` ANY MORE: A CLASS WITH NO ROWS IS A CLAIM THAT HAS",
        "# STOPPED BEING TRUE, AND `classes_hold()` FAILS A CLASS THAT HAS NONE. EACH",
        "# STORY IS BELOW, WITH THE READING.",
    ]
    for name, was, why in RETIRED:
        out.append("")
        # EVERY LINE carries the `#`, not just the first: a story with bare
        # continuation lines is prose the file's own reader (`grep -v '^#'`) cannot
        # tell from a row, which is how a pins file grows 51 phantom rows.
        story = f"{name} -- 0 ROWS. IT WAS {was}. {why}".split("\n")
        out += [f"# {ln}" if ln.strip() else "#" for ln in story]
    return "\n".join(out)


def pins_blob() -> str:
    r = subprocess.run(["git", "rev-parse", "--short=8",
                        "HEAD:tinygrad/renderer/amd/dsl.py"],
                       capture_output=True, text=True, cwd=str(ROOT))
    return r.stdout.strip() if r.returncode == 0 else "unknown"


