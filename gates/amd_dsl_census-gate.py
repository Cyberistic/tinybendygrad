    # not in `FMTMOD_AXIS`, not in `MOD_AXIS`. 124 (NULL), 126 (EXEC_LO) and 106
    # (VCC_LO) are all covered, so this is not "the tail of the table is
    # missing"; it is two named registers that no row formats. The property is
    # asserted as the EXACT PAIR rather than widened away: if the axis grows to
    # cover one of them, this goes red and says the gap closed.
    if sorted(o for o in d.Reg._NAMES if o not in covered) != [125, 127]:
        bad.append(f"the uncovered _NAMES offsets are "
                   f"{sorted(o for o in d.Reg._NAMES if o not in covered)}, "
                   f"expected [125, 127] -- the fmt axis grew")
    return report("axes_hold", bad)


