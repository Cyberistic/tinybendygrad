# `dsl.bend`'s FIELD SPELLINGS -> the `dsl.py` classes they stand for. The two
# sides name a field the same way in their own vocabulary, and this is the whole
# of the translation; a new spelling on either side is an unmatched key here.
KIND = {"plain": "BitField", "fixed": "FixedBitField", "enum": "EnumBitField",
        "src": "SrcField", "vgpr": "VGPRField", "sgpr": "SGPRField",
        "ssrc": "SSrcField", "align2": "AlignedSGPRField", "sbase": "SBaseField",
        "srsc": "SRsrcField", "vdsty": "VDSTYField"}


def fixtures_hold() -> bool:
    """THE SHARED FIXTURE, compared as TEXT, in two halves.

    (a) the FIELD declarations -- `dsl.bend`'s `Fld.X("name", hi, lo[, dflt])`
        against the oracle's, which are the same `dsl.BitField` subclasses built
        at the same widths. This is what stops the `raw_*` rows from being "the
        oracle agrees with the port about a fixture neither of them got from
        CPython".
    (b) the VALUE lists -- the same NAMES in the same ORDER, since `dsl.py:334`
        looks a value up by the field list's name, so a value list whose ORDER
        differs is a different fixture and not a re-spelling of the same one.
        (The port's `Vf` carries its own field, so its list order is its
        `_fields` order -- which is what the retired `WALK_IS_VALUES` row was.)
    """
    def bend_fields():
        src = PORT.read_text()
        out = {}
        for m in re.finditer(r"^def ([A-Z0-9_]+)\(\) -> List<&2, (?:Vf|Fld)>:(.*?)(?=^def |\Z)",
                             src, re.M | re.S):
            out[m.group(1)] = [(KIND[k], n, hi, lo, df)
                              for k, n, hi, lo, df in re.findall(
                                  r'Fld\.(\w+)\("(\w+)", (\d+), (\d+)(?:, (\d+))?\)',
                                  m.group(2))]
        return out
    try:
        import importlib.util
        sys.path.insert(0, str(HERE))
        spec = importlib.util.spec_from_file_location("_amd_oracle", str(ORACLE))
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
    except Exception as e:                                   # noqa: BLE001
        return report("fixtures_hold", [f"the oracle would not import: {e}"])
    bad = []
    bf = bend_fields()
    for nm, want in (("VOP2_FIELDS", m.VOP2_FIELDS), ("ORD_FIELDS", m.ORD_FIELDS),
                     ("ORD_FIELDS_SWAP", m.ORD_FIELDS_SWAP),
                     ("F32_FIELDS", m.F32_FIELDS), ("F16_FIELDS", m.F16_FIELDS),
                     ("F64_FIELDS", m.F64_FIELDS), ("F40_FIELDS", m.F40_FIELDS),
                     ("F8_FIELDS", m.F8_FIELDS)):
        got = [(type(f).__name__, n, str(f.hi), str(f.lo)) for n, f in want]
        if nm not in bf:
            bad.append(f"{nm} is not declared in dsl.bend")
        elif [(k, n, hi, lo) for k, n, hi, lo, _ in bf[nm]] != got:
            bad.append(f"{nm}: port {bf[nm]} != oracle {got}")
    for nm in ("VOP2_ALL", "VOP2_NEG", "VOP2_HI", "VOP2_INT", "VOP2_INT65",
               "VOP2_INTN17", "VOP2_FCONST", "VOP2_FNOLIT", "VOP2_LIT",
               "VOP2_SDWA", "VOP2_DPP", "VOP2_BIG", "VOP2_BIG2", "ORD_VALS",
               "ORD_VALS_SWAP", "F32_VALS", "F16_VALS", "F64_VALS", "F40_VALS",
               "F8_VALS"):
        want = [n for n, _ in getattr(m, nm)]
        got = [n for _, n, _, _, _ in bf.get(nm, [])]
        if got != want:
            bad.append(f"{nm}: port spells {got}, oracle {want}")
    return report("fixtures_hold", bad)


