def port_rows():
    """`dsl.bend`'s own printed row NAMES, in order, by `re.findall` over the
    `g_*` bodies. 1174 census rows plus the `dsl-done=1` completion marker."""
    src = PORT.read_text()
    names = re.findall(r'^\s+(?:srow|urow|row)\("([^"]+)"', src, re.M)
    return names + ["dsl-done=1"]


def oracle_rows():
    """The ORACLE's row names, by running it. The two lists must be equal AND in
    the same order -- `names_holds()` is what stops an oracle from quietly
    covering whatever the port happens to do."""
    r = subprocess.run([str(PY), str(ORACLE)], capture_output=True, text=True)
    if r.returncode != 0:
        return None, f"the oracle failed rc={r.returncode}: {r.stderr.strip()[:300]}"
    names = [l.split("=", 1)[0] for l in r.stdout.splitlines() if "=" in l]
    # the completion marker is a row NAME and a row NAME on the port side, so it
    # has to be one on this side too -- `dsl-done`, not `dsl-done=1`.
    if names and names[-1] == "dsl-done":
        names[-1] = "dsl-done=1"
    return names, ""


def groups_hold() -> bool:
    """The DRIVER axis is the `g_*` defs `main()` calls -- not a list here."""
    src = PORT.read_text()
    declared = set(re.findall(r"^def g_([a-z0-9]+)\(\) -> IO\(Unit\):", src, re.M))
    body = src[src.index("def main() -> IO(Unit):"):]
    called = re.findall(r"<-\s+g_([a-z0-9]+)\(\)", body)
    bad = []
    if declared != set(GROUPS):
        bad.append(f"g_* defs are {sorted(declared)}, this gate expects {sorted(GROUPS)}")
    if tuple(called) != GROUPS:
        bad.append(f"main() calls {tuple(called)}, this gate's order is {GROUPS}")
    # and every one of them must be REACHED: a group nothing calls is a
    # population of zero rows that still looks like a gate.
    for g in GROUPS:
        m = re.search(rf"^def g_{g}\(\) -> IO\(Unit\):\n(.*?)(?=^def |\Z)", src, re.M | re.S)
        if not m or '("' not in m.group(1):
            bad.append(f"g_{g} prints no rows")
    return report("groups_hold", bad)


def names_hold() -> bool:
    """THE TWO POPULATIONS ARE EQUAL AND IN THE SAME ORDER."""
    want = port_rows()
    got, why = oracle_rows()
    bad = []
    if got is None:
        bad.append(why)
    elif len(got) != len(want):
        bad.append(f"the oracle emits {len(got)} rows, the port's body declares "
                   f"{len(want)}")
    else:
        for i, (a, b) in enumerate(zip(want, got)):
            if a != b:
                bad.append(f"row {i}: port {a!r}, oracle {b!r}")
                if len(bad) > 4:
                    break
    return report("names_hold", bad)


def dup_rows_hold() -> bool:
    """FINDING A: the port's body prints 14 rows under 1160 names. Pinned, so a
    reader of this file cannot mistake the census for a keyed table."""
    from collections import Counter
    names = port_rows()[:-1]
    dups = sorted(n for n, c in Counter(names).items() if c > 1)
    bad = []
    if len(names) != 1174:
        bad.append(f"{len(names)} census rows, expected 1174")
    if len(set(names)) != 1160:
        bad.append(f"{len(set(names))} distinct row names, expected 1160")
    if len(dups) != 14:
        bad.append(f"{len(dups)} duplicated names, expected 14: {dups}")
    return report("dup_rows_hold", bad)


def axes_hold() -> bool:
    """FINDING C and the fixture axes. Re-measured here, not asserted in prose.

    (a) the five group-O labels match 0 of `dsl.OPERANDS`;
    (b) every offset in `Reg._NAMES` appears at SOME width in the `fmt` axis or
        the `fmtmod` axis, and every `Reg.fmt` arm boundary does;
    (c) 512 -- the refusal arm, dsl.py:58 -- is in the `fmt` axis.
    """
    sys.path.insert(0, str(ROOT))
    import tinygrad.renderer.amd.dsl as d
    bad = []
    labels = ("v_cndmask_f32", "v_cmp_lt_f32", "v_co_ci_add_f32",
              "v_f8f6f4_mfma_f32_32x32x8_f16", "v_add_f32")
    keys = {getattr(k, "name", "").lower() for k in d.OPERANDS}
    hit = [x for x in labels if x in keys]
    if hit:
        bad.append(f"FINDING C is stale: {hit} are now real opcodes")
    if len(d.OPERANDS) != 4623:
        bad.append(f"OPERANDS has {len(d.OPERANDS)} keys, the pins say 4623")
    widths = {(int(a), int(b)) for a, b in
              re.findall(r'\("(?:fmt)_(\d+)_(\d+)"', PORT.read_text())}
    modw = {(int(a), int(b)) for a, b in
            re.findall(r'"fmtmodu?_(\d+)_(\d+)_\d{3}"', PORT.read_text())}
    covered = {o for o, _ in widths | modw}
    for bnd in (0, 105, 106, 108, 123, 124, 128, 192, 193, 208, 240, 256, 511, 512):
        if bnd not in covered:
            bad.append(f"fmt arm boundary {bnd} is at no width")
    # FINDING E, AND A MEASURED COVERAGE GAP. `_NAMES` offsets 125 (M0) and 127
    # (EXEC_HI) are at NO width on any axis in this census -- not in `FMT_AXIS`,
    # not in `FMTMOD_AXIS`, not in `MOD_AXIS`. 124 (NULL), 126 (EXEC_LO) and 106
    # (VCC_LO) are all covered, so this is not "the tail of the table is
    # missing"; it is two named registers that no row formats. The property is
    # asserted as the EXACT PAIR rather than widened away: if the axis grows to
    # cover one of them, this goes red and says the gap closed.
    if sorted(o for o in d.Reg._NAMES if o not in covered) != [125, 127]:
        bad.append(f"the uncovered _NAMES offsets are "
                   f"{sorted(o for o in d.Reg._NAMES if o not in covered)}, "
                   f"expected [125, 127] -- the fmt axis grew")
    return report("axes_hold", bad)


