# --refresh : rewrite the pins from a fresh pair of lanes. Its ONLY writer.
# ===========================================================================
CLASSES = [
    # `afenc_{sr,sr2}_(2|126|127)` are REFUSALS on this axis -- the value is not
    # an alignment shift at all -- so they belong to MSG_TEXT, and only the
    # encode/decode rows here are the shift itself.
    ("MSG_TEXT", r"^(afenc_(ab|sb|sr|sr2)_(nonreg|hi|odd|127)$|afenc_(sr|sr2)_(2|126|127)$"
                 r"|vgencneg_|fixed_(op7|enc33|enc17)$)"),
    # `modmask_*` and `srcbit_*` are ONE PLACE with TWO defects and the tautology half of it is
    # already fixed (see the pins file). What is left is the half nobody has touched: `mod_mask`
    # requires only that the value be a `Reg`, never that the RIGHT modifier is the one set, so
    # `neg_bits`/`abs_bits`/`opsel_bits` (dsl.py:317-319) come out equal and the three families are
    # the same measurement under three names.
    ("MODMASK", r"^(modmask_|srcbit_(sdst|op|nosuch)$)"),
    ("SRC_WIDTH", r"^sf_width(msg)?_"),
    # `to_bytes_f32i` and `to_bytes_f16i` are exact; `to_bytes_vop2` is not, and NOT because of
    # byte order any more -- `Res.v` is a `U32` and a VOP2 word is 42 bits wide, so the port
    # cannot hold `sdst` or `op_sel`. The class reason names the WIDTH.
    ("TO_BYTES", r"^to_bytes_"),
]
CLASS_WHY = {
    "MSG_TEXT": "both sides refuse; dsl.py:207/:209/:211 name the CLASS and format "
                "type(val).__name__, dsl.bend names the FIELD and the Ov kind.",
    "MODMASK": "`src_bit.vdst`'s tautology is FIXED (String.eq(name, \"vdst\"), so the "
               "sdst/op/nosuch pins are dropped rather than moved); what remains is that "
               "mod_mask never tests WHICH modifier is set, so neg/abs/opsel come out equal.",
    "SRC_WIDTH": "dsl.py:155-157 compares 1 << bits (512) against the range count "
                  "(512) and accepts; dsl.bend compares bits (9) against 512, and "
                  "prints the mask (511) where CPython prints actual_size (512).",
    "TO_BYTES": "dsl.py:416 is _raw.to_bytes(base_size, 'little') and f32i/f16i are now "
                "EXACT. What is left is WIDTH: `Res` is Res{v: U32, s: String} and "
                "`bf_set.placed` shifts with U32.shln, so every bit at index >= 32 is "
                "discarded and a 42-bit VOP2 word loses `sdst` [41:36] and `op_sel` "
                "[35:34]. CPython's raw is 0x4814060a00 (39 bits); the port's is "
                "0x0014060a00.",
}


def refresh() -> int:
    """REWRITE the pins from a fresh pair of lanes. Its ONLY writer.

    It does not go through `Gate.run()`, because a refresh is exactly what a run
    cannot do when the pins are wrong. The header is regenerated with it, because
    a pins file whose prose outlives its content is a second copy of the answer.
    """
    if not PINS.is_file() and not _header_ok():
        pass
    lanes = {}
    for tag, argv in (("py", [str(PY), str(ORACLE)]),
                      ("bd", [str(BEND), str(PORT)])):
        r = subprocess.run(argv, capture_output=True, text=True, cwd=str(ROOT))
        if r.returncode != 0:
            print(f"--refresh: lane {tag} failed rc={r.returncode}: "
                  f"{(r.stderr or '').strip()[:200]}", file=sys.stderr)
            return 1
        lanes[tag] = [l for l in r.stdout.splitlines() if "=" in l]
    if len(lanes["py"]) != ROWS or len(lanes["bd"]) != ROWS:
        print(f"--refresh: row counts py={len(lanes['py'])} bd={len(lanes['bd'])}, "
              f"expected {ROWS}", file=sys.stderr)
        return 1
    by = {t: dict((l.split("=", 1)[0], l) for l in v) for t, v in lanes.items()}
    order = [l.split("=", 1)[0] for l in lanes["py"]]
    rows = []
    for name in order:
        if by["py"][name] == by["bd"][name]:
            continue
        cls = next((c for c, pat in CLASSES if re.search(pat, name)), None)
        if cls is None:
            print(f"--refresh: no class for {name!r} -- declare one before "
                  f"refreshing, or a new divergence is pinned with no reason",
                  file=sys.stderr)
            return 1
        rows.append((cls, name,
                     by["py"][name].split("=", 1)[1],
                     by["bd"][name].split("=", 1)[1]))
    # ONE CONTIGUOUS BLOCK PER CLASS, and the rows KEEP THEIR LANE ORDER inside
    # it -- so the file reads as "this class, in the order the gate emits it".
    # Sorting by class is what makes a per-class COUNT readable; without it the
    # same class header is emitted once per run of its rows and two headers can
    # disagree.
    order = {c: i for i, (c, _) in enumerate(CLASSES)}
    at = {id(r): i for i, r in enumerate(rows)}
    rows.sort(key=lambda r: (order[r[0]], at[id(r)]))
    out = [_header(len(rows))]
    last = None
    for cls, name, pv, bv in rows:
        if cls != last:
            out += ["", f"# {cls} -- {sum(1 for r in rows if r[0] == cls)} rows. "
                        f"{CLASS_WHY[cls]}"]
            last = cls
        out.append(f"{name}\t{pv}\t{bv}")
    PINS.write_text("\n".join(out) + "\n")
    print(f"--refresh: {PINS.name} rewritten -- {len(rows)} divergences, "
          f"{ROWS - len(rows)} exact matches, {len(set(c for c, _, _, _ in rows))} classes")
    return 0


def _header_ok() -> bool:
    return PINS.is_file()


def _header(n):
    return "\n".join([
        "# amd_dsl_census-pins.rows -- GENERATED by",
        "# `amd_dsl_census-gate.py --refresh`, which is its ONLY writer. One TAB-",
        "# separated TRIPLE per line: the row NAME, the ORACLE's value, the PORT's.",
        "# Loaded by path by the gate and committed BESIDE it, because a gate's",
        "# declared divergences must live in git -- not in `gates/artifacts/`",
        "# (`.gitignore`d, and where one `rm -rf` takes them) and not in the",
        "# environment of whoever ran it last.",
        f"#\n# {n} DIVERGENCES of {ROWS} ROWS. Each block is a CLASS, and each",
        "# class says WHY the two sides differ. A pin without a reason is a",
        "# weakened instrument; a divergence without a pin is a silent one.",
        f"#\n# dsl.py blob at HEAD, at `ad117c928` and at the pin `{PIN}`:",
        "# `pin_drift_hold()` re-measures all three on every run.",
        f"# HEAD blob of tinygrad/renderer/amd/dsl.py when these rows were taken: "
        f"{pins_blob()}",
    ])


