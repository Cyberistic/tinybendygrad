#!/usr/bin/env python3
"""fixture-region-gate.py -- A GENERATED REGION AGAINST THE GENERATOR IT NAMES.

    .venv/bin/python gates/fixture-region-gate.py
    .venv/bin/python gates/fixture-region-gate.py --file <path>
    .venv/bin/python gates/fixture-region-gate.py --plant

WHY THIS FILE EXISTS, AND IT IS THE THIRD HALF OF A STORY.
`tinybendygrad/renderer/ptx.bend` holds a `# ==== BEGIN GENERATED FIXTURES` region with
the port's OWN 25 fixture graphs (`Wk`) and 268 `want` values (`Wt`), and EVERY ONE OF THEM
IS CPython's answer.  The oracle that produced them (`.agents/slop/ptx-s3-oracle.py`) and the
script that wrote them (`.agents/slop/ptx-s3-gen.py`) were DELETED by the 2026-10-05 sweep, so
the region was a FROZEN COPY and NOTHING could check it.

`gates/fixture-embed-census.py` counted every literal inside a region the port DECLARES as
generated as FROZEN, and **THAT CLASS CAN NOT GO EMPTY**: a literal in a generated region is
frozen BY CONSTRUCTION, whether or not a generator exists, so REGENERATING THE REGION CHANGES
NOTHING ABOUT THE COUNT.  A class that cannot go empty is not a class, it is a LABEL.

THE CLASS, REDEFINED BY THE GENERATOR's PRESENCE AND NOT BY THE PRESENCE OF A LITERAL:

  GENERATED   the region NAMES its generator, the generator IS THERE, it RUNS, and the region
              MATCHES what it emits.  The literal is a BUILD PRODUCT.
  DRIFTED     the region names its generator, it is there, it runs, and the region does NOT
              match.  **THIS IS THE ROW THAT CAN GO RED.**
  FROZEN      the region names its generator and THE GENERATOR IS GONE.  THIS IS THE ROT.
  UNDECLARED  the region names nobody.  The census cannot tell a generated value from a
              frozen one, and it says so rather than counting it.

**THE POPULATION IS DISCOVERED BY A WALK, AND THE DECLARATION IS THE DISCOVERY KEY.**
`AGENTS.md`, doctrine 1: a population is a generator's own declaration, loaded by path.  So
the regions this gate checks are the ones that DECLARE a generator, and the ones that do not
are counted and reported, so the omission is visible instead of silent.

**THE COMPARISON IS AGAINST A FRESH EMISSION AND NOT AGAINST A HAND LIST.**  The region names
a generator BY PATH and with its ARGS, so this gate RUNS what the region names -- in a NEW
PROCESS, so nothing is shared -- and compares the region with what came out.  A region that
drifts from its generator is RED, and that is the row the tree did not have.

**THE PLANT IS A TEXT EDIT AND NEVER A READ OF `git show HEAD:`.**  A plant that reads HEAD
plants nothing the moment HEAD carries the defect's fix, and three units scored green under
`--falsify` for exactly that reason.  So the plant copies the LIVE file, edits the COPY, and
runs this gate against the copy.
"""
import argparse
import importlib.util
import os
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
PY = ROOT / ".venv" / "bin" / "python"

#: THE PORT's OWN MARKERS.  A region is what is BETWEEN them, and the markers are the
#: port's own declaration -- so a region that grew or shrank is still found.
BEGIN = "# ==== BEGIN GENERATED FIXTURES"
END = "# ==== END GENERATED FIXTURES"

#: THE DECLARATION, AND IT IS A PATH PLUS ITS ARGS, so the census can RUN it.
DECL = re.compile(r"^#\s*GENERATOR\s+(\S+)\s*(.*)$", re.M)

#: THE HEADER FORM, WHICH NAMES A GENERATOR THAT WRITES THE WHOLE FILE.  It is NOT a
#: region declaration -- the axis's generator emits the whole file, markers and all, so
#: comparing the REGION with it would be comparing two different things -- and it is named
#: here so that an UNDECLARED region can say WHICH generator wrote the file around it.
HEADER_DECL = re.compile(r"^#\s*=+\s*GENERATED by (\S+)", re.M)

#: DIRECTORIES THE WALK DOES NOT DESCEND, AND THE LIST IS NAMED BECAUSE A WALK THAT
#: DESCENDED `runs/` WOULD COUNT A PREVIOUS RUN's OUTPUT AS A SOURCE.
PRUNED = {".git", ".venv", "node_modules", "__pycache__", "references", "runs", "artifacts"}

#: THE SCRATCH THE PLANT WRITES.  `gates/.*` is gitignored (`.gitignore:116`) and `gates/`
#: is NOT in the substrate walk, so a scratch file here moves neither the git index nor the
#: substrate digest.
SCRATCH = HERE / ".tmp-fixture-region-plant.bend"

#: THE PORT's OWN FILE, AND IT IS FOUND BY THE WALK AND NOT NAMED HERE.  The plant needs to
#: know WHICH file to copy, and it asks the walk for the file whose region DECLARES the
#: generator this gate is about.
PLANT_ANCHOR = "# GENERATOR gates/ptx_render_census-gen.py --port"


def walk_regions():
    """EVERY GENERATED REGION IN THE TREE, DISCOVERED BY A WALK.

    **AND THE WALK IS `os.walk` AND NOT `glob`, BECAUSE `glob('*.bend')` ANSWERS `[]` FOR A
    TREE THAT HAS `.bend` FILES IN IT** -- `AGENTS.md` records that, and it is why a suffix
    set and a hand list are not populations.
    """
    out = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = [d for d in dirnames if d not in PRUNED and not d.startswith(".")]
        for fn in filenames:
            if not fn.endswith(".bend"):
                continue
            p = Path(dirpath) / fn
            try:
                raw = p.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            if BEGIN in raw and END in raw:
                out.append((p, raw))
    return out


def region_body(raw):
    """THE REGION's TEXT: everything between the port's own markers."""
    a = raw.index(BEGIN) + len(BEGIN)
    b = raw.index(END, a)
    body = raw[a + 1:b]
    return body[:-1] if body.endswith("\n") else body


def region_bodies(raw):
    """EVERY REGION IN A FILE, IN ORDER.

    **A FILE MAY HOLD MORE THAN ONE REGION**, and a file's class is the WORST of its
    regions' -- so a file with one current region and one drifted region is DRIFTED, and a
    census that only looked at the first would call it current.
    """
    out = []
    i = 0
    while True:
        a = raw.find(BEGIN, i)
        if a < 0:
            return out
        a += len(BEGIN)
        b = raw.find(END, a)
        if b < 0:
            return out
        body = raw[a + 1:b]
        out.append(body[:-1] if body.endswith("\n") else body)
        i = b


def declaration(body):
    """`(path, [args])` -- WHAT THE REGION SAYS WROTE IT, OR `None`."""
    m = DECL.search(body)
    return (m.group(1), m.group(2).split()) if m else None


def emit(gen, args):
    """THE FRESH EMISSION: A NEW PROCESS RUNNING WHAT THE REGION NAMES.

    **A GENERATOR THAT WRITES MUST NOT BE RUN BY THE CENSUS THAT CHECKS IT.**  The
    declaration could name a `--write` mode, and running that would rewrite the very file
    being checked -- a census with a side effect on its own subject is not a census.  So
    the write modes are REFUSED, by name.
    """
    if any(a.startswith("--write") or a == "-w" for a in args):
        return None, "REFUSED: the declaration names a WRITE mode, and a census that writes " \
                     "the file it is checking is not a census"
    cmd = [str(PY), str(ROOT / gen)] + args
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=ROOT)
    if r.returncode != 0:
        return None, f"the generator did not run (rc={r.returncode}): {r.stderr.strip()[:200]}"
    return r.stdout.rstrip("\n"), None


# ---------------------------------------------------------------------------
# THE RECORDS, AND WHY THEY ARE COMPARED KEYED AND NOT POSITIONALLY.
#
# A POSITIONAL COMPARISON OF TWO REGIONS SAYS "THE 85th LINE DIFFERS" AND NOTHING ELSE,
# and a region that GREW a node moves every line after it.  The records are therefore
# compared BY KEY: a `Wt` is keyed by (fixture, the row it names) and a `Wk` by
# (fixture, its position in the fixture's graph).  Then a row that MOVED is STALE (the
# key the region names is one the generator no longer emits), a row whose VALUE CHANGED is
# WRONG (the same key, a different answer -- a fixture that asserts something false), and
# a row the generator emits and the region does not hold is MISSING.
# ---------------------------------------------------------------------------
WT = re.compile(r'Wt\{"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"\}')
FIXTURE = re.compile(r"^def (f\d+_\w+|r_fns)\b")


def wk_records(line):
    """THE `Wk` RECORDS ON A LINE, AND THE BRACES ARE COUNTED.

    **A REGEX CANNOT READ THIS RECORD.**  `Wk{O.OpsBUFFER{}, ...}` holds braces INSIDE it,
    so `Wk\\{.*?\\}` stops at the FIRST `}` and hands back `Wk{O.OpsBUFFER{}` -- a PREFIX of
    the record, and two records that differ only in their tail then compare EQUAL.
    MEASURED, in this file: the first version did exactly that and reported "2 of 7 records
    moved" for a fixture where all 7 moved, because the tail is where the `nmn` and the
    `refs` live.
    """
    out = []
    i = 0
    while True:
        j = line.find("Wk{", i)
        if j < 0:
            return out
        depth = 0
        k = j + 2
        while k < len(line):
            if line[k] == "{":
                depth += 1
            elif line[k] == "}":
                depth -= 1
                if depth == 0:
                    break
            k += 1
        if k >= len(line):
            return out
        out.append(line[j:k + 1])
        i = k + 1


def records(body):
    """`{fixture: {"wt": {row name: (value, text)}, "wk": {position: text}}}` -- KEYED.

    **A `Wt` IS KEYED BY THE ROW IT NAMES AND NOT BY ITS VALUE**, so that a row whose VALUE
    changed is `wrong` and not `stale` -- a stale row is one the generator no longer emits at
    all, which is a different defect with a different remedy.
    """
    out = {}
    fix = None
    pos = 0
    for line in body.splitlines():
        m = FIXTURE.match(line)
        if m:
            fix = m.group(1)
            pos = 0
            out.setdefault(fix, {"wt": {}, "wk": {}})
            continue
        if fix is None:
            continue
        for w in WT.finditer(line):
            out[fix]["wt"][w.group(1)] = (w.group(2), w.group(0))
        for w in wk_records(line):
            out[fix]["wk"][pos] = w
            pos += 1
    return out


def compare(body, emission):
    """THE COUNTED COMPARISON, AND EVERY NUMBER IS A COUNT OF SOMETHING.

    Returns `(same, wrong, stale, missing, total)` where `same` is a record the region
    holds and the generator holds too, with the same text.
    """
    a, b = records(body), records(emission)
    same = wrong = stale = missing = 0
    for fix, got in a.items():
        want = b.get(fix, {"wt": {}, "wk": {}})
        for name, (_value, text) in got["wt"].items():
            if name not in want["wt"]:
                stale += 1
            elif want["wt"][name][0] == _value:
                same += 1
            else:
                wrong += 1
        for pos, text in got["wk"].items():
            if pos not in want["wk"]:
                stale += 1
            elif want["wk"][pos] == text:
                same += 1
            else:
                wrong += 1
        missing += len(want["wt"]) - len([k for k in want["wt"] if k in got["wt"]])
        missing += len(want["wk"]) - len([k for k in want["wk"] if k in got["wk"]])
    total = sum(len(v["wt"]) + len(v["wk"]) for v in a.values())
    return same, wrong, stale, missing, total


def check_body(body, raw=""):
    """ONE REGION's CLASS AND ITS EVIDENCE.

    Returns `(cls, detail)` where `cls` is one of GENERATED / DRIFTED / FROZEN /
    UNDECLARED / REFUSED, and `detail` is the evidence.
    """
    decl = declaration(body)
    if decl is None:
        m = HEADER_DECL.search(raw) if raw else None
        why = ("the region names no generator in the machine-readable form, so the census "
               "cannot tell a generated value from a frozen one")
        if m and (ROOT / m.group(1)).is_file():
            why += (f"; the file's own HEADER names {m.group(1)}, and that generator writes "
                    f"the WHOLE FILE, so the region is not what it emits")
        return "UNDECLARED", why
    gen, args = decl
    if not (ROOT / gen).is_file():
        return "FROZEN", f"the region names {gen} and THAT FILE IS GONE"
    emission, err = emit(gen, args)
    if emission is None:
        return "REFUSED", err
    same, wrong, stale, missing, total = compare(body, emission)
    detail = (f"records={total} same={same} wrong={wrong} stale={stale} missing={missing} "
              f"generator={gen} {' '.join(args)}")
    if emission == body:
        return "GENERATED", detail
    return "DRIFTED", detail


#: THE WORSE OF TWO CLASSES, AND THE ORDER IS BY SEVERITY.
SEVERITY = {"GENERATED": 0, "UNDECLARED": 1, "REFUSED": 2, "FROZEN": 3, "DRIFTED": 4}


def check_file(path, raw):
    """A FILE's CLASS: THE WORST OF ITS REGIONS'."""
    worst = (None, "")
    for body in region_bodies(raw):
        cls, detail = check_body(body, raw)
        if worst[0] is None or SEVERITY[cls] > SEVERITY[worst[0]]:
            worst = (cls, detail)
    return worst


def main():
    ap = argparse.ArgumentParser(description="a generated region against the generator it names")
    ap.add_argument("--file", help="check this file's region instead of walking the tree")
    ns = ap.parse_args()

    if ns.file:
        p = Path(ns.file).resolve()
        raw = p.read_text(encoding="utf-8", errors="replace")
        targets = [(p, raw)]
    else:
        targets = walk_regions()

    print(f"PORT                : {ROOT}")
    print(f"REGIONS FOUND       : {len(targets)} (a WALK over the tree, markers by the file's "
          f"own text)")
    declared = undeclared = 0
    bad = []
    for p, raw in targets:
        rel = os.path.relpath(p, ROOT)
        cls, detail = check_file(p, raw)
        if cls == "UNDECLARED":
            undeclared += 1
            print(f"  {rel}: UNDECLARED -- {detail}")
            continue
        declared += 1
        print(f"  {rel}: {cls} -- {detail}")
        if cls in ("DRIFTED", "FROZEN", "REFUSED"):
            bad.append((rel, cls))
    print(f"DECLARED REGIONS    : {declared}")
    print(f"UNDECLARED REGIONS  : {undeclared}   (a region that names nobody -- reported, and "
          f"NOT counted as frozen, because the census cannot see it)")
    if bad:
        print(f"\n== FAIL: {len(bad)} region(s) that are not what their generator emits")
        for rel, cls in bad:
            print(f"  {cls}: {rel}")
        return 1
    print("\n== PASS: every declared region is what its generator emits")
    return 0


# ---------------------------------------------------------------------------
# THE PLANT, THE CONTROL, AND THE TWO WRONG SHAPES OF A COMMENT-ONLY EDIT.
# ---------------------------------------------------------------------------
def _load_port_compile():
    """`checks/port-compile-gate.py` BY PATH, for its `strip_comments()`.

    The stripper is that file's, and it knows that a `#` inside a string is not a comment.
    A second copy of it here would be a second copy of the question, and the two would
    drift.
    """
    spec = importlib.util.spec_from_file_location(
        "port_compile", ROOT / "checks" / "port-compile-gate.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _code_only(text):
    """The file with every comment REMOVED and every blank line DROPPED.

    **THE BLANK-LINE DROP IS WHAT MAKES THE PROOF COVER A WHOLE-LINE COMMENT**, and it is
    copied from `gates/ptx_render_census-gate.py`'s own `_code_only`, which copied it from
    `checks/port-compile-gate.py`'s `strip_comments()`.  A comment on its own line
    contributes a line that is EMPTY once the comment is stripped, and comparing LINE LISTS
    would call that "not comment-only" -- which is the most comment-only edit there is.
    """
    pc = _load_port_compile()
    return "\n".join(l for l in pc.strip_comments(text).split("\n") if l.strip())


def plant() -> int:
    """THE PLANT IS A TEXT EDIT ON A COPY OF THE LIVE FILE, AND NEVER A READ OF HEAD.

    THE PLANT changes ONE `want` VALUE in the port's own region, and the census MUST GO
    RED -- a region that no longer matches its generator's output.  THE CONTROL is a
    comment on a line that carries ONE statement, OUTSIDE the region, and it must move
    NOTHING.

    THE TWO WRONG SHAPES ARE MEASURED, NOT ASSUMED, because a control that edits more than
    it meant to is not a control:

      SHAPE A -- a comment BETWEEN the two parts of a line that carries two parts DELETES
      the second part.  In bend a `#` runs to the end of the line, so a comment inserted
      between a list opener and its first element swallows the element, and the file still
      COMPILES -- which is the dangerous part: the comment-only proof is what catches it,
      and the compiler does not.

      SHAPE B -- a whole-line comment AT COLUMN 0 does NOT break a bend file, and the
      PROOF IS `_code_only`: the code is byte-identical, so the file cannot behave
      differently, so it cannot break.
    """
    targets = [(p, raw) for p, raw in walk_regions() if PLANT_ANCHOR in raw]
    if not targets:
        print(f"REFUSED: no region's declaration is {PLANT_ANCHOR!r}. THE PLANT IS A TEXT EDIT "
              f"ON THE WORKING TREE, so an anchor that moved means the plant must be "
              f"re-anchored -- NOT that it should fall back to reading git.")
        return 3
    path, raw = targets[0]
    body = region_body(raw)
    # THE ANCHOR IS A `want` VALUE, AND IT IS CHOSEN FROM THE LIVE TEXT -- so the plant
    # edits the bytes that are actually there.
    m = WT.search(body)
    if not m:
        print("REFUSED: the region holds no `Wt` record to plant into.")
        return 3
    planted_value = m.group(0).replace(m.group(2), "%PLANTED_0")
    plant_text = raw.replace(m.group(0), planted_value, 1)
    if plant_text == raw:
        print("REFUSED: the plant did not change the file, so it planted nothing.")
        return 3

    # THE CONTROL: a comment on a line that carries ONE statement, OUTSIDE the region.
    head = raw[:raw.index(BEGIN)]
    anchor = None
    for line in head.splitlines():
        if line.startswith("import ") and " as " in line:
            anchor = line
            break
    if anchor is None:
        print("REFUSED: no one-statement import line to comment on.")
        return 3
    control_text = raw.replace(anchor, anchor + "  # A COMMENT-ONLY LINE", 1)

    # SHAPE A: a comment BETWEEN the list opener and its first element, ON THE SAME LINE --
    # so the `#` swallows the element, and the list still COMPILES with one fewer member.
    shape_a_text = raw.replace("   [Wk{", "   [  # A COMMENT INSIDE THE LIST", 1)
    # SHAPE B: a whole-line comment at column 0.
    shape_b_text = raw.replace(BEGIN, "# A WHOLE-LINE COMMENT AT COLUMN 0\n" + BEGIN, 1)
    # THE ROT: the region names a generator and THE GENERATOR IS GONE.  This is the class
    # that used to be a LABEL, and it has to be able to FIRE -- so it gets a case.
    frozen_text = raw.replace(PLANT_ANCHOR, "# GENERATOR gates/ptx_render_census-gen-that-is-gone.py --port", 1)

    cases = [
        ("PLANT (one want value changed)", plant_text, "DRIFTED"),
        ("CONTROL (a comment, outside the region)", control_text, "GENERATED"),
        ("THE ROT (the named generator is gone)", frozen_text, "FROZEN"),
        ("WRONG-SHAPE-A (a comment inside a list)", shape_a_text, None),
        ("WRONG-SHAPE-B (a whole-line comment)", shape_b_text, None),
    ]
    bad = 0
    try:
        for name, text, want_cls in cases:
            SCRATCH.write_text(text)
            sraw = SCRATCH.read_text()
            cls, detail = check_file(SCRATCH, sraw)
            same_code = _code_only(text) == _code_only(raw)
            print(f"{name:<44} class={cls:<10} comment-only={same_code!s:<5} {detail}")
            if want_cls is not None and cls != want_cls:
                print(f"  THE {'PLANT' if want_cls == 'DRIFTED' else 'CONTROL'} DID NOT HOLD: "
                      f"expected {want_cls} and the census said {cls}.")
                bad += 1
            if name.startswith("THE ROT") and cls != "FROZEN":
                print("  THE ROT DID NOT FIRE: a region whose generator is gone is FROZEN, and "
                      "a class that cannot fire is a label.")
                bad += 1
            if name.startswith("WRONG-SHAPE-A") and same_code:
                print("  THE WRONG SHAPE DID NOT MISBEHAVE: it was comment-only after all, so it "
                      "is not a demonstration of anything.")
                bad += 1
            if name.startswith("WRONG-SHAPE-B") and not same_code:
                print("  THE WRONG SHAPE CHANGED THE CODE: a whole-line comment must not, and "
                      "this is the shape that proves the blank-line drop is needed.")
                bad += 1
    finally:
        SCRATCH.unlink(missing_ok=True)
    print(f"\n=== plant: {'FAIL' if bad else 'PASS'}: {bad} problem(s) ===")
    return 1 if bad else 0


if __name__ == "__main__":
    if "--plant" in sys.argv:
        sys.exit(plant())
    sys.exit(main())
