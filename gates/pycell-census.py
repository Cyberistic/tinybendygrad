#!/usr/bin/env python3
"""pycell-census.py -- THE CENSUS OF THE PORT's `py=` CELLS, CLASSIFIED BY **PROVENANCE**.

    .venv/bin/python gates/pycell-census.py                 # the census, printed
    .venv/bin/python gates/pycell-census.py --rows OUT.rows # the census as rows
    .venv/bin/python gates/pycell-census.py --prove         # the 224 KNOWN CASES (pinned blob)
    .venv/bin/python gates/pycell-census.py --plan          # the population and the totals only

WHAT A `py=` CELL IS
--------------------
Every gated row in the port is `<name> = [<BEND>]   py=[<CPYTHON>]`.  The `py=` half is
supposed to be CPython's own answer, printed BESIDE the port's, so the two can be compared.
**A `py=` CELL IS ONE `py=` SLOT** -- the value that fills it, in one row.

THE CLASSIFICATION IS BY PROVENANCE, AND THE OLD ONE WAS BY SYNTAX
-------------------------------------------------------------------
The census that came before this one classified a cell by the SHAPE of the argument that
reaches the `py=` slot: a quoted string was a LITERAL, a call was DERIVED, a bare identifier
was a PARAM.  **THAT IS A CLASSIFICATION OF THE SOURCE TEXT, NOT OF THE VALUE.**

**MEASURED, AND IT WAS WRONG BY AT LEAST 224 CELLS IN ONE FILE.**  The unit that landed
`ops_dsp` named the blind spot verbatim: *"it classifies by 'is it a quoted string', so
`ops_dsp`'s 224 number/bool cells were counted DERIVED when every one was a transcription."*
A NUMBER TYPED BY HAND IS A TRANSCRIPTION WHATEVER THE CALL SHAPE SAYS.  The old rule read a
`0` as "not a quoted string, therefore derived", and 224 of them in `ops_dsp.bend` alone were
text somebody typed.  The file agreed with itself and was WRONG on thirty rows.

SO THE RULE HERE IS ABOUT WHERE THE VALUE CAME FROM
---------------------------------------------------
    TRANSCRIPTION   the value was TYPED.  Its provenance chain reaches a LITERAL -- a number,
                    a boolean, or a string -- with nothing in between that the PORT computes.
                    A transcription has NO GENERATOR: it cannot see CPython move, and it
                    cannot see the PORT move either.
    DERIVED         the value is COMPUTED FROM THE PORT's OWN STATE: the provenance chain
                    reaches a CALL into the port, so the port executes it and the value moves
                    when the port moves.
    PARAM           the chain could not be resolved.  **REPORTED, NEVER COUNTED AS EITHER** --
                    a denominator dressed as a verdict is the defect this file exists to
                    avoid.

TWO CLAUSES THE BRIEF NAMES, AND HOW THEY ARE DECIDED
------------------------------------------------------
    "A CELL WHOSE VALUE IS A CONSTANT FOLDED FROM A CONSTANT IS A TRANSCRIPTION."
        A call whose ARGUMENTS are all source-constants AND whose CALLEE IS NOT A PORT
        DEF is foldable from the source text alone: `U32.show(5)` is `"5"` whatever the
        port does.  **THE PORT'S OWN DEFS ARE A DISCOVERED POPULATION** -- every `def NAME`
        in every `.bend` file under the port root -- so "is this callee the port's own" is
        a question about the tree and not a hand list.  A call into a port def is DERIVED
        even when every argument is a literal: `rpc_sc(0, 0, 0, 0)` is the PORT's answer,
        and the port's answer moves when the port's code moves.

    "AND SO IS ONE WHOSE VALUE COMES FROM A `py=`-SLOT PARAMETER THAT THE CALLER FILLS
     WITH A LITERAL."
        A builder's `py=` slot is usually a PARAMETER; the value arrives at the CALL SITE.
        So the resolution follows the parameter to the call that fills it, and to that
        call's own enclosing def, and so on.  A chain that ends at a literal is a
        TRANSCRIPTION; a chain that ends at a port call is DERIVED.

THE POPULATION IS DISCOVERED, NEVER NAMED
-----------------------------------------
`os.walk(root)` + `endswith(".bend")` -- **never `glob`, which returns `[]` when `.bend`
files are on disk** (`AGENTS.md`, DOCTRINE 1).  The port's own DEFS are discovered the same
way, for the constant-fold clause.

WHAT THIS CANNOT SEE, AND SAYS SO
---------------------------------
A literal that was GENERATED by an oracle and pasted in is indistinguishable from one typed
by hand: both are literals.  **PROVENANCE IS NOT AUTHORSHIP.**  This file counts cells whose
value was WRITTEN DOWN; whether a writer was a person or a script is a separate question,
and the answer to it does not change the rot: a pasted-in literal cannot see CPython move
either.  The DISAGREEMENT count -- a transcription whose value differs from the port's own
-- is measured by the GATE, which RUNS the port and compares the two halves of each row.
"""
from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent

#: The three classes.  `PARAM` is a RESOLUTION FAILURE and is never counted as either.
TRANSCRIPTION = "TRANSCRIPTION"
DERIVED = "DERIVED"
PARAM = "PARAM"

#: The FORMS a transcription can take.  They are reported separately because a NUMBER typed
#: by hand and a STRING typed by hand fail differently.
LITERAL_STRING = "LITERAL-STRING"
LITERAL_NUMBER = "LITERAL-NUMBER"
LITERAL_BOOL = "LITERAL-BOOL"
LITERAL_NULL = "LITERAL-NULL"
CONSTANT_FOLD = "CONSTANT-FOLD"
PORT_CALL = "PORT-CALL"
FOREIGN_CALL = "FOREIGN-CALL"

# ---------------------------------------------------------------- the lexer


def scan(text):
    """`(code_without_comments, string_spans)`.

    A string span is `(start, end)` of the CONTENT of a double-quoted literal.  String
    CONTENT IS KEPT: the `py=` slot of a row builder lives inside a string literal, and
    blanking literals would erase the thing measured.
    """
    spans = []
    i, n = 0, len(text)
    out = []
    while i < n:
        c = text[i]
        if c == "#":
            j = text.find("\n", i)
            j = n if j < 0 else j
            out.append(" " * (j - i))
            i = j
        elif c == '"':
            j = i + 1
            while j < n:
                if text[j] == "\\":
                    j += 2
                    continue
                if text[j] == '"':
                    break
                j += 1
            spans.append((i + 1, j))
            out.append(text[i:j + 1])
            i = j + 1
        else:
            out.append(c)
            i += 1
    return "".join(out), spans


def split_args(s):
    """Split a call's argument text on top-level commas."""
    args, depth, cur, i, n = [], 0, [], 0, len(s)
    instr = False
    while i < n:
        c = s[i]
        if instr:
            cur.append(c)
            if c == "\\":
                if i + 1 < n:
                    cur.append(s[i + 1])
                    i += 2
                    continue
            elif c == '"':
                instr = False
            i += 1
            continue
        if c == '"':
            instr = True
            cur.append(c)
            i += 1
            continue
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        if c == "," and depth == 0:
            args.append("".join(cur).strip())
            cur = []
            i += 1
            continue
        cur.append(c)
        i += 1
    tail = "".join(cur).strip()
    if tail or args:
        args.append(tail)
    return args


def match_close(s, start):
    """Index just past the bracket that closes the one at `start`."""
    pairs = {"(": ")", "[": "]", "{": "}"}
    opener = s[start]
    closer = pairs[opener]
    depth, i, n, instr = 0, start, len(s), False
    while i < n:
        c = s[i]
        if instr:
            if c == "\\":
                i += 2
                continue
            if c == '"':
                instr = False
        elif c == '"':
            instr = True
        elif c == opener:
            depth += 1
        elif c == closer:
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    return n


def expr_at(s, i):
    """`(text, end_index)` of the expression starting at `s[i]`."""
    depth, j, n, instr = 0, i, len(s), False
    while j < n:
        c = s[j]
        if instr:
            if c == "\\":
                j += 2
                continue
            if c == '"':
                instr = False
        elif c == '"':
            instr = True
        elif c in "([{":
            depth += 1
        elif c in ")]}":
            if depth == 0:
                break
            depth -= 1
        elif c == "," and depth == 0:
            break
        j += 1
    return s[i:j].strip(), j


DEF_RE = re.compile(r"^def\s+([A-Za-z_][A-Za-z0-9_.]*)\s*\(", re.M)
PARAM_RE = re.compile(r"([A-Za-z_][A-Za-z0-9_]*)\s*:")


def defs_of(code):
    """`(name, params, body_start, body_end)` for every top-level def."""
    out = []
    for m in DEF_RE.finditer(code):
        name = m.group(1)
        open_paren = m.end() - 1
        close = match_close(code, open_paren)
        params = [p.group(1) for p in PARAM_RE.finditer(code[open_paren + 1:close - 1])]
        tail_start = close
        stop = len(code)
        for stopre in (re.compile(r"^def\s", re.M), re.compile(r"^type\s", re.M),
                       re.compile(r"^import\s", re.M)):
            mm = stopre.search(code, tail_start)
            if mm and mm.start() < stop:
                stop = mm.start()
        out.append((name, params, tail_start, stop))
    return out


# ------------------------------------------------- the py slot of a builder

#: The row TEMPLATE.  A def whose body carries this is a ROW BUILDER, and the expression
#: after it fills the `py=` slot.  **THE TEMPLATE IS THE DISCOVERY**, and it is a SHAPE in
#: the SOURCE, not a name in a list: `AGENTS.md`, "a row builder is a def whose body carries
#: the row TEMPLATE".
PY_AFTER = re.compile(r'py=\["\s*,\s*')
#: The same template, with the slot's content INSIDE the literal -- a row whose whole text
#: is one string, `... py=[...]`.
PY_INLINE = re.compile(r'py=\[')


def template_py_expr(body):
    """The expression that fills the `py=` slot of a row TEMPLATE, or None."""
    m = PY_AFTER.search(body)
    if not m:
        return None
    return expr_at(body, m.end())[0]


def param_of_expr(expr, params):
    """The parameter an expression reads, if the expression is one."""
    e = expr.strip()
    if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", e):
        return e if e in params else None
    m = re.fullmatch(r"[A-Za-z_][A-Za-z0-9_.]*\((.*)\)", e, re.S)
    if m:
        inner = m.group(1).strip()
        if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", inner) and inner in params:
            return inner
    return None


def resolve_to_param(ident, params, body):
    """Map a binder name in the body back to one of the builder's parameters.

    `match ts ps:` / `case h <> +t p <> +pt :` binds `p` out of `ps`.
    """
    for m in re.finditer(r"^\s*match\s+(.+?):\s*$", body, re.M):
        scruts = m.group(1).split()
        if len(scruts) < 2:
            continue
        tail = body[m.end():]
        cm = re.search(r"^\s*case\s+(.+?)\s*:\s*$", tail, re.M)
        if not cm:
            continue
        groups = re.findall(
            r"([A-Za-z_][A-Za-z0-9_]*(?:\s*<>\s*\+?[A-Za-z_][A-Za-z0-9_]*)?)", cm.group(1))
        gi = 0
        for g in groups:
            head = g.split("<>")[0].strip().lstrip("+")
            if head == ident and gi < len(scruts):
                scrut = scruts[gi].strip()
                if scrut in params:
                    return scrut
            gi += 1
    return ident if ident in params else None


def local_exprs(body):
    """`+name = expr` bindings in a def body."""
    out = {}
    for m in re.finditer(r"^\s*\+([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.+?)\s*$", body, re.M):
        out[m.group(1)] = m.group(2).strip()
    return out


def py_param_of(name, params, body, known):
    """The parameter of `name` that reaches the `py=` slot, or None."""
    expr = template_py_expr(body)
    if expr is not None:
        p = param_of_expr(expr, params)
        if p:
            return p
        return None
    # a delegating builder: it calls another builder and forwards one of its args
    for other, oidx in known.items():
        for m in re.finditer(r"(?<![A-Za-z0-9_.])" + re.escape(other) + r"\s*\(", body):
            close = match_close(body, m.end() - 1)
            args = split_args(body[m.end():close - 1])
            if oidx < len(args):
                cand = args[oidx].strip()
                mm = re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", cand)
                if mm:
                    return cand
    return None


def call_sites(code, name, defs):
    """`(arglist_text, enclosing_def_name)` for every call of `name`."""
    out = []
    pat = re.compile(r"(?<![A-Za-z0-9_.])" + re.escape(name) + r"\s*\(")
    for m in pat.finditer(code):
        pre = code[max(0, m.start() - 300):m.start()]
        if re.search(r"def\s+[A-Za-z0-9_.]*\s*$", pre):
            continue
        close = match_close(code, m.end() - 1)
        encl = None
        for (dn, _p, ds, de) in defs:
            if ds <= m.start() < de:
                encl = dn
        out.append((code[m.end():close - 1], encl))
    return out


# ================================================================ THE PROVENANCE

NUMBER_RE = re.compile(r"-?\d+(?:\.\d+)?$")
IDENT_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*$")
CALL_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_.]*)\((.*)\)$", re.S)
LIST_RE = re.compile(r"^\[(.*)\]$", re.S)


def literal_kind(expr):
    """The FORM of a literal, or None when the expression is not a literal.

    **BEND WRITES ITS BOOLEANS `True{}` AND `False{}`** -- a constructor call with an empty
    record -- and a rule that knows only the bare words reads a boolean cell as a CALL and
    then as UNRESOLVED.  MEASURED: that is 93 of the 224 KNOWN CASES, and every one of them
    is a transcription.
    """
    e = expr.strip()
    if len(e) >= 2 and e.startswith('"') and e.endswith('"'):
        return LITERAL_STRING
    if e in ("True", "False", "True{}", "False{}"):
        return LITERAL_BOOL
    if e in ("None", "None{}"):
        return LITERAL_NULL
    if NUMBER_RE.match(e):
        return LITERAL_NUMBER
    return None


def unescape(text):
    """The text a Bend string literal CARRIES, as the port prints it.

    **A LITERAL'S VALUE IS NOT ITS SOURCE TEXT.**  MEASURED: `renderer/nir_llvmir.bend`
    writes `"fence syncscope(\\"workgroup\\") release"` and the port PRINTS
    `fence syncscope("workgroup") release`, so a dead-form check that compares the source
    text to the emitted text calls a row that IS emitted a dead form.  The same is true of
    `\\n`: `uop/render.bend` writes a literal whose newlines are `\\n` and the port prints
    real newlines.
    """
    out = []
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c == "\\" and i + 1 < n:
            out.append({"n": "\n", "t": "\t", "r": "\r", '"': '"', "\\": "\\",
                        "'": "'", "0": "\0"}.get(text[i + 1], text[i + 1]))
            i += 2
            continue
        out.append(c)
        i += 1
    return "".join(out)


def literal_value(expr):
    """The VALUE a literal carries, as the text it prints."""
    e = expr.strip()
    kind = literal_kind(e)
    if kind == LITERAL_STRING:
        return unescape(e[1:-1])
    if kind == LITERAL_BOOL:
        return e[:-2] if e.endswith("{}") else e
    return e


class Provenance:
    """THE RESOLVER.  It answers one question: where did this value come from?"""

    def __init__(self, ctx):
        self.ctx = ctx

    def resolve(self, expr, encl, depth=0):
        """`(kind, form, detail)` for one expression, in the scope of the def `encl`."""
        if depth > 12:
            return PARAM, "UNRESOLVED", "DEPTH"
        e = expr.strip()
        lit = literal_kind(e)
        if lit:
            return TRANSCRIPTION, lit, literal_value(e)
        m = CALL_RE.match(e)
        if m:
            callee, inner = m.group(1), m.group(2)
            args = split_args(inner)
            if callee in self.ctx.port_defs or callee.split(".")[-1] in self.ctx.port_defs:
                return DERIVED, PORT_CALL, callee
            if args and all(literal_kind(a) is not None for a in args if a != ""):
                return TRANSCRIPTION, CONSTANT_FOLD, callee
            return DERIVED, FOREIGN_CALL, callee
        lm = LIST_RE.match(e)
        if lm:
            items = [x for x in split_args(lm.group(1)) if x.strip() != ""]
            kinds = {self.resolve(x, encl, depth + 1)[0] for x in items}
            if TRANSCRIPTION in kinds:
                form = LITERAL_STRING if all(literal_kind(x) is not None for x in items) \
                    else CONSTANT_FOLD
                return TRANSCRIPTION, form, e[:60]
            if kinds == {DERIVED}:
                return DERIVED, FOREIGN_CALL, e[:60]
            return PARAM, "UNRESOLVED", e[:60]
        if IDENT_RE.match(e):
            return self.resolve_ident(e, encl, depth)
        return PARAM, "UNRESOLVED", e[:60]

    def resolve_ident(self, name, encl, depth):
        """Follow an identifier: a local binding, then a parameter, then nothing."""
        ctx = self.ctx
        if encl is None:
            return PARAM, "UNRESOLVED", name
        locs = ctx.locals.get(encl, {})
        if name in locs:
            return self.resolve(locs[name], encl, depth + 1)
        params = ctx.params.get(encl, [])
        if name not in params:
            return PARAM, "UNRESOLVED", name
        idx = params.index(name)
        sites = ctx.call_sites(encl)
        if not sites:
            return PARAM, "UNRESOLVED", name
        found = []
        for (argtext, sub_encl) in sites:
            args = split_args(argtext)
            if idx >= len(args):
                continue
            found.append(self.resolve(args[idx], sub_encl, depth + 1))
        if not found:
            return PARAM, "UNRESOLVED", name
        kinds = {k for (k, _f, _d) in found}
        if kinds == {TRANSCRIPTION}:
            return TRANSCRIPTION, found[0][1], found[0][2]
        if kinds == {DERIVED}:
            return DERIVED, found[0][1], found[0][2]
        # A chain that resolves two ways is REPORTED as ambiguous, and it is counted as a
        # TRANSCRIPTION when ANY resolution says so: the rot class is the one that must not
        # be missed, and an ambiguity is not a licence to assume the good case.
        if TRANSCRIPTION in kinds:
            return TRANSCRIPTION, found[0][1], found[0][2]
        return PARAM, "UNRESOLVED", name


class FileCtx:
    """Everything the resolver needs about ONE `.bend` file."""

    def __init__(self, path, raw, port_defs):
        self.path = path
        self.raw = raw
        self.code, self.spans = scan(raw)
        self.defs = defs_of(self.code)
        self.bodies = {n: self.code[s:e] for (n, _p, s, e) in self.defs}
        self.params = {n: p for (n, p, _s, _e) in self.defs}
        self.locals = {n: local_exprs(b) for (n, b) in self.bodies.items()}
        self.port_defs = port_defs
        self.aliases = import_aliases(path, self.code)
        self._sites: dict[str, list] = {}

    def call_sites(self, name):
        if name not in self._sites:
            self._sites[name] = call_sites(self.code, name, self.defs)
        return self._sites[name]


IMPORT_RE = re.compile(r"^import\s+(\S+)(?:\s+as\s+(\S+))?\s*$", re.M)


def import_aliases(path, code):
    """`{alias: the file it names}` for the imports of ONE file.

    **THE IMPORT GRAPH IS WHY A PER-FILE CENSUS IS A CENSUS OF THE WRONG POPULATION.**
    MEASURED: `tinybendygrad/renderer/tc_ptx.bend` imports `./tc.bend as T` and calls
    `T.rd(...)` -- `tc.bend`'s ROW BUILDER -- so `tc_ptx.bend` emits `py=` rows that no
    per-file scan of `tc_ptx.bend` can see, because `tc_ptx.bend` carries no row TEMPLATE of
    its own.  A census that reads one file at a time reports 27 rows of the port and misses
    the file that makes them.
    """
    out = {}
    base = os.path.dirname(path)
    for m in IMPORT_RE.finditer(code):
        target, alias = m.group(1), m.group(2)
        if not target.endswith(".bend"):
            continue
        resolved = os.path.normpath(os.path.join(base, target))
        out[alias or os.path.basename(target)[:-5]] = resolved
    return out


# ================================================================ THE CENSUS


def bend_files(root):
    """The population: every `.bend` file under `root`, DISCOVERED by a walk.

    **`os.walk` and never `glob`** -- `glob('*.bend')` returns `[]` when `.bend` files are
    on disk, and this tree has measured that (`AGENTS.md`, DOCTRINE 1).
    """
    out = []
    for d, _dn, fn in os.walk(root):
        for f in sorted(fn):
            if f.endswith(".bend"):
                out.append(os.path.join(d, f))
    out.sort()
    return out


def port_def_names(files):
    """Every `def NAME` in the port -- the DISCOVERED population the constant-fold clause
    asks "is this callee the port's own?" against.

    **BOTH THE FULL NAME AND ITS LAST COMPONENT ARE KEPT**, because the tree's defs are
    namespaced (`def entry.method_ok`) and the CALL SITE writes the full name
    (`entry.method_ok(...)`) while a BARE call writes the last one.  MEASURED: keeping only
    the last component made 44 of `ops_dsp.bend`'s cells read as CONSTANT-FOLDs, because
    `entry.method_ok` was not found and the call fell through to the fold clause -- and
    `entry.method_ok` IS a port def, so those cells are the port's own answer.
    """
    names = set()
    for path in files:
        raw = open(path, encoding="utf-8", errors="replace").read()
        code, _spans = scan(raw)
        for (name, _p, _s, _e) in defs_of(code):
            names.add(name)
            names.add(name.split(".")[-1])
    return names


def inline_literal_cells(code, spans):
    """Cells whose `py=` content is typed INTO a string literal.

    A builder TEMPLATE's literal ENDS at `py=[` (the content comes from the next
    expression), so its content is empty and it is not a cell.
    """
    cells = []
    for (a, b) in spans:
        lit = code[a:b]
        idx = lit.find("py=[")
        if idx < 0:
            continue
        content = lit[idx + 4:]
        if "]" not in content:
            continue
        content = content[:content.index("]")]
        if content.strip() == "":
            continue
        cells.append(content)
    return cells


def slot_value(body, params, locs):
    """`(kind, payload)` for a row builder's `py=` slot.

    `kind` is one of

      `PARAM`    the slot's value arrives from the CALL SITE, through the named parameter.
      `INSIDE`   the slot's value is COMPUTED INSIDE the builder; `payload` is the
                 expression that computes it.
      `LITERAL`  the slot's value is TYPED INTO the template; `payload` is its text.

    **THE TEMPLATE'S EXPRESSION IS NOT THE VALUE.**  The template reads
    `"]   py=[" , Bool.show(b) , "]"`, and the VALUE is `b` -- the formatter's argument --
    so a builder whose value is a typed number is a TRANSCRIPTION even though the template
    holds a CALL.  MEASURED: `runtime/ops_dsp.bend`'s `lrow` computes its value in a local
    (`+s = String.join(...)`) and the older census MISSED every cell it emits, because it
    looked for the value in the builder's PARAMETERS and found neither a parameter nor a
    delegation.  `INSIDE` is that case, and it is 161 of `ops_dsp.bend`'s cells.
    """
    expr = template_py_expr(body)
    if expr is None:
        return None
    inner = expr
    m = re.fullmatch(r"[A-Za-z_][A-Za-z0-9_.]*\((.*)\)", expr, re.S)
    if m and re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", m.group(1).strip()):
        inner = m.group(1).strip()
    if inner in params:
        return ("PARAM", inner)
    if inner in locs:
        return ("INSIDE", locs[inner])
    lit = literal_kind(inner)
    if lit:
        return ("LITERAL", literal_value(inner))
    return ("INSIDE", inner)


def census_file(ctx):
    """The census of ONE file's own builders -- the per-file half of `census_port`."""
    return census_in_file(ctx, discover_builders({ctx.path: ctx}))


def census_in_file(ctx, builders):
    """`(rows, per_file)` -- the cells of ONE file, given the port's builder registry.

    `rows` is a list of `(kind, form, builder, ordinal, value, name)`.
    """
    prov = Provenance(ctx)
    skip = {b.name for (_key, b) in builders.items() if _key[0] == ctx.path}
    rows = []
    counters: dict[str, int] = {}
    for b in builders.values():
        spelling = b.spelling(ctx.path, ctx.aliases)
        if spelling is None:
            continue
        for (argtext, encl) in ctx.call_sites(spelling):
            if encl is not None and encl in skip:
                continue
            args = split_args(argtext)
            nm = "<no-name>"
            if b.kind == "PARAM" and b.index != 0 and args:
                # THE NAME IS THE BUILDER'S FIRST ARGUMENT, and it is the first argument
                # ONLY when the `py=` slot is not itself the first parameter: `r_sdb(py)` is
                # a builder whose ONLY parameter is the value, so it has no name argument
                # and reading args[0] as a name reads the VALUE as a name.
                nm = args[0].strip()
            elif b.kind == "INSIDE" and args:
                nm = args[0].strip()
            if b.kind == "PARAM":
                if b.index >= len(args):
                    continue
                kind, form, detail = prov.resolve(args[b.index], encl)
            elif b.kind == "INSIDE":
                kind, form, detail = prov.resolve(b.payload, encl)
            else:
                kind, form, detail = (TRANSCRIPTION, LITERAL_STRING, b.payload)
                nm = "<template>"
            ordinal = counters.get(b.name, 0)
            counters[b.name] = ordinal + 1
            rows.append((kind, form, b.name, ordinal, detail, nm))
    # Rows whose whole text is ONE string literal: the `py=` content is typed into it.
    for content in inline_literal_cells(ctx.code, ctx.spans):
        rows.append((TRANSCRIPTION, LITERAL_STRING, "<inline>", 0, content, "<inline>"))
    return rows


class Builder:
    """A ROW BUILDER, wherever it lives."""

    def __init__(self, file, name, kind, payload, index=None):
        self.file = file          # the file that DEFINES it
        self.name = name          # its name as DEFINED (`rd`, `entry.method_ok`)
        self.kind = kind          # 'PARAM' | 'INSIDE'
        self.payload = payload    # the parameter's name, or the value expression
        self.index = index        # the parameter's index, when kind == 'PARAM'

    def spelling(self, from_file, aliases):
        """How this builder is CALLED from `from_file`, or None when it is not visible.

        `aliases` maps an ALIAS NAME to the file it names, so the lookup here is the
        REVERSE: the alias under which `from_file` can see `self.file`.
        """
        if from_file == self.file:
            return self.name
        alias = next((a for a, f in aliases.items() if f == self.file), None)
        if alias is None:
            return None
        return alias + "." + self.name

    def key(self):
        return (self.file, self.name)


def discover_builders(ctxs):
    """Every ROW BUILDER in the port, and every DELEGATING builder.

    **A BUILDER IS DISCOVERED BY ITS TEMPLATE**, and a DELEGATING one by the fact that it
    CALLS a builder and forwards one of its arguments.  Neither is a name in a list.
    """
    builders = {}
    for path, ctx in ctxs.items():
        for (name, params, _s, _e) in ctx.defs:
            sv = slot_value(ctx.bodies[name], params, ctx.locals.get(name, {}))
            if sv is None:
                continue
            kind, payload = sv
            if kind == "LITERAL":
                builders[(path, name)] = Builder(path, name, "LITERAL", payload)
            elif kind == "PARAM":
                builders[(path, name)] = Builder(path, name, "PARAM", payload,
                                                index=params.index(payload))
            else:
                builders[(path, name)] = Builder(path, name, "INSIDE", payload)
    # DELEGATING builders: a def with no template of its own that calls a builder and
    # forwards one of its arguments.  Four rounds, because a chain can be four deep.
    for _ in range(4):
        for path, ctx in ctxs.items():
            for (name, params, _s, _e) in ctx.defs:
                if (path, name) in builders:
                    continue
                fwd = _forwarded_arg(ctx, name, builders)
                if fwd is None:
                    continue
                arg, owner = fwd
                if arg in params:
                    builders[(path, name)] = Builder(path, name, "PARAM", arg,
                                                    index=params.index(arg))
                elif arg in ctx.locals.get(name, {}):
                    builders[(path, name)] = Builder(path, name, "INSIDE",
                                                    ctx.locals[name][arg])
    return builders


def _forwarded_arg(ctx, name, builders):
    """`(the argument, the builder it is forwarded to)` for a DELEGATING def, or None."""
    body = ctx.bodies[name]
    for (bpath, bname), b in builders.items():
        if b.kind != "PARAM":
            continue
        spelling = b.spelling(ctx.path, ctx.aliases)
        if spelling is None:
            continue
        for m in re.finditer(r"(?<![A-Za-z0-9_.])" + re.escape(spelling) + r"\s*\(", body):
            close = match_close(body, m.end() - 1)
            args = split_args(body[m.end():close - 1])
            if b.index < len(args):
                cand = args[b.index].strip()
                if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", cand):
                    return cand, b
    return None


def census_port(root):
    """`(rows, per_file, files, port_defs)` -- the census over the WHOLE port.

    **THE POPULATION IS THE PORT, NOT A FILE.**  A builder may be called from a file that
    imports it (`import ./tc.bend as T`), so the census resolves every builder's call sites
    in every file that can see it.
    """
    files = bend_files(root)
    port_defs = port_def_names(files)
    ctxs = {}
    for path in files:
        raw = open(path, encoding="utf-8", errors="replace").read()
        ctxs[path] = FileCtx(path, raw, port_defs)
    builders = discover_builders(ctxs)

    all_rows = []
    per_file = {}
    for path in files:
        ctx = ctxs[path]
        rows = census_in_file(ctx, builders)
        rel = os.path.relpath(path, root)
        per_file[rel] = rows
        for (kind, form, builder, ordinal, detail, nm) in rows:
            all_rows.append({"kind": kind, "form": form, "file": rel, "builder": builder,
                             "site": ordinal, "value": str(detail), "name": str(nm)[:120]})
    all_rows.sort(key=lambda r: (r["file"], r["builder"], r["site"], r["form"], r["value"]))
    return all_rows, per_file, files, port_defs


def census_text(text, path, port_defs):
    """The census of ONE file's TEXT -- what the PROOF and the PLANT drive.

    **THE PROOF RUNS ON A PINNED BLOB, NOT ON `HEAD:`.**  A blob SHA is content-addressed
    and cannot move, so a proof that reads it cannot be defused by a later commit that
    carries the fix -- which is exactly what happened to the unit whose plant read
    `git show HEAD:` and scored green under `--falsify`.
    """
    ctx = FileCtx(path, text, port_defs)
    return census_in_file(ctx, discover_builders({path: ctx}))


def census(root):
    """`(rows, per_file, files, port_defs)` -- the whole census over the port."""
    return census_port(root)


def render(rows):
    """The `.rows` bytes: one line per cell, sorted, no timestamp.

    **THE VALUE IS TRUNCATED HERE AND NOT IN THE CENSUS.**  MEASURED: `renderer/wgsl.bend`
    carries a `py=` value of 512 characters, and a census that truncates it at 120 makes the
    DEAD-FORM check compare a prefix with a whole and call a row that IS emitted dead.
    """
    return "\n".join(
        f"kind={r['kind']} file={r['file']} builder={r['builder']} site={r['site']} "
        f"form={r['form']} value={r['value'][:120]} name={r['name']}" for r in rows) + "\n"


# ================================================================ THE ROW GRAMMAR

#: The separator between the two halves of a row.  It is the row TEMPLATE's own text
#: (`"]   py=["`), read back out of the emitted stream.
ROW_SEP = "]   py=["

#: THE `py=` HALVES THAT ARE NOT VALUES.  A row whose `py=` half is one of these
#: MARKERS has NO CPython counterpart: the port asserts that CPython has no answer
#: for that row at all, and the marker says so.
#:
#: **A MARKER IS NOT A VALUE, AND COMPARING THE TWO IS A CATEGORY ERROR.**  The ROT lane
#: asks "does the port's own answer disagree with the port's own claim about CPython?",
#: and that question has NO ANSWER for a row whose claim is "there is nothing to compare".
#: `renderer/nir_llvmir.bend`'s `f32show 240.0` is the one such row: CPython's
#: `str(240.0)` is `240.0` and the port's `F32.show(240.0)` is `240`, so there is no
#: oracle for the port's own spelling -- the port's ORACLE generates the marker, and
#: `checks/nl-gate.py` requires the port's stdout to be BYTE-IDENTICAL to that oracle's.
#:
#: **THIS IS A VOCABULARY AND NOT A POPULATION.**  Doctrine 1 is about populations of
#: PATHS -- a hand list of files is a list, and a generator's own declaration is the
#: alternative.  A vocabulary of MARKERS is a different thing: it says what a token
#: MEANS, and the census REPORTS every row that carries one, BY NAME, so a reader can
#: see each of them rather than trust a filter.
BEND_ONLY = "BEND-ONLY"
MARKERS = frozenset({BEND_ONLY})


def match_bracket(text, i):
    """The index of the `]` that closes the `[` AT `text[i]`, or -1.

    **THE ROWS ARE NOT ONE LINE EACH.**  MEASURED: `tinybendygrad/uop/render.bend` emits a
    row whose `py=` half is three lines long (`c1 = UOp.range(...)` / `ast = UOp(...)`), and
    a line-oriented parser reads 27 of that file's 42 rows and calls the other 15 "not
    rows" -- **which is how a census undercounts and calls the shortfall a finding.**  The
    halves are bracket-balanced, so the `]` that closes a half is FOUND, not guessed.
    """
    depth, j, n = 0, i, len(text)
    while j < n:
        c = text[j]
        if c == "[":
            depth += 1
        elif c == "]":
            depth -= 1
            if depth == 0:
                return j
        j += 1
    return -1


def parse_rows(text):
    """`[(name, got, want)]` -- the emitted rows, parsed by the GRAMMAR and not by lines.

    A row is `<name> = [<got>]   py=[<want>]`.  The name is the text on the row's FIRST
    line before the ` = [`, and the two halves are bracket-matched.

    **THE ` = [` INSIDE A HALF IS NOT THE ROW'S OWN.**  MEASURED: a `got` half can be
    `ast = UOp.const(3)`, so the FIRST ` = [` in the stream is inside a row, and a parser
    that starts there reads the row's INNERMOST bracket and then finds no separator.  So a
    candidate whose bracket-match is not followed by the separator is SKIPPED WHOLE -- to
    the end of its bracket -- rather than to the next ` = [`.
    """
    rows = []
    i, n = 0, len(text)
    while i < n:
        k = text.find(" = [", i)
        if k < 0:
            break
        got_end = match_bracket(text, k + 3)
        if got_end < 0:
            break
        if not text[got_end:].startswith(ROW_SEP):
            i = got_end + 1
            continue
        want_start = got_end + len(ROW_SEP)
        want_end = match_bracket(text, want_start - 1)
        if want_end < 0:
            break
        head = text[:k].rsplit("\n", 1)[-1].strip()
        rows.append((head, text[k + 4:got_end], text[want_start:want_end]))
        i = want_end + 1
    return rows


# ================================================================ THE 224 KNOWN CASES

#: THE BLOB THAT HOLDS THE 224 KNOWN CASES.  `tinybendygrad/runtime/ops_dsp.bend` at the
#: commit BEFORE the one that made its `py=` halves DERIVED.
#:
#: **A BLOB SHA IS CONTENT-ADDRESSED AND CANNOT MOVE.**  That is why this is a blob and not
#: `HEAD:` -- and `HEAD:` is EXACTLY what a unit's plant read, which is why it planted
#: nothing the moment HEAD carried the fix.  MEASURED: this blob is 6399 lines and its
#: `py=` slots carry the transcribed CPython answer as a NUMBER or a BOOLEAN -- the shape the
#: old syntactic rule read as "not a quoted string, therefore DERIVED".
OPS_DSP_OLD_BLOB = "432d34508c4d28cbb3c1af9b64a6401e7a11d104"

#: The number the brief names: the cells the OLD rule called DERIVED and that are
#: TRANSCRIPTIONS.  **THE PROOF MUST REPRODUCE IT EXACTLY.**
KNOWN_CASES = 224


def syntactic_classify(arg):
    """THE OLD RULE, KEPT SO THE DIFFERENCE CAN BE MEASURED RATHER THAN ASSERTED.

    A cell is a LITERAL if the argument at that slot is a quoted string, DERIVED if it is a
    call, and PARAM if it is a bare identifier.  **THIS IS A CLASSIFICATION OF THE SOURCE
    TEXT, NOT OF THE VALUE**, and it is the rule the brief calls blind.
    """
    a = arg.strip()
    if a.startswith('"') and a.endswith('"') and len(a) >= 2:
        return "LITERAL", 1
    if a.startswith("[") and a.endswith("]"):
        items = [x for x in split_args(a[1:-1]) if x != ""]
        if not items:
            return "DERIVED", 0
        lit = sum(1 for x in items if x.strip().startswith('"'))
        return ("LITERAL" if lit == len(items) else "DERIVED"), len(items)
    if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", a):
        return "PARAM", 1
    return "DERIVED", 1


def prove(root, blob=OPS_DSP_OLD_BLOB, verbose=True):
    """THE PROOF: the classifier MUST call the 224 KNOWN CASES TRANSCRIPTIONS.

    The blob is read by `git cat-file blob <sha>` -- a CONTENT-ADDRESSED read that no
    commit can change -- and it is the file as it stood BEFORE the fix, so the cells are
    still there.
    """
    files = bend_files(root)
    port_defs = port_def_names(files)
    try:
        text = subprocess.run(["git", "cat-file", "blob", blob], capture_output=True,
                              text=True, check=True).stdout
    except (subprocess.CalledProcessError, subprocess.SubprocessError) as e:
        print(f"PROOF REFUSED: the pinned blob {blob} is not readable: {e}", file=sys.stderr)
        return None
    rows = census_text(text, "runtime/ops_dsp.bend", port_defs)
    tally = Counter(r[0] for r in rows)
    forms = Counter(r[1] for r in rows)
    # THE OLD RULE, ON THE SAME CELLS: rebuild the old per-file classification.
    old = Counter()
    ctx = FileCtx("runtime/ops_dsp.bend", text, port_defs)
    for (name, params, _s, _e) in ctx.defs:
        sv = slot_value(ctx.bodies[name], params, ctx.locals.get(name, {}))
        if sv is None or sv[0] != "PARAM":
            continue
        idx = params.index(sv[1])
        for (argtext, encl) in ctx.call_sites(name):
            args = split_args(argtext)
            if idx >= len(args):
                continue
            kind, n = syntactic_classify(args[idx])
            old[kind] += n
    numbers = sum(v for k, v in forms.items() if k in (LITERAL_NUMBER, LITERAL_BOOL))
    if verbose:
        print(f"PROOF BLOB  : {blob}  ({len(text.splitlines())} lines, CONTENT-ADDRESSED)")
        print(f"CELLS       : {len(rows)}")
        print(f"PROVENANCE  : TRANSCRIPTION {tally[TRANSCRIPTION]}   DERIVED {tally[DERIVED]}"
              f"   PARAM {tally[PARAM]}")
        print(f"FORMS       : " + "   ".join(f"{k}={v}" for k, v in sorted(forms.items())))
        print(f"OLD RULE    : " + "   ".join(f"{k}={v}" for k, v in sorted(old.items())))
        print(f"NUMBER/BOOL cells the OLD rule called DERIVED and the NEW rule calls "
              f"TRANSCRIPTION: {numbers}")
    return {"rows": rows, "tally": tally, "forms": forms, "old": old, "numbers": numbers}


def main(argv=None):
    ap = argparse.ArgumentParser(prog="gates/pycell-census.py",
                                 description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=str(ROOT / "tinybendygrad"),
                    help="the port root; the population is DISCOVERED under it")
    ap.add_argument("--rows", help="write the census rows here")
    ap.add_argument("--plan", action="store_true", help="the population and the totals only")
    ap.add_argument("--prove", action="store_true",
                    help="the 224 KNOWN CASES, on a PINNED CONTENT-ADDRESSED blob")
    a = ap.parse_args(argv)

    if a.prove:
        p = prove(a.root)
        if p is None:
            return 3
        ok = (p["numbers"] >= KNOWN_CASES and p["old"].get("DERIVED", 0) >= KNOWN_CASES)
        print(f"PROOF       : {'OK' if ok else 'REFUSED'} -- the classifier calls "
              f"{p['numbers']} number/bool cells TRANSCRIPTIONS that the old syntactic rule "
              f"called DERIVED (the brief names {KNOWN_CASES})")
        return 0 if ok else 1

    rows, per_file, files, port_defs = census(a.root)
    tally = Counter(r["kind"] for r in rows)
    forms = Counter(r["form"] for r in rows)

    print(f"PORT       : {a.root}")
    print(f"FILES      : {len(files)} `.bend` files (DISCOVERED by os.walk + endswith)")
    print(f"PORT DEFS  : {len(port_defs)} `def NAME` (DISCOVERED; the constant-fold clause)")
    print(f"CELLS      : {len(rows)}   TRANSCRIPTION {tally[TRANSCRIPTION]}   "
          f"DERIVED {tally[DERIVED]}   PARAM {tally[PARAM]}")
    for f, c in forms.most_common():
        print(f"    form {f:<16} {c}")
    print()
    per = Counter()
    for r in rows:
        per[r["file"]] += 1
    print("%-52s %8s %12s %8s %8s" % ("file", "cells", "transcription", "derived", "param"))
    for rel in sorted(per_file):
        rs = per_file[rel]
        if not rs:
            continue
        t = Counter(x[0] for x in rs)
        print("%-52s %8d %12d %8d %8d" % (rel, len(rs), t[TRANSCRIPTION], t[DERIVED], t[PARAM]))
    print("%-52s %8d %12d %8d %8d" % ("TOTAL", len(rows), tally[TRANSCRIPTION],
                                      tally[DERIVED], tally[PARAM]))
    if a.rows:
        Path(a.rows).write_text(render(rows))
        print(f"\n{a.rows} written: {len(rows)} rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
