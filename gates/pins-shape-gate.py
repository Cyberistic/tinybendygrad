# A HEADER'S OWN ARITY WORD, so the file DECLARES its shape and this gate CHECKS the declaration
# rather than trusting it -- the difference `gates/gates-pop.py`'s header insists on ("a declaration
# derived from the tables it describes cannot audit those tables"). `QUAD` is used BARE by three of
# the headers and `TRIPLE` by four, so the suffix is optional and its absence is the word.
ARITY_WORD = re.compile(r"\b(QUARTET|QUAD|TRI)PLE?\b", re.I)
# `GENERATED by <writer>` -- the writer may be a gate, a generator, a FLAG (`--write-baseline`), or
# `hand`, and it may sit on the NEXT header line, because four of the ten headers wrap there.
WRITER = re.compile(r"GENERATED\s+by\s+(?:#\s*)?`?([\w./-]+(?:\.py)?|hand|[-]\w[\w-]*)",
                    re.I | re.S)
# A DOT-PREFIXED `.rows` under `gates/` is a TEMP, not an input. This is the SAME convention
# `gatekit.TMP` already uses, and it is a NAME SHAPE, which doctrine 1 forbids as a population --
# so it is applied to the EXCLUSION and the count of what it hid is printed on every run.
# MEASURED: `gates/.crp-mut-pins.rows` and `gates/.wgsl-mut-pins.rows` are mutate-harness scratch,
# `git ls-tree -r --name-only HEAD` answers 0 for either, and `.crp-mut-pins.rows` was present in
# one census run and gone in the next, with no edit by this unit.
TEMP = re.compile(r"^\..*\.rows$")


def _resolve(rel, beside):
    """A writer path as the header spelled it: ROOT-relative first, then beside the table's gate,
    then beside the table itself. THREE BASES because the three spellings are all in use --
    `gates/ops_python_exec-gen.py` (ROOT), `indexread-gate.py --write-baseline` (a flag), and
    `wk-f32-rows.py` (beside the table, in a plant's tempdir)."""
    q = Path(rel)
    return next((b for b in (ROOT / q, HERE / q, beside / q) if b.is_file()), None)


def refuse(*why):
    print("== REFUSED, NOT A VERDICT: " + "; ".join(why), file=sys.stderr)
    return REFUSED


def gates_pop(home=None):
    """`gates/gates-pop.py` loaded BY PATH. Importing it by name would make the gate population
    anything a `gates_pop.py` on `sys.path` chose -- `gates/gate-surface.py` states the reason."""
    p = (home or HERE) / "gates-pop.py"
    if not p.is_file():
        return None
    spec = importlib.util.spec_from_file_location("gates_pop", p)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def data_rows(p):
    """The lines that carry a record, not a `#` comment. A pins file's rows ARE its data, so a
    file with none is a shape this gate has to NAME rather than skip."""
    return [l for l in p.read_text().splitlines() if l.strip() and not l.startswith("#")]


def header(p):
    return "\n".join(l for l in p.read_text().splitlines() if l.startswith("#"))


def arity(lines):
    """`(widths, tabbed)`: fields per row, TABS if the file uses tabs and WHITESPACE otherwise.

    NOT A SINGLE DELIMITER, because the population is not one delimiter: MEASURED,
    `indexread-baseline.rows` is `path<TAB>argv` and `ops_python_exec-fixtures.rows` is
    `@ f32.addk.0 1 1 1` in spaces. A whitespace count is only MEANINGFUL for a file that declares
    a shape, so `tabbed` travels with the widths and check I charges only a tabbed or declared one:
    `ops_python_exec-fixtures.rows` is a PACKET (a header line then body lines), and calling its
    seven field-counts a broken table shape is a wrong reason, not a finding."""
    tabbed = any("\t" in l for l in lines)
    return [len(l.split("\t")) if tabbed else len(l.split()) for l in lines], tabbed


def namer(entries):
    """`{basename -> {entry point}}` over the WHOLE population, tree-wide.

    A STRING LITERAL and never a filename shape: `ops_python_exec-gate.py` names two `.rows` files
    no `-pins` glob can see, and `wgsl_render_census-mutate.py:38` names a dot-prefixed TEMP path
    that must not be counted as an input. KEYED BY BASENAME because the literal is repo-relative
    -- `gates/wk-f32-rows.py:69` spells it `gates/wk-f32-table.rows` -- and keying on the literal
    made a table that IS named report "named by nothing", which is the worst possible reason."""
    # `gates/symcases.rows: no gate source names this path` WAS A **FALSE CHARGE**, MEASURED:
    # `gates/sym_graph_census.bend:130` is `def CASES() -> String: "gates/symcases.rows"` and `:626`
    # READS IT AT RUNTIME. `namer()` was `ast.parse`-only, so `if f.suffix != ".py": continue` COULD
    # NOT SEE A `.bend` OWNER. **THAT IS A TOOL LIMIT AND NOT A POLICY**, and the same limit makes
    # `gates-pop.py` blind to 62 `.bend` drivers -- so NO EXISTING INSTRUMENT ADMITTED `.bend` WHILE
    # EXCLUDING `.md`. A `.bend` DRIVER IS TEXT, SO A LITERAL SCAN FINDS THE PATH WITHOUT `ast`, AND
    # THAT IS THE NARROW HALF OF THE FIX. **THE WIDE HALF -- LEARNING EACH OWNER'S FORMAT FROM THE
    # OWNING GATE -- IS A DIFF IN THE REPORT AND IS NOT APPLIED HERE, BECAUSE A GATE THAT LEARNS
    # FORMATS FROM ITS OWN SUBJECT MUST NOT ALSO BE THE JUDGE.**
    out = {}
    for f in entries:
        if f.suffix not in (".py", ".bend"):
            continue
        try:
            if not stat.S_ISREG(os.lstat(f).st_mode):
                continue
            # `gate-surface.py` and `gates-pop.py` ship backslash escapes in DOCSTRINGS, so parsing
            # a gate is allowed to warn -- and another gate's warning printed under this gate's name
            # is a row this gate did not measure.
            if f.suffix == ".py":
                with warnings.catch_warnings():
                    warnings.simplefilter("ignore", SyntaxWarning)
                    tree = ast.parse(f.read_text())
                found = [n.value for n in ast.walk(tree)
                         if isinstance(n, ast.Constant) and isinstance(n.value, str)
                         and n.value.endswith(".rows")]
            else:
                # A `.bend` DRIVER IS NOT PYTHON. `ast.parse` raises, and a gate that SKIPS what it
                # cannot parse is a gate blind to it -- WHICH IS HOW `symcases.rows` CAME TO REPORT
                # "NAMED BY NOTHING" WHILE `sym_graph_census.bend` NAMES IT TWICE. A REGEX OVER ITS OWN
                # TEXT IS DOCTRINE 1 CLAUSE (c), AND A DRIVER'S PATHS ARE LITERALS, NOT COMPUTED.
                found = re.findall(r"[\w./-]*\.rows", f.read_text(errors="replace"))
            for lit in found:
                out.setdefault(lit.rsplit("/", 1)[-1], set()).add(f.name)
        except (SyntaxError, UnicodeDecodeError, OSError):
            continue
    return out


def check(p, owners):
    """Every check on ONE table, each returning a reason string or None. Per GATE, never tree-wide.

    Returns `(reasons, n_rows, n_cols)`; `n_cols` is None when the rows disagree."""
    try:
        rows, head = data_rows(p), header(p)
    except OSError as e:
        # A TABLE THIS GATE COULD NOT READ IS NOT A TABLE THAT PASSED. MEASURED, live, twice in
        # one session: `gates/gates-pop.py:496` raised `FileNotFoundError` at `gate-surface.py:919`
        # on a file another unit deleted between its own `iterdir` and its `lstat`, and this file
        # raised the same from `check()` on a `gates/*.rows` mid-rewrite -- an UNCAUGHT OSError is
        # a traceback and exit 1, and 1 is `FAIL`, so a file being written right now read as the
        # tree disagreeing. NAMED, AND CHARGED: this instrument reporting a result for a table it
        # never ran on is the whole class.
        return [f"could not be read ({type(e).__name__}: {e.strerror}) -- another unit is "
                f"writing gates/ right now; this is not a table that passed"], 0, None
    bad = []
    widths, tabbed = arity(rows)
    widths, ncol = sorted(set(widths)), (sorted(set(widths))[0] if len(set(widths)) == 1 else None)

    # I ARITY UNIFORM, and only where a shape is CLAIMED. A tabbed file or a header that names an
    # arity is a table and must be uniform; a whitespace file that declares nothing is a PACKET or
    # a captured stream, and holding one to a table's rule is a wrong reason. This is the only
    # check asserted without asking the file's header first.
    if len(widths) > 1 and (tabbed or ARITY_WORD.search(head)):
        bad.append(f"{len(rows)} rows carry {len(widths)} arities {widths} -- one reader, one shape")

    # II PROVENANCE DECLARED. A writer, a generator, a flag, or `hand` -- any of the four is a claim
    # somebody made on purpose. NO header at all means a table in git that nobody can regenerate and
    # nobody declared, which is how `deleted()` answers "fixed" for a file that was never read.
    # The writer is resolved ROOT-relative FIRST: MEASURED,
    # `ops_python_exec-fixtures.rows` writes `gates/ops_python_exec-gen.py --write` and
    # `indexread-baseline.rows` writes a FLAG, so a path joined onto the table's own directory
    # reports a generator that is on disk as MISSING.
    #
    # **TWO FINDINGS, NOT ONE, BECAUSE THE ONE WAS A WRONG REASON FOR 3 OF THE 6 TABLES RED TODAY.**
    # MEASURED on this tree: all six findings are check II, and `gates/falseclaim-plant.rows`
    # carries **21 `#` header lines** -- so "no header declares who writes it" is FALSE about it,
    # and `gates/falseclaim-census-gate.py:486` sends its reader to look at "its own header".
    # A WRONG REASON IS WORSE THAN NO REASON: it sends the next agent to add a `#` line to a file
    # that already has twenty-one of them. **THE TWO ARE ALSO NOT EQUALLY CLOSABLE** -- a file with
    # no header can be GIVEN one, while a file whose header names nobody has to have its WRITER
    # NAMED -- so they are two findings with two fixes.
    #
    # AND THE OWNER GOES ON THE LINE, because check VI's own output supplies the writer's name one
    # line above and the finding used to contradict it: `gates/cstyle-live.rows` is written by
    # `checks/repair-dupes.py` (named, at `:48`), which is exactly why its finding says "nobody can
    # regenerate it". THE FINDING THAT NAMES NO OWNER IS THE ONE NOBODY CAN CLOSE.
    w = WRITER.search(head)
    if not w:
        bad.append(("no header at all, so nobody declared who writes it"
                    if not head else
                    f"its {len(head.splitlines())}-line header names no writer "
                    f"(a generator, a flag, or `by hand`)")
                   + (f" -- but {','.join(sorted(owners))} names it"
                      if owners else " -- and NO GATE SOURCE NAMES IT"))
    elif w.group(1).endswith(".py") and not _resolve(w.group(1), p.parent):
        bad.append(f"the header's writer {w.group(1)} is not in the tree")

    # III A DECLARED ARITY IS THE ONE MEASURED. Asserted only where the header declares one, and a
    # header that says TRIPLE over a QUAD body is a reader trusting the header.
    declared = {4 if x.upper().startswith("QUA") else 3 for x in ARITY_WORD.findall(head)}
    if declared and ncol is not None and ncol not in declared:
        bad.append(f"the header declares {'/'.join(str(d) for d in sorted(declared))} columns "
                   f"and the rows are {ncol}")

    # IV A PINS FILE THAT PINS NO VALUES. `ops_python_exec-pins.rows` is NF 1: 52 row NAMES and not
    # one oracle value or port value, so every row of it is an EXCLUSION and a census reading
    # "52 declared divergences" from it is reading names. This is `fixtures_hold`'s defect
    # (instance 13) with the values physically ABSENT rather than discarded. `by hand` is NOT an
    # excuse -- MEASURED, that file's header says "GENERATED by hand" and says nothing about
    # values, which is the whole finding -- so the excuse must name the absence.
    if p.name.endswith("-pins.rows") and ncol == 1 and rows and not re.search(
            r"(row NAMES?\b|exclusion|no values?|names? only)", head, re.I):
        bad.append(f"{len(rows)} rows carry ONE field, so this pins NAMES and no value -- say so in "
                   f"the header, or carry the values")

    # V ZERO IS A CLAIM OR IT IS AN ABSENCE. Two of the tables carry no rows at all, and both say
    # why in their own header; a THIRD that emptied without saying so would read "0 divergences" to
    # a census that never compared anything (class instance 12).
    if not rows and not re.search(r"\bZERO\b|\b0 DECLARED\b|\bno quads\b", head):
        bad.append("the file carries NO rows and does not say so -- 0 from an empty table is not "
                   "0 from a comparison")

    # VI NAMED BY A GATE. Doctrine 1's shape on this subject: a table nothing reads is a list.
    if not owners:
        bad.append("no gate source names this path")
    return bad, len(rows), ncol


def mutate_population(entries):
    """REPORTED, NOT ASSUMED: the `-mutate.py` files, and how many are actually wired.

    "A gate that has never been seen to fail is not a gate"; a mutation harness nothing invokes is
    the same sentence one level up. MEASURED at `c7e7c886`: 5 files exist and 2 of them are named
    by another gate. `mutkit.py` is the mechanism, and importing it is not being invoked by a gate.
    The counts print on every run so neither drifts silently."""
    muts = sorted(p.name for p in HERE.iterdir()
                  if p.name.endswith("-mutate.py") and stat.S_ISREG(os.lstat(p).st_mode))
    src = []
    for f in entries:
        if f.suffix == ".py" and f.name not in muts:
            try:                                             # the live tree, again
                src.append(f.read_text())
            except OSError:
                continue
    wired = [m for m in muts if any(m in s for s in src)]
    return muts, wired


def tracked(names):
    """`{name}` per `git ls-tree -r --name-only HEAD`, ONCE, and NEVER as the population.

    `AGENTS.md` measures `git ls-files --others --exclude-standard` answering ~1% of what
    `git ls-files` answers and `jj` arming the index on every snapshot, so a census that FILTERS on
    git can silently shrink its own population. This is therefore REPORTED and not charged, and the
    reason it matters: MEASURED at `c7e7c886`, `gates/crp-mut-pins.rows` and `gates/crp-mut-gate.py`
    appeared mid-session, untracked, written at 01:53 by another unit -- so this census's table set
    is LIVE and a count without a timestamp is a count about nothing.

    **IT USED TO SAY `git ls-files gates/`, AND `gates/indexread-gate.py` CHARGED THIS FILE FOR IT.
    THE REASON IT CHARGED IT IS THE REASON IT IS WRONG ABOUT THIS FILE: the index is not this
    census's SUBJECT, it was a *diagnostic* on a census whose population is `iterdir` + `discover()`.
    `indexread-gate.py`'s own header draws the line -- "the index is reported as a DIAGNOSTIC ONLY,
    never as the population" (`:237`) -- and it drew it for itself while charging a file that had
    done nothing the rule forbids. **`ls-tree -r --name-only HEAD` reads a COMMIT TREE OBJECT in
    `.git/objects`; no index reset reaches it** (`indexread-gate.py:29-32`), and it is the very
    call that gate uses for its own population.
    MEASURED, this swap moves the diagnostic on **0 of 23** tables: `git ls-files gates/` and
    `git ls-tree -r --name-only HEAD -- gates/` return the SAME 272 names on this tree and all 23
    `.rows` tables read `tracked` under both. THE VERDICT IS PRESERVED AND THE AUTHORITY IS BETTER.
    **THIS IS NOT AN ADMISSION AND NOT A RE-PIN:** no baseline row moved, no finding was deleted,
    and this file simply stopped reading the thing whose reading the census was about."""
    r = subprocess.run(["git", "ls-tree", "-r", "--name-only", "HEAD", "--", "gates/"],
                       capture_output=True, text=True, cwd=ROOT)
    if r.returncode != 0:
        return None
    return {l.rsplit("/", 1)[-1] for l in r.stdout.splitlines() if l.strip()}


def colhead_note(p, n):
    """A NOTE ON THE DENOMINATOR, NEVER A CHANGE TO IT.

    `data_rows()` drops `#` COMMENT lines and keeps everything else, so a table that declares its
    columns as a **TAB-DELIMITED HEADER ROW** -- not a `#` comment -- has that row COUNTED AS DATA.
    MEASURED on this tree: `citations-census-findings.rows` reads **395** here while
    `gates/citations-census-gate.py:131` documents **394**, and `oracleblind.rows` reads **99**
    against 98 oracles. **THE CENSUS AND THE OWNING GATE DISAGREE BY EXACTLY THE HEADER ROW.**

    **AND NO SOUND SHAPE TEST EXISTS TO FIX IT, WHICH IS WHY IT IS A NOTE.** The obvious
    discriminator -- "a header row's fields are lowercase identifiers" -- admits
    `citations-census-findings.rows` (`verdict\\tregression_or_blank\\t...`, all lowercase) and
    REJECTS `oracleblind.rows`, whose row 1 carries `EMPTY` and `VALID-DIFFERENT`. MEASURED BOTH
    WAYS. **A NAME SHAPE IS NOT A POPULATION (doctrine 1), so the denominator is printed BOTH WAYS
    AND NEVER ADJUSTED**: silently subtracting a row whose role this file cannot establish would
    move a denominator on a guess, and this file's own header forbids a tree-wide rule for exactly
    the reason the guess would be wrong.
    """
    try:
        first = next((l for l in p.read_text().splitlines() if l.strip()), "")
    except OSError:
        return ""
    if not (first and "\t" in first and not first.startswith("#")):
        return ""
    return f"  <- row 1 is a COLUMN HEADER ROW, not data: {n - 1} rows if so"


def census(root=None, home=None):
    """`root`/`home` are parameters ONLY so `--plant` can drive the REFUSED paths on a synthetic
    tree; the live run uses the module's own two directories. A census whose own preconditions
    cannot be planted is a census whose REFUSAL is a claim of unknown value -- which is
    `gate-surface.py`'s UNPLANTED, and is why they take arguments."""
    root, home = root or ROOT, home or HERE
    pop = gates_pop(home)
    if pop is None:
        return refuse("gates/gates-pop.py is gone -- it IS the shared population")
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", SyntaxWarning)
            entries, libs = pop.discover(root)
            # `discover()` IS A **TWO-VALUE CONTRACT** -- `gates/gate-surface.py:280` unpacks it
            # straight into `entries, libs`, and a THIRD return value was MEASURED to raise
            # `ValueError: too many values to unpack` in a gate this work may not edit. **SO THE
            # `.bend` POPULATION IS ADDED HERE AND NOT BY CHANGING `discover()`.** `discover()` is
            # `ast`-BASED AND RETURNS **0 OF THE 62 `.bend` DRIVERS** -- MEASURED -- which is why
            # `symcases.rows` REPORTED "NAMED BY NOTHING" WHILE `sym_graph_census.bend` NAMES IT
            # TWICE. **A FIX THAT BREAKS A CALLER IS NOT A FIX; IT IS A TRADE.**
            #
            # **`home`, NOT `HERE` -- AND THIS WAS A RED PLANT SINCE THE PLANTS WERE WRITTEN.**
            # `root`/`home` exist SO `--plant` can drive the REFUSED paths on a synthetic tree. This
            # line read the module global instead, so on the `refuse/empty-pop` plant -- whose whole
            # point is `discover()` returning `([], [])` -- the glob reached back into the LIVE
            # `gates/` and found **60** real `.bend` drivers. `entries` became 60, the
            # "0 entry points is not a green census" refusal NEVER FIRED, and the plant ran a FULL
            # CENSUS OF THE REAL TREE inside a synthetic-root refusal and returned **1**.
            # MEASURED: `--plant` at HEAD already prints `refuse/empty-pop  rc=1  NOT OK` -- and
            # **rc=1 IS ALSO WHAT A GENUINE RED FINDING RETURNS**, so a broken plant and a working
            # gate are the same exit code. That is doctrine 2's shape one level down: this file
            # publishes its own exit-code table and cannot hear its own harness.
            # **ON THE LIVE RUN `home IS HERE`** (`census()`: `home = home or HERE`), so this is a
            # **ZERO-EFFECT CHANGE TO THE REAL CENSUS** and a total fix to the plant.
            entries = list(entries) + sorted(home.glob("*.bend"))
    except Exception as e:                                    # a census that cannot pop is not 0
        return refuse(f"discover() raised {type(e).__name__}: {e}")
    if not entries:
        return refuse("the gate population is EMPTY -- a gate over 0 gates cannot fail")

    # OWNERS ARE LOOKED UP IN `entries + libs`, NOT `entries` ALONE, AND THAT IS A MEASUREMENT.
    # `gates/wk-f32-rows.py` WRITES `gates/wk-f32-table.rows` (`wk-f32-rows.py:69`) and has no
    # `__main__`, so `discover()` files it as a LIB. Reading owners out of `entries` alone made a
    # table report "named by nothing" while the file that writes it sat in the same directory --
    # doctrine 1's blind spot reproduced inside the instrument built to close it.
    owners_pool = entries + [p for p in libs if p.suffix == ".py"]
    named = namer(owners_pool)
    temps = [p.name for p in sorted(HERE.iterdir())
             if TEMP.match(p.name) and stat.S_ISREG(os.lstat(p).st_mode)]
    tables = [p for p in sorted(HERE.iterdir())
              if p.suffix == ".rows" and not p.name.startswith(".")
              and stat.S_ISREG(os.lstat(p).st_mode)]
    print(f"POPULATION: {len(entries)} discovered entry point(s) + {len(owners_pool) - len(entries)}"
          f" lib(s) as owners, {len(tables)} checked-in .rows file(s) under gates/, "
          f"{len(named)} distinct .rows path(s) named by one of them"
          + (f", {len(temps)} dot-prefixed TEMP excluded: {', '.join(temps)}" if temps else ""))

    bad, tally, live = [], {}, []
    git = tracked(None)
    for p in tables:
        why, n, w = check(p, named.get(p.name, set()))
        tally[w] = tally.get(w, 0) + 1
        untracked = git is not None and p.name not in git
        if untracked:
            live.append(p.name)
        bad += [f"{p.name}: {r}" for r in why]
        print(f"  {p.name:34s} rows={n:5d} cols={w or '-':>2} "
              f"{'UNTRACKED ' if untracked else ''}"
              f"owners={','.join(sorted(named.get(p.name, {'NONE'})))[:56]}"
              + colhead_note(p, n))
    muts, wired = mutate_population(owners_pool)
    print(f"MUTATIONS: {len(muts)} -mutate.py file(s), {len(wired)} wired; the unwired ones are "
          f"{', '.join(m for m in muts if m not in wired) or '(none)'} -- REPORTED, not charged: "
          f"a harness nothing invokes is a coverage gap or a dead def and this cannot tell which")
    print(f"SHAPES (column count -> files): {dict(sorted(tally.items(), key=lambda kv: kv[0] or 0))}"
          f"  -- a column COUNT, not one vocabulary")
    if live:
        print(f"LIVE: {len(live)} of {len(tables)} table(s) are UNTRACKED ({', '.join(live)}) -- "
              f"another unit is writing gates/ now, so this census's table set is not a fixed "
              f"denominator and its findings about them are about work in flight")

    for r in bad:
        print(f"  RED {r}")
    print(f"PINS-SHAPE: {'RED -- ' + str(len(bad)) + ' finding(s)' if bad else 'GREEN'}")
    return FAIL if bad else PASS


# ---- the MUTATIONS. Each one edits an INPUT and requires the check to go red. --------------
