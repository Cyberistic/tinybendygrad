# THE THREE REFUSED PRECONDITIONS, each a synthetic root that is missing exactly one thing. A
# refusal that cannot be planted is a refusal nobody has ever seen fire.
REFUSALS = [
    ("no-gates-pop", lambda d: None,
     "the shared population loader is gone"),
    ("empty-pop", lambda d: (d / "gates" / "gates-pop.py").write_text(
        "def discover(root):\n    return [], []\n"),
     "0 entry points is not a green census"),
    ("discover-raises", lambda d: (d / "gates" / "gates-pop.py").write_text(
        "def discover(root):\n    raise FileNotFoundError('deleted mid-walk')\n"),
     "a walk that raises is REFUSED, not a traceback that reads as FAIL"),
]


def plant():
    """A mutation of ONE OF ITS INPUTS MUST MAKE IT RED, and this is that measurement. Everything
    runs on synthetic directories in a tempdir: no `bend`, no CPython, no tree state, and the
    tree's own tables are never touched.

    THE THREE REFUSALS ARE PLANTED TOO, AND THAT IS THE POINT OF THE WHOLE FILE. Instance 4 of
    the class was a sweep reporting 0 of 67 gates green because `timeout` does not exist on this
    machine, so every run was `command not found`: a run that CANNOT HAPPEN reported a result. A
    verdict a gate can never reach cannot be tested, so `REFUSED` is exercised here or it is a
    comment. MEASURED that the distinction is worth three plants: `gate-surface.py` reports **4
    UNOWNED and 10 RENAMED exit codes** over the same tree, and `gates-pop.py:496` raises
    `FileNotFoundError` on a file another unit deleted between its own `iterdir` and its `lstat`
    -- which is a THIRD exit code for the same event that this file answers with `3`."""
    bad = []
    for name, (body, head, why) in PLANTS.items():
        with tempfile.TemporaryDirectory() as td:
            d = Path(td)
            (d / "x-gate.py").write_text("")               # the named writer, for `gone-writer`
            f = d / ("t-pins.rows" if name != "whitespace-packet" else "t-fixtures.rows")
            f.write_text(head + body)
            reasons, n, w = check(f, set() if name == "unnamed" else {"x-gate.py"})
            want_red = name not in ("healthy", "whitespace-packet")
            ok = bool(reasons) == want_red
            print(f"  {name:18s} {'RED ' if reasons else 'GREEN'}  n={n} cols={w or '-'}  "
                  f"{'ok' if ok else 'NOT OK -- ' + why}")
            if not ok:
                bad.append(f"{name}: wanted {'RED' if want_red else 'GREEN'}, got "
                           f"{'RED: ' + reasons[0] if reasons else 'GREEN'}")

    # THE REFUSED VERDICT, THREE WAYS, on synthetic roots. Each must be exit 3 and NOT 0 or 1.
    sys.stdout.flush()                       # the refusals print to stderr; do not interleave them
    for name, build, why in REFUSALS:
        with tempfile.TemporaryDirectory() as td:
            d = Path(td)
            (d / "gates").mkdir()
            build(d)
            rc = census(root=d, home=d / "gates")
            ok = rc == REFUSED
            print(f"  refuse/{name:14s} rc={rc}  {'ok' if ok else 'NOT OK -- ' + why}")
            if not ok:
                bad.append(f"refuse/{name}: wanted REFUSED(3), got {rc}")

    # THE TABLE THAT CANNOT BE READ. A mutation of the instrument's ENVIRONMENT rather than of a
    # row: the file is deleted between `iterdir` and `read_text`, which is what another unit's
    # write looks like from in here. It must be a NAMED finding, and it must NOT be a traceback
    # with exit 1 -- 1 is `FAIL`, so a table being rewritten would read as the tree disagreeing.
    with tempfile.TemporaryDirectory() as td:
        f = Path(td) / "t-pins.rows"
        f.write_text("# GENERATED by `x-gate.py --refresh`. one TRIPLE\n")
        f.unlink()                                   # gone before anything reads it
        f.mkdir()                                   # and now not even a file: EACCES/IsADirectory
        reasons, n, w = check(f, {"x-gate.py"})
        ok = bool(reasons)
        print(f"  {'unreadable':18s} {'RED ' if reasons else 'GREEN'}  n={n} cols={w or '-'}  "
              f"{'ok' if ok else 'NOT OK -- a table this gate cannot read is not one that passed'}")
        if not ok:
            bad.append("unreadable: a table that cannot be read is not a table that passed")

    total = len(PLANTS) + len(REFUSALS) + 1
    print(f"--plant: {'all ' + str(total) + ' mutations behaved' if not bad else 'FAILED'}")
    for b in bad:
        print(f"  {b}")
    return 1 if bad else PASS


if __name__ == "__main__":
    sys.exit(plant() if "--plant" in sys.argv else census())