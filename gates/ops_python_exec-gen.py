SEED_FAIL, PAIR_BAD, ALU_BAD = [], [], []
HEADER = ("# ops_python_exec fixtures -- GENERATED by gates/ops_python_exec-gen.py --write.\n"
          "# THE ONLY WRITER. The gate reads this and reconstructs each PACKET.in from it;\n"
          "# it is not hand-edited and nothing else writes it.\n")


def sweep(emit):
    """ONE pass over the population -- the harvest first, then the ALU spine, both
    STREAMED through `emit`. `emit` is the record writer for `--write` and the row
    printer for the oracle lane, so neither mode holds the population."""
    canon, n = {}, 0
    for f in harvest():
        n += 1
        emit(f, None)
        keep_canon(canon, f)
    if PAIR_BAD: sys.exit(f"PAIR_BAD {PAIR_BAD}")
    if not canon: sys.exit("no harvested kernel has a single-STORE ALU spine")
    for f in alu_fixtures(canon):
        n += 1
        emit(f, None)
    return n, canon


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true", help="rewrite the fixture file and exit")
    ap.add_argument("--coverage", action="store_true", help="print the coverage census and exit")
    args = ap.parse_args()

    if args.write:
        with FIXTURES.open("w") as fh:
            fh.write(HEADER)
            n, canon = sweep(lambda f, _: fh.write(record(f)))
        print(f"wrote {FIXTURES.name}: {n} fixtures, canonical spines "
              f"{sorted((a, m) for a, m in canon)}, {len(SEED_FAIL)} seed failures, {ALU_BAD}")
        return

    if args.coverage:
        seen = set()

        def watch(f, _):
            try:
                prog, _b = py_run(f)
                seen.update(o.name for o in prog.uops.seen)
            except Exception:                                              # noqa: BLE001
                pass

        n, _ = sweep(watch)
        cov = coverage(seen)
        for k in ("op_of", "dispatch"):
            print(f"{k}: {cov[k][0]} declared, {len(cov[k][1])} unreached {cov[k][1]}")
        print(f"catch_all: {cov['catch_all']}")
        print(f"fixtures: {n}, ops CPython dispatched: {len(seen)}")
        return

    rows = []

    def emit(f, _):
        rows.extend(py_rows(f))

    sweep(emit)
    print("\n".join(rows))
    print("py-done=1")


if __name__ == "__main__":
    main()