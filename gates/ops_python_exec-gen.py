# AXIS 2: the ALU spine. One fixture per `python_alu` op, arity read off the
# table's own callable.
# ---------------------------------------------------------------------------
def data_roots(uops):
    """The ALU roots the STORE of a one-STORE kernel reads: the direct srcs of the
    STORE's data node, or that node itself when it is not a STACK.

    THE SHAPE IS FOUND BY CONSUMERSHIP, NOT BY POSITION. MEASURED on the canonical
    eight-element `x*y`: it is VECTORISED -- 36 uops whose tail is four `Ops.MUL`
    roots (16,24) (19,25) (20,26) (23,27) into a `STACK` into the `STORE` -- so
    "the i-th ALU node" is not a thing, and replacing one of the four drops it from
    the list while the `STACK` still reads it (`encode` refuses with "STORE reads
    STACK, which is not in the uop list").
    """
    stores = [i for i, u in enumerate(uops) if u.op is Ops.STORE]
    if len(stores) != 1: raise RuntimeError(f"{len(stores)} STOREs, not 1")
    data = uops[stores[0]].src[1]
    roots = list(data.src) if data.op is Ops.STACK else [data]
    if not roots: raise RuntimeError("the STORE data node has no srcs")
    return roots


def spine(uops, op):
    """Rewrite `uops` so every ALU root becomes `op`, and re-toposort the result.

    THE REWRITE IS FROM THE SINK DOWN, not a list splice, and the difference is
    measured: splicing the list replaces a node in place, but `UOp(Ops.POW, srcs)`
    is REWRITTEN BY CONSTRUCTION (tinygrad folds POW into LOG2/EXP2/MUL), so the
    node the splice installed is not the node the rest of the tree reads and
    `encode` refuses with "STACK reads ADD, which is not in the uop list".
    Rebuilding from the root and re-toposorting lets the fold happen where it
    belongs -- and then POW has no fixture, which is a fact about tinygrad and not a
    hole in the census, so it is reported in `bad` rather than hidden.
    """
    roots = data_roots(uops)
    go = set(id(r) for r in roots)

    def walk(u):
        src = tuple(walk(s) for s in u.src)
        if id(u) in go: return UOp(op, src)
        return u.replace(src=src) if src != u.src else u

    return list(walk(uops[-1]).toposort())


def family(uops):
    """The dtype CLASS of a kernel's spine, by tinygrad's own `DType` predicates:
    `is_float`, else `bool`, else integer. X86 shift and bitwise are refused at
    construction on float operands -- MEASURED, `UOp(Ops.SHL, (f32, f32))` raises
    `RuntimeError: shift operands must be int` and `UOp(Ops.XOR, (f32, f32))`
    raises `TypeError: unsupported operand type(s) for ^` -- so the canonical for an
    integer op has to be an integer kernel or the op never gets a fixture. The class
    predicates are `dtypes.is_float`/`dtypes.is_bool` (dtype.py:90,:96), tinygrad's own --
    `DType` carries no such attribute (MEASURED: `dir(dtypes.float)` is
    `['bitsize','const','fmt','itemsize','max','min','name','new','priority']`)."""
    d = data_roots(uops)[0].dtype
    return "f" if dtypes.is_float(d) else ("b" if dtypes.is_bool(d) else "i")


def pick_canon(fx):
    """The smallest harvested kernel per (SPINE ARITY, DTYPE CLASS), chosen by
    MEASURING the harvest's own STORE spines rather than by naming one."""
    best, have = {}, set()
    for f in fx:
        try:
            roots = data_roots(f.uops)
            arity, fam = len(roots[0].src), family(f.uops)
        except RuntimeError: continue
        if any(len(r.src) != arity for r in roots): continue
        if any(r.op not in GroupOp.ALU for r in roots): continue
        have.add((arity, fam))
        if (arity, fam) not in best or len(f.uops) < len(best[(arity, fam)].uops): best[(arity, fam)] = f
    return best, sorted(have)


def alu_fixtures(canon):
    """`python_alu` is ops.py's own table and IS `PythonRenderer.code_for_op`, so the
    population of this axis is the table's keys; the arity of each member comes from
    `GroupOp`'s own Unary/Binary/Ternary sets, which is what ops_python.py:151
    dispatches on. A generator, for the memory reason on `harvest`."""
    for op in python_alu:
        # ARITY IS CPYTHON'S OWN DECLARATION, not a table typed here: `GroupOp`'s
        # Unary/Binary/Ternary sets (tinygrad/uop/__init__.py:105-108) are the
        # grouping ops_python.py:151 dispatches on, and `inspect.signature` cannot
        # read `max` (measured: `ValueError: no signature found for builtin max`).
        arity = 1 if op in GroupOp.Unary else 2 if op in GroupOp.Binary else 3 if op in GroupOp.Ternary else 0
        if not arity:
            ALU_BAD.append(f"{op.name}: no GroupOp arity")
            continue
        # The dtype classes are tried FLOAT FIRST and the first one CPython accepts
        # is kept, so `alu.SHL` lands on the integer spine (MEASURED: `UOp(Ops.SHL,
        # (f32, f32))` raises `RuntimeError: shift operands must be int` and
        # `UOp(Ops.XOR, (f32, f32))` raises `TypeError: unsupported operand type(s)
        # for ^`) without a table saying which op wants which dtype. ONE per op, not
        # one per class: the second copy cost ~8 MB of tinygrad's per-node derived
        # caches each and this machine has ~62 MB free (`vm_stat`: `Pages free:
        # 3978`), so a second copy of every op is what turned a working sweep into
        # rc=137.
        for (a, fam), c in sorted(canon.items(), key=lambda kv: (kv[0][0], kv[0][1] != "f", kv[0][1])):
            if a != arity: continue
            try:
                nu = spine(c.uops, op)
                if not any(u.op is op for u in nu):
                    ALU_BAD.append(f"{op.name}.{fam}: folded away by the rewrite "
                                   f"({sorted({u.op.name for u in nu if u.op in GroupOp.ALU})})")
                    continue
                f = Fixture(f"alu.{op.name}.{fam}", nu, c.bufs, c.gsize, c.vals)
                # CPython's own interpreter is the fixture's validator: a shape it
                # refuses is not a fixture, and the refusal is recorded rather than
                # papered over with a different shape.
                py_run(f)
            except Exception as e:                                         # noqa: BLE001
                ALU_BAD.append(f"{op.name}.{fam}: {type(e).__name__} {str(e)[:60]}")
                continue
            # ONE per op, so this is `break` and not `return`: `return` here ends
            # the GENERATOR, and a first draft had it, so `alu_fixtures` answered
            # exactly ONE fixture (`alu.LOG2.f`) and the coverage census reported
            # CDIV, FLOORDIV, FLOORMOD and POW as unreached while `ALU_BAD` was
            # empty -- a population of one that looked like a clean run.
            yield f
            break
        else:
            ALU_BAD.append(f"{op.name}: no canonical spine CPython accepted")


# ---------------------------------------------------------------------------
# THE ORACLE LANE. CPython's own `PythonProgram.__call__`, on the same buffers.
# ---------------------------------------------------------------------------
def py_run(fx, fresh=False):
    """Run the fixture through CPython and return `(program, buffers)`, where
    `program.uops` is the `Trace` `__call__` stepped through.

    `fresh=True` copies the buffers so the answer is the interpreter's and not the
    caller's array; the harvest path already copied them, so the default reuses.
    THE COPY IS NOT OPTIONAL GARBAGE: `ctypes.c_char.from_buffer` takes the address
    of a LIVE writable buffer, and handing it a `bytearray` that is about to fall
    out of a list comprehension leaves `__call__` writing through a freed address.
    MEASURED: the first `--coverage` draft did exactly that and the process died
    rc=139 (SIGSEGV) inside `PythonProgram.__call__`.
    """
    bufs = [bytearray(b) for b in fx.seen()]
    prog = OPY.PythonProgram.__new__(OPY.PythonProgram)
    prog.__init__(None, Elf(fx.uops, Target(renderer="PYTHON")))
    # AFTER `__init__`, not before: it assigns `self.uops = pickle.loads(obj.lib)`,
    # so a Trace installed first is overwritten and `seen` stays empty.
    prog.uops = Trace(prog.uops)
    addrs = [ctypes.addressof(ctypes.c_char.from_buffer(b)) for b in bufs]
    prog(*addrs, global_size=fx.gsize, local_size=(1, 1, 1), vals=tuple(fx.vals))
    return prog, bufs


def py_rows(fx):
    try:
        _, bufs = py_run(fx)
        return [f"{fx.name}.b{i}={bytes(b).hex()}" for i, b in enumerate(bufs)]
    except Exception as e:                                                    # noqa: BLE001
        return [f"{fx.name}=REFUSED-{type(e).__name__}"]


# ---------------------------------------------------------------------------
# THE FIXTURE FILE. A record per fixture: `@ <name> <gx> <gy> <gz> <vals>` then the
# packet, verbatim, line for line -- so the gate reconstructs a packet by copying
# lines and never parses a number.
# ---------------------------------------------------------------------------
def keep_canon(canon, f):
    """Keep `f` as the canonical for its (arity, dtype class) when it is the smallest
    seen. Seven keys at most, which is what lets the harvest STREAM: every other
    fixture is dropped the moment its rows are written."""
    try:
        roots = data_roots(f.uops)
        arity = len(roots[0].src)
        if any(len(r.src) != arity for r in roots): return
        if any(r.op not in GroupOp.ALU for r in roots): return
        k = (arity, family(f.uops))
    except RuntimeError:
        return
    if k not in canon or len(f.uops) < len(canon[k].uops): canon[k] = f


def record(f):
    """THE FIXTURE FILE RECORD, and it is a `PACKET.in` VERBATIM under a header line.

    `BendProgram.__call__` (ops_bend.py:217) writes
    `self.src + "".join(f"{len(v)} {bytes(v).hex()}\\n" for v in views)`, so the gate
    reconstructs a packet by DROPPING THE `@` LINE AND COPYING THE REST. There is no
    packet parsing in the gate at all -- which is the point: a gate that had to
    re-derive the wire to test the reader of the wire would be the reimplementation
    this axis exists to avoid.
    """
    body = f.packet + "".join(f"{len(b)} {bytes(b).hex()}\n" for b in f.seen())
    return f"@ {f.name} {' '.join(str(v) for v in f.argv())}\n" + body


def read_fixtures():
    """`(name, argv, packet_text)` per record. The gate reconstructs a `PACKET.in`
    out of `packet_text` by copying lines and never parses a number."""
    recs, cur = [], None
    for ln in FIXTURES.read_text().splitlines():
        if ln.startswith("@ "):
            head = ln.split()[1:]
            cur = [head[0], tuple(int(x) for x in head[1:]), []]
            recs.append(cur)
        elif cur is not None and ln.strip():
            cur[2].append(ln)
    return [(n, a, "\n".join(p) + "\n") for n, a, p in recs]


# ---------------------------------------------------------------------------
# THE COVERAGE CENSUS: the port's own arm table against CPython's own dispatch.
# ---------------------------------------------------------------------------
def port_arms():
    """`op_of`'s names and `Prog.dispatch`'s named arms, read out of the PORT by
    regex. Neither is listed here: the port is the declaration (AGENTS.md doctrine 1,
    clause (c) -- a regex over the tree's own write sites)."""
    src = PORT.read_text()
    names = re.findall(r'case "(\w+)": Some\{O\.Ops', src)
    body = src[src.index("def Prog.dispatch("):src.index("def Prog.run(+p")]
    arms = re.findall(r"case O\.Ops(\w+)\{\}", body)
    catch = re.findall(r"case _:\s*Prog\.(\w+)\(", body)
    return names, arms, catch


def coverage(dispatched):
    names, arms, catch = port_arms()
    return {
        "op_of": (len(names), sorted(set(names) - dispatched)),
        "dispatch": (len(arms), sorted(set(arms) - dispatched)),
        "catch_all": catch,
    }


