# THE GENESIS OF A LAUNCH. `PythonProgram.__call__` receives the memoryviews
# ops_python binds, and `BendProgram.__call__` does `to_mv(b, nb)` over them, so
# an int address is what both take -- NOT a memoryview (measured: a memoryview
# raises `TypeError: integer expected` out of `to_mv`). The bytes are copied before
# the call so the row is the answer and not the identity of the caller's array.
class Elf:
    """The `TinyELF` `PythonProgram.__init__` reads two fields off: `obj.lib`, the
    pickle it unpickles into `self.uops`, and `obj.target`, which it hands to
    `PythonRenderer` for `tensor_cores`."""

    def __init__(self, uops, target): self.lib, self.target = pickle.dumps(uops), target


class Fixture:
    __slots__ = ("name", "uops", "packet", "bufs", "gsize", "vals", "nbuf")

    def __init__(self, name, uops, bufs, gsize, vals):
        self.name, self.uops, self.bufs, self.gsize, self.vals = name, uops, bufs, gsize, vals
        self.packet = encode(uops)
        self.nbuf = int(self.packet.splitlines()[0].split()[2])

    def argv(self): return (*self.gsize, *self.vals)

    def seen(self):
        """THE BUFFERS BOTH LANES CAN SEE, and it is a real distinction.

        `exec_kernel` hands `PythonProgram.__call__` EVERY buffer of the linear
        (realize.py:170), while `BendProgram.__call__` hands it exactly the packet's
        `self.in_bufs` (ops_bend.py:214) -- MEASURED on `f32.neg.0`: the packet's
        header says `bendexec1 29 2` and the PYTHON launch arrives with 3 buffers. The
        executor can only see the 2 the packet declares, so comparing all 3 would be
        comparing a buffer the subject cannot read. The rows are over `seen()`.
        """
        return self.bufs[:self.nbuf]


