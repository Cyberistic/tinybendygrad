# AXIS 1: real launches, captured at the renderer/runtime boundary and PAIRED by
# `encode(uops) == the packet CPython was handed`. An unpaired launch is counted,
# not skipped silently.
# ---------------------------------------------------------------------------
class Trace(list):
    """`PythonProgram.__call__` reads its uops in exactly one way -- `u = self.uops[i]`
    at ops_python.py:63, plus `len(self.uops)` at :62 -- so overriding `__getitem__`
    observes CPython's OWN dynamic dispatch order without editing ops_python.py and
    without reimplementing a step of it. This is what makes the coverage census a
    measurement of the interpreter rather than of the fixture file."""

    def __init__(self, *a): super().__init__(*a); self.seen = []

    def __getitem__(self, i):
        # `list.__getitem__`, NOT `self[i]`: the latter re-enters this method and
        # recurses until the interpreter gives up. MEASURED: with `self[i]` the
        # first fixture died rc=137 after `harvest` had already run 128 clean
        # launches, which is a RecursionError's stack allocation and not a
        # divergence.
        u = super().__getitem__(i)
        self.seen.append(u.op)
        return u


def harvest():
    """A GENERATOR over the real launches, not a list.

    STREAMING IS A MEMORY MEASUREMENT, not a style choice. MEASURED 2026-10-14 on
    this machine: `vm_stat` reports `Pages free: 3978` of 16384 bytes, i.e. ~62 MB
    free, and a first draft that MATERIALISED the population died rc=137 (SIGKILL)
    partway through the ALU axis at `ru_maxrss` 2041 MB -- on `Ops.MULACC`, which
    runs in 66 MB on its own. Holding ~130 uop lists plus tinygrad's rewrite caches
    is what does it, so this yields and the caller drops.
    """
    renders, calls = [], []
    _render, _call = OPY.PythonRenderer.render, OPY.PythonProgram.__call__

    def render(self, uops): renders.append(list(uops)); return _render(self, uops)

    def call(self, *bufs, **kw):
        # THE BUFFERS ARE INTEGERS, NOT MEMORYVIEWS, AND THAT IS THE WHOLE BUG THIS
        # HOOK HAD. MEASURED: `PythonProgram.__call__` does `to_mv(pbufs.pop(0),
        # size)` (ops_python.py:104) and `to_mv` is `from_address` (helpers.py:574),
        # so `bufs` are ADDRESSES -- `bytes(addr)` is `bytes(4390684688)`, a 4.3 GB
        # zero-filled object, not the memory at that address. The first harvest draft
        # did exactly that and every symptom followed from it: `os.walk`-shaped disk
        # blowups, `OSError: [Errno 28] No space left on device` on an 8.5 GB pickle,
        # and rc=137 SIGKILLs that looked like a tinygrad rewrite-cache leak. The
        # byte counts come from the PACKET'S OWN buffer lines (`<nbytes> <hex>`, the
        # wire `encode` writes), so nothing here re-derives a size.
        pkt = encode(self.uops)
        # `encode` writes NO buffer lines -- its own docstring says "No buffers --
        # those are per-launch" (ops_bend.py:134) -- so a packet from `encode` alone
        # has `len(body) == nuops` and the extents are not in the text. They are in
        # the `<arg>` of the buffer PARAMs, `k:param:<nbytes>:<letter>`, and the tree
        # already owns both halves of that read: `ops_bend.is_buf` and
        # `ops_bend.buf_extent`. So the sizes are read with the tree's own reader and
        # the COUNT is checked against `encode`'s own header field.
        ext = [buf_extent(wire_arg(u)) for u in self.uops if is_buf(wire_arg(u))]
        if len(ext) != int(pkt.splitlines()[0].split()[2]):
            raise RuntimeError(f"{len(ext)} buffer params against a header that says {pkt.splitlines()[0]}")
        # THE INPUTS, read BEFORE the call. The harvest is what fills the fixture
        # file's buffer lines, and the packet the port reads is
        # `<uop lines><nbytes> <hex>` -- the launch's INPUT state, not what the
        # launch left behind.
        calls.append((pkt, ext, [bytes(to_mv(a, s)) for a, s in zip(bufs, ext)],
                      tuple(kw.get("global_size", (1, 1, 1))), tuple(kw.get("vals", ()))))
        return _call(self, *bufs, **kw)

    OPY.PythonRenderer.render, OPY.PythonProgram.__call__ = render, call
    try:
        with Context(DEV="PYTHON"):
            for dt in (dtypes.float, dtypes.int, dtypes.uint, dtypes.bool):
                x = Tensor(SEED_VALUES[dt], dtype=dt).realize()
                y = Tensor(SEED_VALUES[dt], dtype=dt).contiguous().realize()
                for nm, fn in SEEDS:
                    renders.clear(); calls.clear()
                    try:
                        fn(x, y).realize()
                    except Exception as e:                                    # noqa: BLE001
                        SEED_FAIL.append(f"{dt.name}/{nm}: {type(e).__name__}")
                        continue
                    for k, (uops, (seen, ext, bufs, g, v)) in enumerate(zip(renders, calls)):
                        # THE PAIRING CHECK, and it is not tautological: `renders[k]` is
                        # the list the RENDERER was handed and `calls[k][0]` is the
                        # packet the PROGRAM was built from, and they are equal only if
                        # the k-th render is the k-th launch of this seed.
                        if encode(uops) != seen: PAIR_BAD.append(f"{nm}.{k}")
                        yield Fixture(f"{dt.name}.{nm}.{k}", uops, bufs, g, v)
    finally:
        OPY.PythonRenderer.render, OPY.PythonProgram.__call__ = _render, _call


