r"""ops_python_exec-gen.py -- the FIXTURE GENERATOR and the CPython lane of the
`ops_python` EXECUTOR census.

    .venv/bin/python gates/ops_python_exec-gen.py             # the py lane: rows on stdout
    .venv/bin/python gates/ops_python_exec-gen.py --write     # rewrite the fixture file
    .venv/bin/python gates/ops_python_exec-gen.py --coverage  # the coverage census on stdout

WHAT THIS IS. `gates/ops_python_census-gate.py` covers the RENDERER/DEVICE half of
`tinygrad/runtime/ops_python.py` with 85 rows and finding D in its own header
records the gap: `PythonProgram.__call__` is :52-157, **106 of 186 lines**, and not
one of them has a row, because that half of the file is reached only through
`main()` with a PACKET on the command line. This file is the other half.

THE ARROW, WHICH IS THE WHOLE ANSWER TO FINDING D. Finding D's blocker was
"the CPython lane needs real `UOp`s from the v1 wire, and `ops_bend.parse` stops
where the uops begin". **Measured: the CPython lane does not need a wire -> `UOp`
decoder, because the census does not run that way.** The tree already owns the
OTHER direction: `ops_bend.encode(uops)` (:133) turns a list of real `UOp`s into
the v1 packet the port reads. So the fixtures are real `UOp` lists, the packets
are `encode`'s own output, and the port's `Prog.parse` consumes them. Nothing here
parses a packet into a `UOp`, which is the reimplementation the oracle exists to
prevent -- and MEASURED the port could not generate them anyway:
`grep -c "UOp.new" tinybendygrad/runtime/ops_python.bend` answers **0**, because
this layer builds no UOps, so "a fixture set generated by a def in the port" has no
def to be generated by. What the port DOES declare, and what this file is measured
against, is its own arm table: `op_of`'s 47 names and `Prog.dispatch`'s 21 named
arms, both read out of `ops_python.bend` by the GATE and diffed against what
CPython's own dispatch loop was observed to execute.

WHERE THE FIXTURES COME FROM, and why that is not a hand list.

  AXIS 1 -- REAL LAUNCHES. `PythonRenderer.render` and `PythonProgram.__call__` are
    wrapped for the duration of one `DEV=PYTHON` pass and the two hooks are PAIRED
    AND VERIFIED: a launch is only kept when `encode(uops) == self.uops`-derived
    packet text, byte for byte. So every fixture is a launch the tree actually
    performed, with the buffers and the `global_size`/`vals` it actually used, and
    `ops_bend.encode`'s own two asserts (`:139` every src is in the list, `:143`
    post-order) run on all of them. `PAIR_BAD` counts the failures and must be 0.
  AXIS 2 -- THE ALU SPINE. For every op in `tinygrad.uop.ops.python_alu` -- ops.py's
    OWN table, which is also `PythonRenderer.code_for_op` -- one fixture is built by
    replacing the single ALU node of a canonical harvested kernel with that op at
    the same arity, where the ARITY IS READ OFF the table's own callable by
    `inspect.signature` rather than typed here. This is what gives `FLOORDIV`,
    `FLOORMOD` and `POW` rows: tinygrad's scheduler lowers `//` to CDIV/CMOD and
    `**` to EXP2/LOG2/MUL, so no Tensor expression emits them, and MEASURED on the
    axis-1 population below they are three of the `op_of` names nothing reaches.

  The SEED EXPRESSIONS in `SEEDS` are the generator's INPUTS and are named here on
  purpose: they are the only typed list in this file, and they are not the
  population. The population is what the tree emits from them, and the gate reports
  its size and its op coverage on every run.

THE THIRD LANE IS NOT THERE, AND HERE IS WHY. `gatekit`-shaped censuses run the
port twice, `bend file.bend` (interpreted) and `bend file.bend -o exe` (native).
MEASURED 2026-10-14 on a 7-uop fixture: `bend tinybendygrad/runtime/ops_python.bend
PACKET 1 1 1` exits 1 in 6.76 s with `bend: memory fault (machine stack overflow?)`
and writes no PACKET.out, while the same packet through the compiled executor exits
0 in 1.79 s and writes both buffers. The executor's `run` is a fuel recursion
(ops_python.bend `FUEL() = 4000000n`) and the interpreter cannot hold it. So the
executor census is TWO lanes and says so; it does not fake a third.
"""
