class _PciShim:
    """THE SHIM'S ALLOCATOR, AND ITS FIRST ADDRESS IS **4096** SO THAT THE
    PORT'S ROWS CAN USE THE SAME FIXTURE.

    THE LIST PAGE'S ADDRESS IS A REAL INPUT TO THE PRP TABLE'S ENTRIES --
    `list_addrs[(p + 1) // 256] + (p + 1) % 256 * 8` -- SO A ROW THAT
    COMPARES THE ENTRIES MUST PIN THAT ADDRESS, OR THE TWO SIDES WOULD BE
    COMPARING DIFFERENT FIXTURES. **4096** IS THE PAGE AFTER NOTHING AND IS
    THE PORT'S FIXTURE."""

    def __init__(self):
        self.next = 4096

    def alloc_sysmem(self, size):
        base = self.next
        self.next += round_up(size, 0x1000)
        return bytearray(size), [base]


class _DevShim:
    def __init__(self):
        self.pci_dev = _PciShim()


def _prp(pages):
    """UPSTREAM'S OWN `prp_table`, AGAINST THE SHIM.

    **THE PAGES ARE THE FIXTURE AND THE FIXTURE IS PART OF THE CLAIM**: THE
    TABLE'S ENTRIES ARE THE **PHYSICAL PAGE NUMBERS** INTERLEAVED WITH THE
    POINTERS, SO A DIFFERENT PAGE LIST GIVES A DIFFERENT TABLE. THE PORT'S
    ROWS USE `[100, 200]` AND `[100, 200, 300]` AND THIS CALLS
    `prp_table` WITH **THE SAME LISTS**."""
    dev = _DevShim()
    table, table_addrs = prp_table(dev, list(pages))
    entries = struct.unpack_from(f"<{2*len(pages)}Q", bytes(table[:8 * 2 * len(pages)]))
    return table, table_addrs, entries, dev


