class _CqView:
    """`self.cq.view(slot*CQE+12, 4, fmt='I')[0]` -- upstream reads the
    COMPLETION'S PHASE-FIELD WORD. THE SHIM ANSWERS WITH A WORD WHOSE PHASE
    BIT MATCHES, SO THE `wait_cond` SUCCEEDS AND UPSTREAM'S OWN PHASE LINE
    RUNS."""
    def __init__(self, cq, phase):
        self.cq, self.phase = cq, phase

    def view(self, off, n, fmt=None):
        return [_CqWord(self.cq, self.phase, off)]


class _CqWord:
    def __init__(self, cq, phase, off):
        self.v = (phase << 16) if off % CQE == 12 else 0

    def __getitem__(self, i):
        return self.v


class _Queue:
    """UPSTREAM'S `NVMEQueue` FIELDS, WITH THE DEVICE-SIDE CALLS REPLACED."""

    def __init__(self, qid, entries=0x1000 // SQE, db_stride=4):
        self.dev, self.qid, self.tail, self.phase, self.entries = None, qid, 0, 1, entries
        self.sq, self.cq = bytearray(0x1000), bytearray(0x1000)
        self.sq_addr, self.cq_addr = 0x10000, 0x20000
        self.db_stride = db_stride
        self.sq_db, self.cq_db = _sq_db(qid, db_stride), _cq_db(qid, db_stride)
        self.regs = [0] * 4096
        self.pci_dev = None
        self.submitted = []

    # UPSTREAM'S OWN `submit`, VERBATIM EXCEPT FOR THE TWO DEVICE CALLS.
    def submit(self, opcode, nsid=0, prp1=0, cdw10=0, cdw11=0):
        slot, self.tail = self.tail, (self.tail + 1) % self.entries
        self.sq[slot * SQE:(slot + 1) * SQE] = struct.pack("<IIQQQQII16x",
                                                           opcode | slot << 16, nsid, 0, 0, prp1, 0, cdw10, cdw11)
        self.regs[self.sq_db // 4] = self.tail
        self.submitted.append((slot, opcode, nsid, prp1, cdw10, cdw11))
        self.phase ^= int(self.tail == 0)
        self.regs[self.cq_db // 4] = self.tail


