#!/usr/bin/env python3
"""ggml_common-gen.py -- writes `tinybendygrad/runtime/autogen/ggml_common.bend`'s GRIDS.

    .venv/bin/python tinybendygrad/runtime/autogen/ggml_common-gen.py

THE DATA IS READ OUT OF CPYTHON, NEVER RETYPED. This imports
`tinygrad.runtime.autogen.ggml_common` -- the same module `gguf.py:51` imports -- and emits
each grid's entries as the 32-BIT WORDS `gguf.py:13` splits them into (`(v >> shift) &
0xffffffff` for shift in 0 and 32, which is why a `U32` cannot hold one entry).

WHY THE OUTPUT IS FIVE FILES AND NOT ONE, MEASURED: a single list literal past ~24 KB of
source makes `bin/bend` answer `the machine stack overflowed (a deep recursion, or a
literal too large to expand)`, and a 2,500-word literal is already 26,997 bytes. MEASURED
on this tree: 1,800 and 2,200 words RUN, 2,500 and 3,000 do not. So each part holds at most
2,000 words, and the facade `ggml_common.bend` concatenates them.

THE GRIDS ARE WHOLE, per part, wherever it fits: a grid split across two parts is a grid a
reader has to reassemble by hand. `iq1s_grid` is the only one that does not fit (4,096
words) and it is split at 1,800, whose boundary is an ENTRY boundary because that grid is
two words per entry.
"""
import hashlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

# (def name, ggml_common attribute, bytes per entry) -- the six the ladders index.
GRIDS = (
  ("iq3xxs_grid", "iq3xxs_grid", 4),
  ("iq2xxs_grid", "iq2xxs_grid", 8),
  ("iq2xs_grid", "iq2xs_grid", 8),
  ("iq3s_grid", "iq3s_grid", 4),
  ("iq2s_grid", "iq2s_grid", 8),
  ("iq1s_grid", "iq1s_grid", 8),
)

CAP = 2000        # words per part; see the MEASURED note in the docstring


def words(grid, nbytes):
    """`gguf.py:13`'s split: for each entry, its 32-bit words, low first."""
    out = []
    for v in grid:
        for k in range(nbytes // 4):
            out.append((v >> (32 * k)) & 0xFFFFFFFF)
    return out


def chunks(name, ws):
    """Entries stay whole inside a part; a grid is split only where it must be."""
    per = ws_per_entry[name]
    size = max(per * (CAP // per), per)
    return [ws[i:i + size] for i in range(0, len(ws), size)]


ws_per_entry = {n: nb // 4 for n, _, nb in GRIDS}


def main():
    from tinygrad.runtime.autogen import ggml_common as GC

    parts, plan = [], []
    for name, attr, nb in GRIDS:
        ws = words(getattr(GC, attr), nb)
        cs = chunks(name, ws)
        plan.append((name, len(getattr(GC, attr)), nb // 4, len(cs)))
        parts.extend(cs)

    files = []
    for i, ws in enumerate(parts, 1):
        body = ",".join(str(w) for w in ws)
        files.append((f"ggml_common_p{i}.bend",
                      "# GENERATED by `tinybendygrad/runtime/autogen/ggml_common-gen.py`.\n"
                      "# Do not edit: regenerate, then move the pin in `gates/llm_ggml-gate.py`.\n"
                      "import Base\n\n"
                      f"def w() -> List<&2, U32>:\n  [{body}]\n"))

    facade = ["# GENERATED by `tinybendygrad/runtime/autogen/ggml_common-gen.py`, except the\n"
              "# facade below, which is written by hand. Do not edit the parts.\n"
              "#\n"
              "# THE GRID FAMILY of `tinygrad/runtime/autogen/ggml_common.py`: the six grids the\n"
              "# `IQ*` quant ladders index, as the 32-bit words `gguf.py:13` splits each entry\n"
              "# into, plus the sixteen `kvalues_iq4nl`. A grid is `(entries, words)` -- an\n"
              "# EIGHT-byte grid takes two words per entry and a FOUR-byte grid one.\n"
              "import Base\n"]
    for i in range(1, len(parts) + 1):
        facade.append(f"import ./ggml_common_p{i}.bend as P{i}\n")

    lo = 1
    for name, entries, wpe, nparts in plan:
        facade.append(f"\ndef {name}() -> List<&2, U32>:\n  ")
        chain = "P%d.w()" % lo
        for j in range(lo + 1, lo + nparts):
            chain = f"List.append(&2, U32, {chain}, P{j}.w())"
        facade.append(chain + "\n")
        lo += nparts
    facade.append(
      "\n# `kvalues_iq4nl` -- ggml-common.h's sixteen int8s, as 32-bit two's complement.\n"
      "def kvalues_iq4nl() -> List<&2, U32>:\n"
      "  [4294967169, 4294967192, 4294967213, 4294967231, 4294967247, 4294967261,\n"
      "   4294967274, 4294967286, 1, 13, 25, 38, 53, 69, 89, 113]\n")

    if "--sha" in sys.argv:
        for p, src in files + [("ggml_common.bend", "".join(facade))]:
            print(f"{p} {len(src)} {hashlib.sha256(src.encode()).hexdigest()}")
        return 0
    for p, src in files + [("ggml_common.bend", "".join(facade))]:
        (HERE / p).write_text(src)
        print(f"{p}: {len(src)} bytes, sha256 {hashlib.sha256(src.encode()).hexdigest()}")
    print("grids:", ", ".join(f"{n}={e}x{w}" for n, e, w, _ in plan))
    return 0


if __name__ == "__main__":
    sys.exit(main())
